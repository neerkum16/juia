def _define_cluster(
    spark: SparkSession,
    config: KsdsClusterConfig,
    partial_result: ClusterInitResult,
) -> ClusterInitResult:
    """
    Create the Delta Lake managed table that corresponds to a VSAM KSDS cluster.

    Implements the equivalent of:

        DEFINE CLUSTER
          (NAME(<DSN>)
           INDEXED
           KEYS(16 0)
           RECORDSIZE(200 200)
           CYLINDERS(<pri> <sec>)
           SHAREOPTIONS(2 3))
        DATA  (NAME(<DSN>.DATA))
        INDEX (NAME(<DSN>.INDEX))

    Key mapping:
      - INDEXED          → Delta Lake is inherently key-addressable; the key
                           column (``wire_key``) is declared NOT NULL and used
                           as the merge / upsert predicate in downstream steps.
      - KEYS(16 0)       → ``wire_key`` STRING NOT NULL, length 16, offset 0.
      - RECORDSIZE(200 200) → Fixed-width schema; see :func:`_build_ksds_schema`.
      - CYLINDERS        → No direct equivalent; recorded as table properties
                           for capacity-planning reference.
      - SHAREOPTIONS(2 3)→ Delta Lake ACID transactions provide equivalent
                           concurrent-access semantics.
      - DATA / INDEX components → Managed internally by Delta Lake; component
                           names are stored as table properties for traceability.

    Parameters
    ----------
    spark:
        Active SparkSession with the Delta Lake extension enabled.
    config:
        Cluster configuration for the table to create.
    partial_result:
        The :class:`ClusterInitResult` returned by :func:`_delete_cluster`,
        which this function enriches with define_status / define_message.

    Returns
    -------
    ClusterInitResult
        Fully populated result for the cluster.
    """
    qualified: str = config.qualified_table_name
    logger.info(
        "DEFINE equivalent: creating table '%s' (mainframe DSN: %s) …",
        qualified,
        config.mainframe_dsn,
    )

    schema: StructType = _build_ksds_schema(config)
    define_status: OperationStatus
    define_message: str

    try:
        # Ensure the target database / schema exists before creating the table.
        spark.sql(f"CREATE DATABASE IF NOT EXISTS {config.database}")  # noqa: S608

        # Build the TBLPROPERTIES clause from the config dictionary.
        tbl_props_str: str = ", ".join(
            f"'{k}' = '{v}'" for k, v in config.tbl_properties.items()
        )
        tbl_props_clause: str = (
            f"TBLPROPERTIES ({tbl_props_str})" if tbl_props_str else ""
        )

        # Derive the DDL column list from the StructType schema so that the
        # table definition stays in sync with _build_ksds_schema() at all times.
        col_ddl_parts = []
        for struct_field in schema.fields:
            nullable_clause = "" if struct_field.nullable else " NOT NULL"
            # Map PySpark types to SQL DDL keywords
            if isinstance(struct_field.dataType, StringType):
                sql_type = "STRING"
            elif isinstance(struct_field.dataType, IntegerType):
                sql_type = "INT"
            else:
                sql_type = str(struct_field.dataType)
            col_ddl_parts.append(
                f"  {struct_field.name} {sql_type}{nullable_clause}"
            )
        columns_ddl: str = ",\n".join(col_ddl_parts)

        # Mainframe: DEFINE CLUSTER (NAME(WIRE.WORK.INPUT.KSDS) INDEXED …)
        # The KSDS primary key column is used as the Delta Lake partition /
        # cluster key; for very large tables consider Z-ORDER on wire_key in
        # downstream OPTIMIZE commands rather than explicit partitioning.
        create_ddl: str = (
            f"CREATE TABLE IF NOT EXISTS {qualified} (\n"
            f"{columns_ddl}\n"
            f") USING DELTA\n"
            f"{tbl_props_clause}"
        )

        logger.debug("Executing DDL:\n%s", create_ddl)
        spark.sql(create_ddl)  # noqa: S608

        # Add a table comment via ALTER to keep the CREATE statement clean.
        comment: str = (
            f"Wire transfer KSDS work file migrated from mainframe DSN "
            f"{config.mainframe_dsn}. "
            f"Key: {WIRE_KEY} (length={config.key_length}, offset={config.key_offset}). "
            f"Record size: {config.record_size} bytes (fixed). "
            f"DATA component: {config.data_component}. "
            f"INDEX component: {config.index_component}. "
            f"SHAREOPTIONS({config.share_option_1} {config.share_option_2}). "
            f"Mainframe allocation: CYLINDERS({config.cylinders_primary} "
            f"{config.cylinders_secondary})."
        )
        spark.sql(  # noqa: S608
            f"ALTER TABLE {qualified} SET TBLPROPERTIES "
            f"('comment' = '{comment}')"
        )

        define_status = OperationStatus.SUCCESS
        define_message = (
            f"Table '{qualified}' created successfully as Delta Lake managed table."
        )
        logger.info(define_message)

    except Exception as exc:  # pylint: disable=broad-except
        define_status = OperationStatus.WARN_ERROR_SUPPRESSED
        define_message = f"DEFINE of '{qualified}' failed: {exc}"
        logger.error(define_message)
        raise  # DEFINE failures are fatal — do not suppress

    return ClusterInitResult(
        config=partial_result.config,
        delete_status=partial_result.delete_status,
        delete_message=partial_result.delete_message,
        define_status=define_status,
        define_message=define_message,
    )


