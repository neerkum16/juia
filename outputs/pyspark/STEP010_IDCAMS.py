def _build_ksds_schema(config: KsdsClusterConfig) -> StructType:
    """
    Build the PySpark StructType that represents the 200-byte KSDS record.

    The key occupies bytes 1-16 (1-based) of the fixed 200-byte record.
    The remaining 184 bytes are carried as a raw payload column pending
    full copybook decomposition in downstream migration phases.

    Parameters
    ----------
    config:
        Cluster configuration supplying key length and total record size.

    Returns
    -------
    StructType
        Schema with two fields: the 16-byte key and the 184-byte payload.
    """
    payload_length: int = config.record_size - config.key_length  # 200 - 16 = 184

    return StructType([
        # Mainframe: KEYS(16 0) — 16-byte character key at offset 0 (0-based)
        # Equivalent to VSAM primary key; NOT NULL enforced by KSDS semantics
        StructField(
            WIRE_KEY,
            StringType(),
            nullable=False,
            metadata={
                "mainframe.offset.zero_based": str(config.key_offset),
                "mainframe.length": str(config.key_length),
                "mainframe.format": "CH",
                "mainframe.ksds.role": "PRIMARY_KEY",
                "description": (
                    "Wire transfer identifier / reference number. "
                    "Occupies bytes 1-16 of the 200-byte fixed-length record."
                ),
            },
        ),
        # Remaining bytes 17-200 (1-based): decompose once copybook is available.
        # EBCDIC → UTF-8 transcoding must be applied before this column is
        # populated if the source data originates from a mainframe extract.
        StructField(
            RECORD_PAYLOAD,
            StringType(),
            nullable=True,
            metadata={
                "mainframe.offset.zero_based": str(config.key_length),
                "mainframe.length": str(payload_length),
                "mainframe.format": "CH",
                "description": (
                    f"Raw payload — bytes {config.key_length + 1} to "
                    f"{config.record_size} (1-based) of the 200-byte record. "
                    "Decompose into typed fields once the COBOL copybook is resolved."
                ),
            },
        ),
        # Technical sequence column — absent on mainframe; added for auditability.
        StructField(
            RECORD_SEQUENCE,
            IntegerType(),
            nullable=True,
            metadata={"description": "Migration-added monotonic sequence number."},
        ),
    ])


