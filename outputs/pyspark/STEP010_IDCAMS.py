def initialise_wire_ksds_work_files(
    spark: SparkSession,
    input_config: Optional[KsdsClusterConfig] = None,
    extrt_config: Optional[KsdsClusterConfig] = None,
) -> StepInitResult:
    """
    Initialise the two VSAM KSDS work files used in the wire transfer
    processing pipeline by dropping any pre-existing Delta Lake tables and
    re-creating them with the correct schema and properties.

    This function is the direct PySpark equivalent of the IDCAMS STEP010
    control stream:

    .. code-block:: text

        DELETE WIRE.WORK.INPUT.KSDS  CLUSTER PURGE
        DELETE WIRE.WORK.EXTRT.KSDS  CLUSTER PURGE
        IF LASTCC > 8 THEN
          SET MAXCC = 0
        DEFINE CLUSTER                           -
          (NAME(WIRE.WORK.INPUT.KSDS)            -
           INDEXED                               -
           KEYS(16 0)                            -
           RECORDSIZE(200 200)                   -
           CYLINDERS(20 5)                       -
           SHAREOPTIONS(2 3))                    -
        DATA                                     -
          (NAME(WIRE.WORK.INPUT.KSDS.DATA))      -
        INDEX                                    -
          (NAME(WIRE.WORK.INPUT.KSDS.INDEX))
        DEFINE CLUSTER                           -
          (NAME(WIRE.WORK.EXTRT.KSDS)            -
           INDEXED                               -
           KEYS(16 0)                            -
           RECORDSIZE(200 200)                   -
           CYLINDERS(10 5)                       -
           SHAREOPTIONS(2 3))                    -
        DATA                                     -
          (NAME(WIRE.WORK.EXTRT.KSDS.DATA))      -
        INDEX                                    -
          (NAME(WIRE.WORK.EXTRT.KSDS.INDEX))

    Business Rule
    -------------
    Both clusters are temporary work datasets scoped to a single job
    execution.  They must be initialised (empty) at the start of every run
    to ensure idempotency.  The INPUT cluster holds the full wire transfer
    input (up to ~20 cylinders worth of 200-byte records); the EXTRT cluster
    holds an extracted / filtered subset (~10 cylinders).

    Condition-Code Equivalence
    --------------------------
    +------+------------------+--------------------------------------+
    | IDCAMS CC | Scenario        | PySpark equivalent               |
    +------+------------------+--------------------------------------+
    | 0         | Table dropped   | OperationStatus.SUCCESS          |
    | 8         | Table not found | OperationStatus.SKIPPED_NOT_FOUND|
    | > 8       | Unexpected err  | OperationStatus.WARN_ERROR_SUPPRESSED |
    +------+------------------+--------------------------------------+

    When a DELETE raises an unexpected exception (CC>8 equivalent), the error
    is logged but not re-raised, mirroring "IF LASTCC > 8 THEN SET MAXCC = 0"
    which resets MAXCC and allows the DEFINE commands to proceed.

    Key Field Mapping
    -----------------
    +------------------+--------+--------+--------+-------------------+
    | Mainframe field  | Offset | Length | Format | Python column     |
    +------------------+--------+--------+--------+-------------------+
    | Primary key      | 0 (0b) | 16     | CH     | wire_key          |
    | Record payload   | 16(0b) | 184    | CH     | record_payload    |
    +------------------+--------+--------+--------+-------------------+
    Offsets are zero-based (matching IDCAMS KEYS(16 0)).
    1-based mainframe equivalents: key = bytes 1-16; payload = bytes 17-200.

    Note on EBCDIC transcoding
    --------------------------
    If the source data originates from a mainframe extract, all CH (character)
    fields — including ``wire_key`` and ``record_payload`` — must be transcoded
    from EBCDIC to UTF-8 **before** the tables are populated.  This step only
    defines the table structures; transcoding is handled by the ingest layer.

    Parameters
    ----------
    spark:
        Active SparkSession with the Delta Lake extension enabled and
        configured (``spark.sql.extensions`` must include
        ``io.delta.sql.DeltaSparkSessionExtension``).
    input_config:
        Configuration for the INPUT cluster.  Defaults to
        :data:`INPUT_CLUSTER_CONFIG` if not supplied.
    extrt_config:
        Configuration for the EXTRT cluster.  Defaults to
        :data:`EXTRT_CLUSTER_CONFIG` if not supplied.

    Returns
    -------
    StepInitResult
        Aggregate result containing :class:`ClusterInitResult` entries for
        both clusters.  Inspect ``result.all_successful`` to confirm that
        both DEFINEs completed without error.

    Raises
    ------
    RuntimeError
        Re-raised from ``_define_cluster`` if either DEFINE fails — a DEFINE
        failure is considered fatal (unlike a DELETE failure which is masked).
    """
    resolved_input_cfg: KsdsClusterConfig = input_config or INPUT_CLUSTER_CONFIG
    resolved_extrt_cfg: KsdsClusterConfig = extrt_config or EXTRT_CLUSTER_CONFIG

    logger.info(
        "STEP010 — Initialising KSDS work files: %s, %s",
        resolved_input_cfg.qualified_table_name,
        resolved_extrt_cfg.qualified_table_name,
    )

    # ------------------------------------------------------------------
    # Phase 1 — DELETE (DROP TABLE IF EXISTS)
    # Mainframe: DELETE WIRE.WORK.INPUT.KSDS CLUSTER PURGE
    # Mainframe: DELETE WIRE.WORK.EXTRT.KSDS CLUSTER PURGE
    # Errors from DELETE are suppressed (MAXCC reset) — see docstring.
    # ------------------------------------------------------------------

    # Mainframe: DELETE WIRE.WORK.INPUT.KSDS CLUSTER PURGE
    logger.info("Phase 1a — DELETE WIRE.WORK.INPUT.KSDS CLUSTER PURGE")
    input_partial: ClusterInitResult = _delete_cluster(spark, resolved_input_cfg)

    # Mainframe: DELETE WIRE.WORK.EXTRT.KSDS CLUSTER PURGE
    logger.info("Phase 1b — DELETE WIRE.WORK.EXTRT.KSDS CLUSTER PURGE")
    extrt_partial: ClusterInitResult = _delete_cluster(spark, resolved_extrt_cfg)

    # ------------------------------------------------------------------
    # Phase 2 — Condition-code guard equivalent
    # Mainframe: IF LASTCC > 8 THEN SET MAXCC = 0
    #
    # Both _delete_cluster() calls already implement this by catching all
    # exceptions and assigning WARN_ERROR_SUPPRESSED instead of re-raising.
    # We log a summary here for observability, matching what IDCAMS would
    # print to SYSPRINT after evaluating the IF/THEN statement.
    # ------------------------------------------------------------------
    for label, partial in (("INPUT", input_partial), ("EXTRT", extrt_partial)):
        if partial.delete_status == OperationStatus.WARN_ERROR_SUPPRESSED:
            logger.warning(
                "IF LASTCC > 8 THEN SET MAXCC = 0 — %s DELETE returned an "
                "error (CC>8 equivalent); MAXCC reset to 0. "
                "Proceeding with DEFINE. Original message: %s",
                label,
                partial.delete_message,
            )

    # ------------------------------------------------------------------
    # Phase 3 — DEFINE CLUSTER (CREATE TABLE … USING DELTA)
    # ------------------------------------------------------------------

    # Mainframe: DEFINE CLUSTER (NAME(WIRE.WORK.INPUT.KSDS) INDEXED KEYS(16 0)
    #            RECORDSIZE(200 200) CYLINDERS(20 5) SHAREOPTIONS(2 3))
    #            DATA (NAME(WIRE.WORK.INPUT.KSDS.DATA))
    #            INDEX (NAME(WIRE.WORK.INPUT.KSDS.INDEX))
    logger.info("Phase 3a — DEFINE CLUSTER WIRE.WORK.INPUT.KSDS")
    input_result: ClusterInitResult = _define_cluster(
        spark, resolved_input_cfg, input_partial
    )

    # Mainframe: DEFINE CLUSTER (NAME(WIRE.WORK.EXTRT.KSDS) INDEXED KEYS(16 0)
    #            RECORDSIZE(200 200) CYLINDERS(10 5) SHAREOPTIONS(2 3))
    #            DATA (NAME(WIRE.WORK.EXTRT.KSDS.DATA))
    #            INDEX (NAME(WIRE.WORK.EXTRT.KSDS.INDEX))
    logger.info("Phase 3b — DEFINE CLUSTER WIRE.WORK.EXTRT.KSDS")
    extrt_result: ClusterInitResult = _define_cluster(
        spark, resolved_extrt_cfg, extrt_partial
    )

    step_result = StepInitResult(
        input_cluster=input_result,
        extrt_cluster=extrt_result,
    )

    if step_result.all_successful:
        logger.info(
            "STEP010 completed successfully. "
            "Tables '%s' and '%s' are ready for downstream population.",
            resolved_input_cfg.qualified_table_name,
            resolved_extrt_cfg.qualified_table_name,
        )
    else:
        logger.error(
            "STEP010 completed with one or more failures. "
            "INPUT define_status=%s, EXTRT define_status=%s.",
            input_result.define_status,
            extrt_result.define_status,
        )

    return step_result


# ---------------------------------------------------------------------------
# Verification helper — equivalent to IDCAMS LISTCAT
# ---------------------------------------------------------------------------

def verify_wire_ksds_tables(
    spark: SparkSession,
    input_config: Optional[KsdsClusterConfig] = None,
    extrt_config: Optional[KsdsClusterConfig] = None,
) -> Dict[str, bool]:
    """
    Verify that both KSDS work tables exist and are valid Delta Lake tables.

    Equivalent to running ``IDCAMS LISTCAT CLUSTER(WIRE.WORK.INPUT.KSDS)``
    and ``IDCAMS LISTCAT CLUSTER(WIRE.WORK.EXTRT.KSDS)`` to confirm that
    the clusters were successfully defined.

    Parameters
    ----------
    spark:
        Active SparkSession.
    input_config:
        Configuration for the INPUT cluster.  Defaults to
        :data:`INPUT_CLUSTER_CONFIG`.
    extrt_config:
        Configuration for the EXTRT cluster.  Defaults to
        :data:`EXTRT_CLUSTER_CONFIG`.

    Returns
    -------
    dict
        Mapping of qualified table name → bool indicating Delta table existence.
        Example: ``{"wire_work.wire_work_input_ksds": True, …}``.
    """
    resolved_input = input_config or INPUT_CLUSTER_CONFIG
    resolved_extrt = extrt_config or EXTRT_CLUSTER_CONFIG

    results: Dict[str, bool] = {}
    for cfg in (resolved_input, resolved_extrt):
        exists: bool = DeltaTable.isDeltaTable(spark, cfg.qualified_table_name)
        results[cfg.qualified_table_name] = exists
        status_str = "EXISTS" if exists else "NOT FOUND"
        logger.info(
            "LISTCAT equivalent: %s → %s (mainframe DSN: %s)",
            cfg.qualified_table_name,
            status_str,
            cfg.mainframe_dsn,
        )

    return results


