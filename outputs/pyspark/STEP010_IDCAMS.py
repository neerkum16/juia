def _delete_cluster(
    spark: SparkSession,
    config: KsdsClusterConfig,
) -> ClusterInitResult:
    """
    Drop a Delta Lake table that corresponds to a VSAM KSDS cluster.

    Implements the equivalent of:

        DELETE <DSN> CLUSTER PURGE

    with the IDCAMS condition-code semantics:
      - CC = 0  → table existed and was dropped successfully.
      - CC = 8  → table did not exist (non-fatal; first-run scenario).
      - CC > 8  → unexpected error; surfaced as a warning but not re-raised,
                  mirroring "IF LASTCC > 8 THEN SET MAXCC = 0" behaviour.

    The caller is responsible for assembling the :class:`ClusterInitResult`.
    This function returns a partially populated result (delete fields only).

    Parameters
    ----------
    spark:
        Active SparkSession with the Delta Lake extension enabled.
    config:
        Cluster configuration for the table to drop.

    Returns
    -------
    ClusterInitResult
        Populated with delete_status and delete_message; define fields are
        left at their defaults and filled in by :func:`_define_cluster`.
    """
    qualified = config.qualified_table_name
    logger.info(
        "DELETE equivalent: dropping table '%s' (mainframe DSN: %s) …",
        qualified,
        config.mainframe_dsn,
    )

    delete_status: OperationStatus
    delete_message: str

    try:
        # Mainframe: DELETE WIRE.WORK.INPUT.KSDS CLUSTER PURGE
        # DROP TABLE IF EXISTS — tolerates a missing table (CC=8 equivalent).
        table_existed: bool = DeltaTable.isDeltaTable(spark, qualified)

        if table_existed:
            spark.sql(f"DROP TABLE IF EXISTS {qualified}")  # noqa: S608 — table name is a constant
            delete_status = OperationStatus.SUCCESS
            delete_message = f"Table '{qualified}' dropped successfully (CC=0 equivalent)."
            logger.info(delete_message)
        else:
            # Table does not exist — IDCAMS CC=8, tolerated (PURGE / first run)
            delete_status = OperationStatus.SKIPPED_NOT_FOUND
            delete_message = (
                f"Table '{qualified}' does not exist — treated as CC=8 "
                "(dataset not found, non-fatal on first run)."
            )
            logger.warning(delete_message)

    except Exception as exc:  # pylint: disable=broad-except
        # Mainframe: LASTCC > 8 — genuine error beyond "not found".
        # Equivalent to "IF LASTCC > 8 THEN SET MAXCC = 0": we log the error
        # but do NOT re-raise, allowing the subsequent DEFINE to proceed.
        delete_status = OperationStatus.WARN_ERROR_SUPPRESSED
        delete_message = (
            f"DELETE of '{qualified}' raised an unexpected error "
            f"(CC>8 equivalent; MAXCC reset to 0 — proceeding with DEFINE): {exc}"
        )
        logger.error(delete_message)

    return ClusterInitResult(
        config=config,
        delete_status=delete_status,
        delete_message=delete_message,
        # define fields populated by _define_cluster
        define_status=OperationStatus.SKIPPED_NOT_FOUND,
        define_message="",
    )


