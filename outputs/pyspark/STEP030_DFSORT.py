def extract_pe_wire_transactions(input_df: DataFrame) -> DataFrame:
    """
    Extract, filter, and sort active PE-type wire transfer records.

    Business Rule
    -------------
    Reads the daily wire input dataset and retains only those records where:
      1. The payment type code (2-character field) equals 'PE', AND
      2. The transaction amount (packed decimal field) is strictly greater
         than zero (i.e. non-zero, non-null transactions).

    The qualifying records are then sorted by:
      * Primary   : reference_key   ASCENDING  (A)  — groups related wires
      * Secondary : transaction_amount DESCENDING (D) — largest amount first

    This function is a direct PySpark equivalent of the DFSORT step STEP030
    originally defined by:

        INCLUDE COND=(55,2,CH,EQ,C'PE',AND,17,9,PD,GT,+0)
        SORT FIELDS=(44,8,CH,A,17,9,PD,D)

    The output represents a staged extract of active PE-type wire transactions
    ranked by reference key and amount, feeding downstream payment processing
    or reconciliation workflows.

    Parameters
    ----------
    input_df : DataFrame
        The daily wire input dataset — equivalent to DD SORTIN
        (DSN=WIRE.DAILY.INPUT.SEQ, RECFM=FB, LRECL=200).

        Expected schema (key columns — additional columns are passed through):

        +----------------------+-------------+----------------------------------------------+
        | Column               | Spark Type  | Mainframe Field                              |
        +----------------------+-------------+----------------------------------------------+
        | transaction_amount   | DecimalType | Offset 17, Len 9, PD (pre-decoded, non-null) |
        | reference_key        | StringType  | Offset 44, Len 8, CH (UTF-8 transcoded)      |
        | payment_type         | StringType  | Offset 55, Len 2, CH (UTF-8 transcoded)      |
        +----------------------+-------------+----------------------------------------------+

        IMPORTANT PRE-CONDITIONS:
          - The `transaction_amount` column MUST be pre-decoded from packed
            decimal (COMP-3) format into a numeric Spark type (DecimalType or
            LongType) by the ingestion layer before this function is called.
            Raw PD bytes will cause incorrect comparisons.
          - The `payment_type` and `reference_key` columns MUST be transcoded
            from EBCDIC to UTF-8/ASCII before this function is called.  The
            literal comparison 'PE' assumes ASCII/UTF-8 representation.

    Returns
    -------
    DataFrame
        Filtered and sorted DataFrame equivalent to DD SORTOUT
        (DSN=WIRE.WORK.EXTRT.SEQ, RECFM=FB, LRECL=200).
        All original columns are preserved; no record reformatting is applied.
        Row count will be ≤ input row count.

    Key Field Mapping
    -----------------
    Mainframe Offset | Length | Format | Column Name         | Role
    -----------------|--------|--------|---------------------|----------------------
    17               | 9      | PD     | transaction_amount  | Filter + Sort key 2
    44               | 8      | CH     | reference_key       | Sort key 1 (primary)
    55               | 2      | CH     | payment_type        | Filter key

    Original SYSIN (SYS2.CNTL(WIREEXT))
    ------------------------------------
        INCLUDE COND=(55,2,CH,EQ,C'PE',AND,17,9,PD,GT,+0)
        SORT FIELDS=(44,8,CH,A,17,9,PD,D)
    """

    # -------------------------------------------------------------------------
    # STEP 1 — FILTER
    # Mainframe: INCLUDE COND=(55,2,CH,EQ,C'PE',AND,17,9,PD,GT,+0)
    #
    # Predicate 1 : payment_type == 'PE'
    #   → Offset 55, len 2, CH — retains only PE-category wire transactions.
    #   → EBCDIC C'PE' is assumed transcoded to UTF-8 'PE' at ingestion time.
    #
    # Predicate 2 : transaction_amount > 0
    #   → Offset 17, len 9, PD — excludes zero-value and null transactions.
    #   → The PD field must be pre-decoded to a numeric type (DecimalType /
    #     LongType) before this filter is applied.  Raw bytes would produce
    #     meaningless numeric comparisons.
    #
    # Both predicates are joined with logical AND — a record must satisfy
    # BOTH conditions to be included in the output.
    # -------------------------------------------------------------------------
    payment_type_filter = F.col(PAYMENT_TYPE) == PAYMENT_TYPE_PE
    amount_filter = F.col(TRANSACTION_AMOUNT) > AMOUNT_ZERO

    # Mainframe: INCLUDE COND=(55,2,CH,EQ,C'PE',AND,17,9,PD,GT,+0)
    df_filtered: DataFrame = input_df.filter(payment_type_filter & amount_filter)

    # -------------------------------------------------------------------------
    # STEP 2 — SORT
    # Mainframe: SORT FIELDS=(44,8,CH,A,17,9,PD,D)
    #
    # Sort key 1 (Primary)   : reference_key       ASCENDING
    #   → Offset 44, len 8, CH — groups related wire transfers together.
    #
    # Sort key 2 (Secondary) : transaction_amount   DESCENDING
    #   → Offset 17, len 9, PD — within each reference_key group, the record
    #     with the largest transaction amount appears first (largest-first
    #     ranking within the group).
    #   → The PD field must be pre-decoded to a numeric type so that numeric
    #     ordering (not lexicographic byte ordering) is applied.
    # -------------------------------------------------------------------------

    # Mainframe: SORT FIELDS=(44,8,CH,A,17,9,PD,D)
    df_sorted: DataFrame = df_filtered.orderBy(
        F.col(REFERENCE_KEY).asc(),           # Primary   : offset 44, CH, A
        F.col(TRANSACTION_AMOUNT).desc(),     # Secondary : offset 17, PD, D
    )

    return df_sorted


