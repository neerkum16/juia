def load_wire_daily_input_to_staging(
    input_df: DataFrame,
    config: Optional[StepConfig] = None,
    source_path: str = "",
) -> RepроResult:
    """
    Stage daily wire transfer records from a sequential flat file into a
    keyed, indexed VSAM KSDS equivalent (Delta Lake / Parquet table).

    This function is the PySpark equivalent of the following IDCAMS REPRO:

        REPRO INFILE(SEQIN)      -
              OUTFILE(VSAMOUT)

    Business Rule
    -------------
    All records from the sequential input dataset WIRE.DAILY.INPUT.SEQ are
    copied verbatim into the VSAM KSDS work dataset WIRE.WORK.INPUT.KSDS.
    No filtering, transformation, or selection criteria are applied.
    Records are inserted in the order they appear in the sequential file;
    the KSDS organises them by its defined key field.

    Duplicate Key Handling
    ----------------------
    The original REPRO does NOT include REPLACE.  On the mainframe, a
    duplicate key would generate RC=8 and the record would be silently
    skipped.  This implementation:
      1. Detects duplicate key records using a window function.
      2. Routes duplicates to a separate quarantine DataFrame.
      3. Writes only the first-seen record per key to the primary output,
         exactly mirroring mainframe behaviour.
      4. Logs a WARNING so that silent data loss is made explicit.

    Parameters
    ----------
    input_df : DataFrame
        The raw wire transfer records read from the sequential flat file
        (WIRE.DAILY.INPUT.SEQ).  Expected schema:

        • All EBCDIC character fields must have been transcoded to UTF-8
          before this function is called.
        • All packed-decimal (PD) fields must have been decoded to their
          integer equivalents (LongType or IntegerType) before ingestion.
        • The column identified as the KSDS primary key must be present.
          Its name is held in the constant KSDS_KEY_COLUMN and must be
          updated once the DEFINE CLUSTER statement is located.

    config : StepConfig, optional
        Runtime configuration.  A default StepConfig is used when omitted.
    source_path : str, optional
        Filesystem / S3 path from which input_df was read.  Written into
        the audit column AUDIT_SOURCE_FILE.

    Returns
    -------
    RepроResult
        .primary    — DataFrame ready for write to the KSDS-equivalent table.
        .duplicates — DataFrame of quarantined duplicate-key records.
        .metrics    — dict with keys:
                        "input_count"     : total rows read from input_df
                        "primary_count"   : rows written to primary output
                        "duplicate_count" : rows quarantined

    Key Field Mapping (PLACEHOLDER — update from DEFINE CLUSTER)
    ------------------------------------------------------------
    +------------------+-------------------------+--------+--------+--------+
    | Mainframe Offset | Mainframe Length/Format | Column Constant         |
    +------------------+-------------------------+-------------------------+
    | TBD (DEFINE      | TBD                     | KSDS_KEY_COLUMN         |
    | CLUSTER KEYS)    |                         | = "ksds_primary_key"    |
    +------------------+-------------------------+-------------------------+

    Original SYSIN
    --------------
        REPRO INFILE(SEQIN)      -
              OUTFILE(VSAMOUT)
    """
    if config is None:
        config = StepConfig()

    logger.info(
        "STEP020 — IDCAMS REPRO migration starting. "
        "Source: %s → Target: %s",
        config.source_dataset_name,
        config.target_dataset_name,
    )

    # ------------------------------------------------------------------
    # 1. Validate that the key column exists in the input schema.
    #    On the mainframe, if the key field position falls outside the
    #    record length the REPRO would fail with a non-zero RC.
    # ------------------------------------------------------------------
    _validate_input_schema(input_df, config)

    # ------------------------------------------------------------------
    # 2. Add audit / lineage columns.
    #    These have no mainframe equivalent but are essential for
    #    traceability in a modern data platform.
    # ------------------------------------------------------------------
    # Mainframe: REPRO INFILE(SEQIN) — straight copy, no decoration
    enriched_df = _add_audit_columns(input_df, source_path)

    # ------------------------------------------------------------------
    # 3. Detect duplicate keys.
    #    Mainframe: REPRO without REPLACE — duplicate key → RC=8, record
    #    skipped.  Here we surface duplicates explicitly.
    # ------------------------------------------------------------------
    # Mainframe: (implicit) duplicate key → RC=8, record silently skipped
    df_with_rank = _rank_by_key(enriched_df, config.ksds_key_column)

    # ------------------------------------------------------------------
    # 4. Split primary (first-seen per key) from duplicates.
    # ------------------------------------------------------------------
    primary_df, duplicate_df = _split_primary_and_duplicates(
        df_with_rank, config
    )

    # ------------------------------------------------------------------
    # 5. Collect metrics.
    # ------------------------------------------------------------------
    metrics = _collect_metrics(primary_df, duplicate_df)

    _log_metrics(metrics, config)

    return RepроResult(
        primary=primary_df,
        duplicates=duplicate_df,
        metrics=metrics,
    )


