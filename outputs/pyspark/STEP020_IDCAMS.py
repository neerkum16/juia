def write_primary_output(
    result: RepроResult,
    output_path: str,
    config: Optional[StepConfig] = None,
    output_format: str = "delta",
) -> None:
    """
    Write the primary staging DataFrame to the KSDS-equivalent table.

    Equivalent to the REPRO OUTFILE(VSAMOUT) operation writing records into
    WIRE.WORK.INPUT.KSDS.

    Parameters
    ----------
    result : RepроResult
        Return value from load_wire_daily_input_to_staging.
    output_path : str
        Delta Lake table path or S3 prefix.
        e.g. "s3://bucket/wire/work/input/ksds/"
    config : StepConfig, optional
        Step configuration (for write_mode).
    output_format : str
        "delta" (default) or "parquet".
    """
    if config is None:
        config = StepConfig()

    logger.info(
        "STEP020 — Writing %d primary records to '%s' (format=%s, mode=%s).",
        result.metrics["primary_count"],
        output_path,
        output_format,
        config.write_mode,
    )

    # Mainframe: REPRO OUTFILE(VSAMOUT) → writes to WIRE.WORK.INPUT.KSDS
    (
        result.primary
        .write
        .format(output_format)
        .mode(config.write_mode)
        .save(output_path)
    )

    logger.info("STEP020 — Primary output write complete.")


def write_quarantine_output(
    result: RepроResult,
    quarantine_path: str,
    output_format: str = "delta",
) -> None:
    """
    Write duplicate-key records to a quarantine path for investigation.

    This has no mainframe equivalent — REPRO would have silently skipped
    these records.  Writing them here ensures no wire transactions are lost
    without an audit trail.

    Parameters
    ----------
    result : RepроResult
        Return value from load_wire_daily_input_to_staging.
    quarantine_path : str
        Delta Lake table path or S3 prefix for duplicate records.
        e.g. "s3://bucket/wire/quarantine/ksds_duplicates/"
    output_format : str
        "delta" (default) or "parquet".
    """
    if result.metrics["duplicate_count"] == 0:
        logger.info("STEP020 — No duplicates to quarantine.")
        return

    logger.warning(
        "STEP020 — Writing %d quarantined duplicate-key record(s) to '%s'.",
        result.metrics["duplicate_count"],
        quarantine_path,
    )

    (
        result.duplicates
        .write
        .format(output_format)
        .mode("append")   # append so historical duplicates are not lost
        .save(quarantine_path)
    )

    logger.info("STEP020 — Quarantine write complete.")


