class CatalogueAdapter:
    """
    Abstract base for target-platform catalogue adapters.

    Subclass this for each target platform (AWS Glue, Azure Purview,
    Apache Atlas, local Hive metastore, etc.) and implement
    ``fetch_metadata()``.  The main LISTCAT function is platform-agnostic
    and delegates catalogue queries to whatever adapter is injected at
    runtime.
    """

    def fetch_metadata(self, dataset_name: str) -> CatalogueEntry:
        """
        Retrieve catalogue metadata for *dataset_name*.

        Parameters
        ----------
        dataset_name : str
            The fully-qualified dataset name in the target catalogue
            (e.g. ``"wire_work.input_ksds"``).

        Returns
        -------
        CatalogueEntry
            Populated metadata record.  If the dataset does not exist,
            return a ``CatalogueEntry`` with ``exists=False`` and
            ``condition_code=4``.

        Raises
        ------
        NotImplementedError
            Must be overridden in concrete subclasses.
        """
        raise NotImplementedError(
            f"{type(self).__name__} must implement fetch_metadata()"
        )


class SparkCatalogueAdapter(CatalogueAdapter):
    """
    Concrete adapter that queries the Spark / Hive metastore (or any
    catalogue exposed through the SparkSession catalogue API).

    This is the default adapter when no platform-specific client is
    available.  It uses ``spark.catalog.tableExists()`` for existence
    checks and ``spark.catalog.listColumns()`` for schema introspection.
    Physical statistics (RBA, extents, record counts) cannot be derived
    from the Spark catalogue; those fields are populated with sentinel
    values of -1 to indicate "not available on this platform".
    """

    def __init__(self, spark: SparkSession) -> None:
        self._spark = spark

    def fetch_metadata(self, dataset_name: str) -> CatalogueEntry:
        """
        Query the Spark metastore for *dataset_name* and build a
        ``CatalogueEntry``.

        Parameters
        ----------
        dataset_name : str
            Dot-separated database.table name (e.g. ``"wire_work.input_ksds"``).

        Returns
        -------
        CatalogueEntry
            Populated entry; physical VSAM attributes are set to -1 where
            the Spark catalogue cannot supply them.
        """
        parts      = dataset_name.split(".", maxsplit=1)
        db_name    = parts[0] if len(parts) == 2 else "default"
        table_name = parts[1] if len(parts) == 2 else parts[0]

        entry = CatalogueEntry(dataset_name=dataset_name)

        try:
            exists = self._spark.catalog.tableExists(f"{db_name}.{table_name}")
        except Exception as exc:  # noqa: BLE001
            logger.warning(
                "Spark catalogue existence check failed for %s — treating as "
                "not found.  Error: %s",
                dataset_name,
                exc,
            )
            exists = False

        if not exists:
            entry.exists         = False
            entry.condition_code = 4
            return entry

        # --- Populate what the Spark catalogue can provide ------------------
        entry.exists         = True
        entry.condition_code = 0

        try:
            columns = self._spark.catalog.listColumns(table_name, dbName=db_name)
            # Approximate AVGLRECL from column count — not a real LRECL,
            # but provides a structural sanity indicator.
            entry.avg_lrecl = len(columns) * 10  # heuristic placeholder
        except Exception as exc:  # noqa: BLE001
            logger.debug("Could not list columns for %s: %s", dataset_name, exc)

        try:
            tbl = self._spark.catalog.getTable(f"{db_name}.{table_name}")
            entry.dataset_type    = tbl.tableType or "MANAGED"
            entry.organisation    = "SPARK_TABLE"
            entry.creation_date   = str(tbl.description or "")
        except Exception as exc:  # noqa: BLE001
            logger.debug("getTable() unavailable for %s: %s", dataset_name, exc)

        try:
            # Attempt to get row count via ANALYZE TABLE if supported.
            self._spark.sql(
                f"ANALYZE TABLE {db_name}.{table_name} COMPUTE STATISTICS"
            )
            stats: dict[str, Any] = (
                self._spark.sql(
                    f"DESCRIBE EXTENDED {db_name}.{table_name}"
                )
                .filter("col_name = 'Statistics'")
                .collect()
            )
            if stats:
                entry.rec_total = -1   # parse from stats[0] if format is known
        except Exception:  # noqa: BLE001
            pass  # ANALYZE not supported on all platforms — silently skip

        # Physical VSAM attributes not available from Spark catalogue.
        for attr in (
            "key_offset", "key_length", "max_lrecl",
            "ci_size", "ca_size", "primary_alloc", "secondary_alloc",
            "freespace_ci_pct", "freespace_ca_pct",
            "high_alloc_rba", "high_used_rba",
            "extent_count", "rec_inserted", "rec_deleted",
            "rec_updated", "rec_retrieved",
        ):
            if getattr(entry, attr) == 0:
                setattr(entry, attr, -1)   # -1 = "N/A on this platform"

        entry.volser           = "N/A"
        entry.expiry_date      = "N/A"
        entry.last_update_date = datetime.now(timezone.utc).strftime("%Y-%m-%d")

        return entry


class AWSGlueCatalogueAdapter(CatalogueAdapter):
    """
    Concrete adapter that queries the AWS Glue Data Catalog via boto3.

    Usage
    -----
    ::

        import boto3
        glue_client = boto3.client("glue", region_name="us-east-1")
        adapter = AWSGlueCatalogueAdapter(glue_client)
        listcat_vsam_ksds_metadata(spark, catalogue_adapter=adapter)

    Notes
    -----
    * ``boto3`` must be installed and AWS credentials must be available in
      the execution environment.
    * The dataset name convention maps ``"wire_work.input_ksds"`` to
      ``DatabaseName="wire_work"`` and ``TableName="input_ksds"``.
    * Physical VSAM statistics (RBA, extents) are not held in the Glue
      catalogue and will be reported as -1.
    """

    def __init__(self, glue_client: Any) -> None:
        """
        Parameters
        ----------
        glue_client : boto3.client("glue")
            A pre-authenticated boto3 Glue client.
        """
        self._glue = glue_client

    def fetch_metadata(self, dataset_name: str) -> CatalogueEntry:
        """
        Call ``glue_client.get_table()`` and map the Glue response to a
        ``CatalogueEntry``.

        Mainframe SYSIN equivalent:
            LISTCAT ENTRIES(<dataset_name>) ALL
        """
        parts      = dataset_name.split(".", maxsplit=1)
        db_name    = parts[0] if len(parts) == 2 else "default"
        table_name = parts[1] if len(parts) == 2 else parts[0]

        entry = CatalogueEntry(dataset_name=dataset_name)

        try:
            # Mainframe: LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS) ALL
            # Migration: boto3 Glue DescribeTable API call
            response = self._glue.get_table(
                DatabaseName=db_name,
                Name=table_name,
            )
            tbl = response.get("Table", {})

            entry.exists              = True
            entry.condition_code      = 0
            entry.dataset_type        = "KSDS"
            entry.organisation        = tbl.get("TableType", "EXTERNAL_TABLE")
            entry.creation_date       = str(tbl.get("CreateTime", ""))
            entry.last_update_date    = str(tbl.get("UpdateTime", ""))

            params: dict[str, str] = tbl.get("Parameters", {})
            entry.rec_total           = int(params.get("numRows",       -1))
            entry.avg_lrecl           = int(params.get("averageRecordSize", -1))

            sd = tbl.get("StorageDescriptor", {})
            entry.volser              = sd.get("Location", "N/A")

            # Physical VSAM attributes are not available in Glue.
            for attr in (
                "key_offset", "key_length", "max_lrecl",
                "ci_size", "ca_size", "primary_alloc", "secondary_alloc",
                "freespace_ci_pct", "freespace_ca_pct",
                "high_alloc_rba", "high_used_rba", "extent_count",
                "rec_inserted", "rec_deleted", "rec_updated", "rec_retrieved",
            ):
                if getattr(entry, attr) == 0:
                    setattr(entry, attr, -1)

        except Exception as exc:  # noqa: BLE001
            # boto3 raises ClientError with Code="EntityNotFoundException"
            # when the table does not exist — mirrors LISTCAT CC=4.
            error_code = getattr(
                getattr(exc, "response", {}).get("Error", {}), "get",
                lambda *_: ""
            )("Code", "")
            if error_code == "EntityNotFoundException" or "not found" in str(exc).lower():
                entry.exists         = False
                entry.condition_code = 4
                logger.warning(
                    "LISTCAT: entry not found in AWS Glue — %s (CC=4)", dataset_name
                )
            else:
                # Unexpected error — re-raise so the orchestrator can handle it.
                logger.error(
                    "LISTCAT: unexpected error querying Glue for %s: %s",
                    dataset_name, exc,
                )
                raise

        return entry


