    if USE_HIVE_ADAPTER:
        # Option A: Hive / Spark metastore — enableHiveSupport() is appropriate
        spark = (
            SparkSession.builder
            .appName("STEP090_IDCAMS_LISTCAT")
            .enableHiveSupport()   # Required for Hive metastore catalogue queries
            .getOrCreate()
        )
    else:
        # FIX (ISSUE 7): Option B — AWS Glue or non-Hive environment.
        # Do NOT call enableHiveSupport() as there is no Hive metastore.
        spark = (
            SparkSession.builder
            .appName("STEP090_IDCAMS_LISTCAT")
            .getOrCreate()
        )

    spark.sparkContext.setLogLevel("WARN")

    logger.info("Starting STEP090 — IDCAMS LISTCAT equivalent")
    logger.info("Job: wire_payment_batch.jcl")
