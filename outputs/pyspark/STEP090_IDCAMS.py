def listcat_vsam_ksds_metadata(
    spark: SparkSession,
    *,
    catalogue_adapter: CatalogueAdapter | None = None,
    raise_on_missing: bool = True,
) -> dict[str, CatalogueEntry]:
    """
    Perform the equivalent of the IDCAMS LISTCAT ALL operation for the two
    VSAM KSDS datasets referenced in STEP090 of wire_payment_batch.jcl.

    This function replicates the diagnostic / audit purpose of the mainframe
    step: it queries the target platform's data catalogue for each dataset,
    captures the available metadata attributes, emits a SYSPRINT-style report
    to the application log, and raises ``DatasetNotFoundException`` if either
    dataset is absent (replicating the IDCAMS CC=4 condition-code signal that
    downstream JCL steps may test).

    Original SYSIN control cards (verbatim)
    ----------------------------------------
    ::

        LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS)  ALL
        LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS)  ALL

    Dataset mapping — mainframe to target platform
    -----------------------------------------------
    +--------------------------+--------------------+----------------------+
    | Mainframe ENTRY          | Target DB          | Target Table         |
    +--------------------------+--------------------+----------------------+
    | WIRE.WORK.INPUT.KSDS     | wire_work          | input_ksds           |
    | WIRE.WORK.EXTRT.KSDS     | wire_work          | extrt_ksds           |
    +--------------------------+--------------------+----------------------+

    Condition-code mapping
    ----------------------
    +----+----------------------------------------------------------+
    | CC | Meaning                                                  |
    +----+----------------------------------------------------------+
    |  0 | All LISTCAT entries found; metadata captured.            |
    |  4 | One or more entries not found in the catalogue.          |
    +----+----------------------------------------------------------+

    Key field mapping
    -----------------
    IDCAMS LISTCAT ALL produces no relational key fields; catalogue attribute
    names used as Python constants are defined at the top of this module and
    correspond directly to the LISTCAT ALL output sections (STATISTICS, DATES,
    DATA, etc.).

    Parameters
    ----------
    spark : SparkSession
        Active SparkSession used by the default ``SparkCatalogueAdapter``.
        If *catalogue_adapter* is supplied the SparkSession is still accepted
        for API symmetry but may not be used internally.
    catalogue_adapter : CatalogueAdapter, optional
        Platform-specific catalogue client.  Defaults to
        ``SparkCatalogueAdapter(spark)`` (Hive / Spark metastore).
        Inject an ``AWSGlueCatalogueAdapter`` for AWS deployments or a
        custom subclass for other platforms.
    raise_on_missing : bool, default True
        When ``True`` (the default), raise ``DatasetNotFoundException`` if any
        LISTCAT entry is not found — replicating the IDCAMS CC=4 abort signal.
        Set to ``False`` to log warnings and continue, returning entries with
        ``exists=False`` in the result dictionary.

    Returns
    -------
    dict[str, CatalogueEntry]
        Mapping of dataset name → ``CatalogueEntry`` for every entry listed
        in the original SYSIN.  Callers can inspect ``entry.condition_code``
        and ``entry.exists`` to make downstream routing decisions.

    Raises
    ------
    DatasetNotFoundException
        Raised when *raise_on_missing* is ``True`` and at least one LISTCAT
        entry is absent from the catalogue.  The exception carries a
        ``missing`` attribute listing the absent dataset names.

    Examples
    --------
    >>> results = listcat_vsam_ksds_metadata(spark)
    >>> for name, entry in results.items():
    ...     print(name, "→ CC =", entry.condition_code, "| rows =", entry.rec_total)
    """
    if catalogue_adapter is None:
        catalogue_adapter = SparkCatalogueAdapter(spark)

    logger.info(
        "STEP090 — IDCAMS LISTCAT processing started.  "
        "Entries to query: %d",
        len(_LISTCAT_ENTRIES),
    )
    logger.info(
        "Platform catalogue adapter: %s", type(catalogue_adapter).__name__
    )

    results:  dict[str, CatalogueEntry] = {}
    missing:  list[str]                 = []
    max_cc:   int                       = 0   # mirrors JCL MAXCC

    for dataset_name in _LISTCAT_ENTRIES:

        logger.info("LISTCAT ENTRIES(%s) ALL — querying catalogue …", dataset_name.upper())

        # ------------------------------------------------------------------
        # Mainframe: LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS) ALL
        # Mainframe: LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS) ALL
        # ------------------------------------------------------------------
        entry = catalogue_adapter.fetch_metadata(dataset_name)
        results[dataset_name] = entry

        # Emit SYSPRINT-style report block to application log
        for line in entry.as_sysprint_block().splitlines():
            logger.info(line)

        if entry.condition_code > max_cc:
            max_cc = entry.condition_code

        if not entry.exists:
            missing.append(dataset_name)
            logger.warning(
                "LISTCAT: ENTRY NOT FOUND — %s  (CC=%d)",
                dataset_name.upper(),
                entry.condition_code,
            )
        else:
            logger.info(
                "LISTCAT: ENTRY FOUND    — %s  (CC=%d)  "
                "REC-TOTAL=%s  HI-USED-RBA=%s",
                dataset_name.upper(),
                entry.condition_code,
                entry.rec_total,
                entry.high_used_rba,
            )

    logger.info(
        "STEP090 — IDCAMS LISTCAT processing complete.  "
        "MAXCC = %d  |  Entries found: %d / %d",
        max_cc,
        len(_LISTCAT_ENTRIES) - len(missing),
        len(_LISTCAT_ENTRIES),
    )

    # Mirror JCL MAXCC / LASTCC semantics --------------------------------
    if missing and raise_on_missing:
        raise DatasetNotFoundException(missing)

    return results


