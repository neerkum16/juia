def initialise_wire_work_ksds_datasets(
    spark: SparkSession,
    database: str = "default",
    raise_on_error: bool = True,
) -> StepResult:
    """
    Scratch-and-rebuild two VSAM KSDS work datasets for the wire transfer
    processing pipeline.

    This function is the PySpark equivalent of IDCAMS STEP010 from
    ``wire_payment_batch.jcl``.  It performs the following operations in order,
    exactly mirroring the SYSIN control stream:

    1. **DELETE WIRE.WORK.INPUT.KSDS**  — drops the existing Delta Lake table
       and underlying storage (PURGE equivalent).  A "not found" condition is
       tolerated (IDCAMS CC=8 equivalent).

    2. **DELETE WIRE.WORK.EXTRT.KSDS**  — same as above for the extract dataset.

    3. **DEFINE CLUSTER WIRE.WORK.INPUT.KSDS**  — creates an empty Delta Lake
       table with a 200-byte fixed-length equivalent schema, a 16-byte primary
       key column (``wire_key``), Change Data Feed enabled, and
       ``WriteSerializable`` isolation.  Primary allocation: 20 cylinders
       equivalent.

    4. **DEFINE CLUSTER WIRE.WORK.EXTRT.KSDS**  — same as above but with a
       10-cylinder primary allocation equivalent (extract subset, ~half the
       input volume).

    No data is read or written; this step produces only empty, correctly
    structured datasets ready for downstream population.

    Original SYSIN control cards (verbatim)::

        DELETE WIRE.WORK.INPUT.KSDS  CLUSTER PURGE
        DELETE WIRE.WORK.EXTRT.KSDS  CLUSTER PURGE
        IF LASTCC > 8 THEN
          SET MAXCC = 0
        DEFINE CLUSTER                           -
          (NAME(WIRE.WORK.INPUT.KSDS)            -
           INDEXED                               -
           KEYS(16 0)                            -
           RECORDSIZE(200 200)                   -
           CYLINDERS(20 5)                       -
           SHAREOPTIONS(2 3))                    -
        DATA                                     -
          (NAME(WIRE.WORK.INPUT.KSDS.DATA))      -
        INDEX                                    -
          (NAME(WIRE.WORK.INPUT.KSDS.INDEX))
        DEFINE CLUSTER                           -
          (NAME(WIRE.WORK.EXTRT.KSDS)            -
           INDEXED                               -
           KEYS(16 0)                            -
           RECORDSIZE(200 200)                   -
           CYLINDERS(10 5)                       -
           SHAREOPTIONS(2 3))                    -
        DATA                                     -
          (NAME(WIRE.WORK.EXTRT.KSDS.DATA))      -
        INDEX                                    -
          (NAME(WIRE.WORK.EXTRT.KSDS.INDEX))

    Key field mapping
    -----------------
    +-----------------+--------+--------+--------+--------------------------+
    | Mainframe Field | Offset | Length | Format | Python Column            |
    +=================+========+========+========+==========================+
    | KSDS Primary Key|      1 |     16 | CH     | ``wire_key``             |
    +-----------------+--------+--------+--------+--------------------------+
    | Record Payload  |     17 |    184 | CH     | ``payload``              |
    +-----------------+--------+--------+--------+--------------------------+

    Note: ``wire_key`` originates as an EBCDIC character field on the
    mainframe.  The upstream ingestion layer is responsible for EBCDIC→UTF-8
    transcoding before records are written to these tables.

    Parameters
    ----------
    spark:
        Active ``SparkSession`` with Delta Lake configured.
    database:
        Hive metastore database / Unity Catalog schema into which the tables
        are created.  Defaults to ``"default"``.
    raise_on_error:
        If ``True`` (default), raise a ``RuntimeError`` when any operation
        fails with an unexpected error (equivalent to IDCAMS CC > 8 aborting
        the job).  Set to ``False`` to collect all errors and return them in
        the :class:`StepResult` without raising.

    Returns
    -------
    StepResult
        A structured record of every operation performed, its outcome, and any
        error messages.  ``result.success`` is ``True`` only if all operations
        completed without unexpected failures.

    Raises
    ------
    RuntimeError
        If ``raise_on_error=True`` and one or more operations fail with an
        unexpected error.
    """
    logger.info("=" * 72)
    logger.info("STEP010  IDCAMS  wire_payment_batch.jcl")
    logger.info("Initialising VSAM KSDS work datasets (scratch-and-rebuild)")
    logger.info("=" * 72)

    result = StepResult()

    # ------------------------------------------------------------------
    # Phase 1: DELETE — drop any pre-existing versions of both clusters.
    #
    # Mainframe: DELETE WIRE.WORK.INPUT.KSDS CLUSTER PURGE
    # Mainframe: DELETE WIRE.WORK.EXTRT.KSDS CLUSTER PURGE
    # Mainframe: IF LASTCC > 8 THEN SET MAXCC = 0
    #
    # A "not found" condition (CC=8) is explicitly tolerated — it is
    # normal on a first run or after a clean environment reset.
    # Only errors with CC > 8 (unexpected failures) are propagated.
    # ------------------------------------------------------------------
    logger.info("--- Phase 1: DELETE (PURGE) ---")

    for descriptor in _ALL_KSDS_DATASETS:
        # Mainframe: DELETE <cluster> CLUSTER PURGE
        _drop_delta_table(spark, descriptor, result)

    if not result.success and raise_on_error:
        raise RuntimeError(
            "STEP010 Phase 1 (DELETE) encountered unexpected errors — "
            "aborting before DEFINE.  Errors: " + "; ".join(result.errors)
        )

    # ------------------------------------------------------------------
    # Phase 2: DEFINE CLUSTER — re-create both clusters as empty Delta
    # Lake tables with the correct schema and sharing properties.
    #
    # Mainframe: DEFINE CLUSTER (NAME(WIRE.WORK.INPUT.KSDS) INDEXED
    #              KEYS(16 0) RECORDSIZE(200 200) CYLINDERS(20 5)
    #              SHAREOPTIONS(2 3))
    #            DATA  (NAME(WIRE.WORK.INPUT.KSDS.DATA))
    #            INDEX (NAME(WIRE.WORK.INPUT.KSDS.INDEX))
    #
    # Mainframe: DEFINE CLUSTER (NAME(WIRE.WORK.EXTRT.KSDS) INDEXED
    #              KEYS(16 0) RECORDSIZE(200 200) CYLINDERS(10 5)
    #              SHAREOPTIONS(2 3))
    #            DATA  (NAME(WIRE.WORK.EXTRT.KSDS.DATA))
    #            INDEX (NAME(WIRE.WORK.EXTRT.KSDS.INDEX))
    # ------------------------------------------------------------------
    logger.info("--- Phase 2: DEFINE CLUSTER ---")

    for descriptor in _ALL_KSDS_DATASETS:
        # Mainframe: DEFINE CLUSTER ... (see docstring for full card image)
        _define_delta_table(spark, descriptor, result, database=database)

    # ------------------------------------------------------------------
    # Final status
    # ------------------------------------------------------------------
    if result.success:
        logger.info(
            "STEP010 completed successfully.  %d operation(s) recorded.",
            len(result.operations),
        )
    else:
        logger.error(
            "STEP010 completed WITH ERRORS.  %d error(s): %s",
            len(result.errors),
            "; ".join(result.errors),
        )
        if raise_on_error:
            raise RuntimeError(
                "STEP010 failed.  Errors: " + "; ".join(result.errors)
            )

    logger.info("=" * 72)
    return result


