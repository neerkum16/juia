def verify_wire_work_ksds_datasets(
    spark: SparkSession,
    database: str = "default",
) -> dict[str, bool]:
    """
    Verify that both KSDS-equivalent Delta Lake tables exist and are empty
    after successful initialisation by :func:`initialise_wire_work_ksds_datasets`.

    This is analogous to an IDCAMS LISTCAT command confirming the clusters
    exist after a DEFINE.

    Parameters
    ----------
    spark:
        Active ``SparkSession``.
    database:
        Hive database / Unity Catalog schema to inspect.

    Returns
    -------
    dict[str, bool]
        Mapping of ``{table_name: is_verified}`` where ``True`` means the
        table exists, uses Delta format, has the expected schema, and is empty.
    """
    verification: dict[str, bool] = {}

    for descriptor in _ALL_KSDS_DATASETS:
        table = descriptor.delta_table_name
        full_name = f"{database}.{table}"
        try:
            df = spark.table(full_name)

            # Schema check: both key columns must be present
            actual_columns = set(df.columns)
            required_columns = {COL_WIRE_KEY, COL_PAYLOAD}
            schema_ok = required_columns.issubset(actual_columns)

            # Empty check: DEFINE creates an empty cluster
            row_count = df.count()
            is_empty = row_count == 0

            # Delta format check
            is_delta = DeltaTable.isDeltaTable(spark, descriptor.delta_table_path)

            verified = schema_ok and is_empty and is_delta
            verification[table] = verified

            logger.info(
                "VERIFY %-40s  schema_ok=%-5s  is_empty=%-5s  is_delta=%-5s  → %s",
                full_name,
                schema_ok,
                is_empty,
                is_delta,
                "PASS" if verified else "FAIL",
            )

        except Exception as exc:  # noqa: BLE001
            logger.error("VERIFY %s FAILED: %s", full_name, exc)
            verification[table] = False

    return verification


