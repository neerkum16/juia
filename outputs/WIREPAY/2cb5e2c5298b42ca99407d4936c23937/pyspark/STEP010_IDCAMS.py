def _drop_delta_table(
    spark: SparkSession,
    descriptor: KsdsDescriptor,
    result: StepResult,
) -> None:
    """
    Drop a Delta Lake table and its underlying storage path, tolerating the
    case where neither the table catalogue entry nor the storage path exists.

    This mirrors the IDCAMS behaviour:
        DELETE <cluster> CLUSTER PURGE
        IF LASTCC > 8 THEN SET MAXCC = 0

    CC=8 (dataset not found) is acceptable; only errors with CC > 8 would
    abort the original job — here they raise an exception after recording
    the failure in *result*.

    Parameters
    ----------
    spark:
        Active SparkSession.
    descriptor:
        Metadata for the dataset to be dropped.
    result:
        Mutable result collector updated in-place.
    """
    table = descriptor.delta_table_name
    path = descriptor.delta_table_path

    # ------------------------------------------------------------------
    # Mainframe: DELETE <cluster> CLUSTER PURGE
    # Drop the Hive / Unity Catalog table entry first (equivalent to
    # removing the catalogue record), then the underlying storage files
    # (equivalent to PURGE — bypasses expiration date, removes data).
    # ------------------------------------------------------------------
    table_existed = False
    try:
        logger.info("DROP TABLE IF EXISTS %s", table)
        # DeltaTable.forName raises AnalysisException when table is absent —
        # that is the CC=8 equivalent; we catch it and continue.
        if DeltaTable.isDeltaTable(spark, path):
            table_existed = True

        spark.sql(f"DROP TABLE IF EXISTS {table}")  # noqa: S608 — table name is a constant
        logger.info("Dropped catalogue entry for table: %s", table)

    except Exception as exc:  # noqa: BLE001
        # Any exception here beyond "not found" is unexpected (CC > 8).
        error_msg = (
            f"Unexpected error dropping catalogue entry for {table}: {exc}"
        )
        logger.error(error_msg)
        result.errors.append(error_msg)
        result.success = False
        result.record(table, "DROP_TABLE", OperationStatus.FAILED)
        return

    # ------------------------------------------------------------------
    # Remove the underlying Delta Lake storage path (PURGE equivalent).
    # dbutils is the Databricks file-system utility; replace with an
    # appropriate storage SDK call in non-Databricks environments
    # (e.g. azure-storage-blob, boto3, or hadoop FileSystem via JVM).
    # ------------------------------------------------------------------
    try:
        dbutils: Any = _get_dbutils(spark)  # type: ignore[assignment]
        if dbutils is not None:
            dbutils.fs.rm(path, recurse=True)
            logger.info("Removed storage path: %s", path)
        else:
            # Fallback: use Spark's Hadoop FileSystem API
            _remove_hadoop_path(spark, path)

    except Exception as exc:  # noqa: BLE001
        # If the path simply does not exist that is fine — not-found is
        # the CC=8 equivalent and is explicitly tolerated.
        err_str = str(exc).lower()
        if "nosuchfile" in err_str or "not found" in err_str or "no such file" in err_str:
            logger.info(
                "Storage path not found (tolerated — equivalent to CC=8): %s", path
            )
            result.record(descriptor.cluster_name, "DELETE", OperationStatus.NOT_FOUND_TOLERATED)
            return
        # Anything else is unexpected (CC > 8 equivalent).
        error_msg = f"Unexpected error removing storage path {path}: {exc}"
        logger.error(error_msg)
        result.errors.append(error_msg)
        result.success = False
        result.record(descriptor.cluster_name, "DELETE", OperationStatus.FAILED)
        return

    status = (
        OperationStatus.DROPPED_EXISTING
        if table_existed
        else OperationStatus.NOT_FOUND_TOLERATED
    )
    result.record(descriptor.cluster_name, "DELETE", status)


def _define_delta_table(
    spark: SparkSession,
    descriptor: KsdsDescriptor,
    result: StepResult,
    database: str = "default",
) -> None:
    """
    Create an empty Delta Lake table equivalent to an IDCAMS DEFINE CLUSTER.

    The table is created with:
    * The schema defined in :data:`KSDS_SCHEMA` (200-byte record equivalent).
    * ``delta.enableChangeDataFeed`` enabled — supports concurrent read/write
      patterns analogous to VSAM SHAREOPTIONS(2 3).
    * ``delta.isolationLevel`` set to ``WriteSerializable`` to preserve
      within-cluster write ordering (SHAREOPTIONS option 2 analogue).
    * A UNIQUE constraint on :data:`COL_WIRE_KEY` to enforce KSDS key
      uniqueness.  (On Databricks / Unity Catalog; remove if not supported.)
    * Table properties recording provenance from the mainframe step.

    Parameters
    ----------
    spark:
        Active SparkSession.
    descriptor:
        Metadata for the dataset to be created.
    result:
        Mutable result collector updated in-place.
    database:
        Target Hive database / Unity Catalog schema name.
    """
    table = descriptor.delta_table_name
    path = descriptor.delta_table_path
    full_table_name = f"{database}.{table}"

    logger.info(
        "DEFINE CLUSTER %s → Delta Lake table %s at %s",
        descriptor.cluster_name,
        full_table_name,
        path,
    )

    # ------------------------------------------------------------------
    # Mainframe:
    #   DEFINE CLUSTER
    #     (NAME(<cluster>)
    #      INDEXED
    #      KEYS(16 0)
    #      RECORDSIZE(200 200)
    #      CYLINDERS(<primary> <secondary>)
    #      SHAREOPTIONS(2 3))
    #   DATA  (NAME(<cluster>.DATA))
    #   INDEX (NAME(<cluster>.INDEX))
    #
    # Modern equivalent: CREATE TABLE … USING DELTA with properties that
    # mirror the VSAM structural and sharing characteristics.
    # ------------------------------------------------------------------
    try:
        (
            spark.createDataFrame([], KSDS_SCHEMA)
            .write.format("delta")
            .mode("overwrite")
            .option("overwriteSchema", "true")
            .option("path", path)
            # SHAREOPTIONS(2 3): enable Change Data Feed so concurrent
            # readers can track changes during a write window.
            .option("delta.enableChangeDataFeed", "true")
            # SHAREOPTIONS option 2 (within system — one writer at a time):
            # WriteSerializable prevents concurrent write conflicts.
            .option("delta.isolationLevel", "WriteSerializable")
            .option(
                "delta.minReaderVersion", "1",
            )
            .option(
                "delta.minWriterVersion", "4",
            )
            .saveAsTable(full_table_name)
        )

        # Record provenance and mainframe lineage in table properties.
        _apply_table_properties(spark, full_table_name, descriptor)

        logger.info(
            "Created Delta Lake table %s (path=%s, schema=%s cols)",
            full_table_name,
            path,
            len(KSDS_SCHEMA.fields),
        )
        result.record(descriptor.cluster_name, "DEFINE", OperationStatus.CREATED)

    except Exception as exc:  # noqa: BLE001
        error_msg = (
            f"Failed to create Delta Lake table {full_table_name} "
            f"(cluster={descriptor.cluster_name}): {exc}"
        )
        logger.error(error_msg)
        result.errors.append(error_msg)
        result.success = False
        result.record(descriptor.cluster_name, "DEFINE", OperationStatus.FAILED)


def _apply_table_properties(
    spark: SparkSession,
    full_table_name: str,
    descriptor: KsdsDescriptor,
) -> None:
    """
    Stamp Delta Lake table properties with mainframe lineage metadata.

    These properties are visible via DESCRIBE EXTENDED and serve as an
    audit trail back to the original VSAM cluster definition.

    Parameters
    ----------
    spark:
        Active SparkSession.
    full_table_name:
        Fully-qualified table name (database.table).
    descriptor:
        Source KSDS descriptor containing lineage metadata.
    """
    properties: dict[str, str] = {
        "mainframe.cluster_name": descriptor.cluster_name,
        "mainframe.data_component": descriptor.data_component,
        "mainframe.index_component": descriptor.index_component,
        "mainframe.record_type": "KSDS",
        "mainframe.record_size": str(RECORD_LENGTH_BYTES),
        "mainframe.key_length": str(KEY_LENGTH_BYTES),
        "mainframe.key_offset": str(KEY_OFFSET),
        "mainframe.primary_cylinders": str(descriptor.primary_cylinders),
        "mainframe.secondary_cylinders": str(descriptor.secondary_cylinders),
        "mainframe.shareoptions": "2 3",
        "mainframe.source_step": "STEP010",
        "mainframe.source_job": "wire_payment_batch.jcl",
        "mainframe.source_program": "IDCAMS",
        "migration.generated_by": "JUIA",
    }

    prop_kv = ", ".join(
        f"'{k}' = '{v}'" for k, v in properties.items()
    )
    alter_sql = f"ALTER TABLE {full_table_name} SET TBLPROPERTIES ({prop_kv})"  # noqa: S608
    spark.sql(alter_sql)


def _get_dbutils(spark: SparkSession) -> Any:
    """
    Attempt to obtain the Databricks ``dbutils`` helper via the JVM bridge.

    Returns ``None`` in non-Databricks environments so that callers can fall
    back to the Hadoop FileSystem API.

    Parameters
    ----------
    spark:
        Active SparkSession.

    Returns
    -------
    dbutils or None
    """
    try:
        from pyspark import SparkContext  # noqa: PLC0415
        sc: SparkContext = spark.sparkContext
        # pylint: disable=protected-access
        dbutils_module = sc._jvm.com.databricks.service.DBUtils  # type: ignore[attr-defined]
        return dbutils_module
    except Exception:  # noqa: BLE001
        pass

    # Second attempt: IPython / notebook kernel injection
    try:
        import IPython  # noqa: PLC0415
        kernel = IPython.get_ipython()
        if kernel is not None and "dbutils" in kernel.user_ns:
            return kernel.user_ns["dbutils"]
    except Exception:  # noqa: BLE001
        pass

    return None


def _remove_hadoop_path(spark: SparkSession, path: str) -> None:
    """
    Remove a storage path using Spark's Hadoop FileSystem API.

    This is the non-Databricks fallback for environments where ``dbutils``
    is not available (e.g. EMR, HDInsight, standalone Spark).

    Parameters
    ----------
    spark:
        Active SparkSession.
    path:
        The HDFS / object-store path to remove recursively.

    Raises
    ------
    RuntimeError
        If the FileSystem call reports an error other than "not found".
    """
    # pylint: disable=protected-access
    jvm = spark.sparkContext._jvm  # type: ignore[attr-defined]
    hadoop_conf = spark.sparkContext._jsc.hadoopConfiguration()  # type: ignore[attr-defined]
    fs_class = jvm.org.apache.hadoop.fs.FileSystem
    path_class = jvm.org.apache.hadoop.fs.Path
    hadoop_path = path_class(path)
    file_system = fs_class.get(hadoop_path.toUri(), hadoop_conf)

    if file_system.exists(hadoop_path):
        file_system.delete(hadoop_path, True)  # True = recursive
        logger.info("Hadoop FS: removed %s", path)
    else:
        logger.info("Hadoop FS: path not found (tolerated): %s", path)


