def summarise_wire_transfers_by_currency(input_df: DataFrame) -> DataFrame:
    """Summarise wire transfer records aggregated by currency code and amount tier.

    Implements DFSORT STEP070 from wire_payment_batch.jcl.

    Business Rule
    -------------
    Records from WIRE.PROCESSED.SEQ are sorted by currency code (ascending)
    and then by transaction amount (descending) so that within each currency
    group the largest amounts appear first.  Records that share BOTH the same
    currency code AND the same transaction amount value are collapsed into a
    single consolidated record whose amount field is the arithmetic sum of all
    contributing records.  The surviving record is then reformatted to 200
    bytes by extracting and reordering six fields; the remaining 156 bytes are
    padded with spaces to satisfy the fixed-block LRECL=200 requirement of the
    SORTOUT dataset.

    IMPORTANT — Pre-conditions on input_df
    ---------------------------------------
    * ``transaction_amount`` (offset 17, len 9, PD):
        Must already be decoded from EBCDIC packed decimal to a Python-native
        numeric type (LongType or DecimalType).  Raw packed-decimal bytes
        cannot be summed or compared directly.  Decoding is the responsibility
        of the upstream ingestion layer (e.g., an EBCDIC extraction job,
        IBM DataStage, or a custom Spark UDF).

    * ``account_ref``, ``value_date``, ``country_code``, ``currency_code``,
      ``txn_type_code`` (all CH fields):
        Must be transcoded from EBCDIC to UTF-8 before this function runs.
        Character fields that are still in raw EBCDIC bytes will produce
        incorrect sort orders and garbled output strings.

    * ``account_ref`` (offset 1, len 16):
        When multiple source records share the same (currency_code,
        transaction_amount) key, DFSORT retains the field values from the
        *first* record encountered after the descending-amount sort (i.e. the
        record with the largest original amount).  This function replicates
        that behaviour by using a Window row_number() to deterministically
        select the first record per group before aggregation.

    Parameters
    ----------
    input_df : DataFrame
        Input DataFrame representing WIRE.PROCESSED.SEQ.
        Expected schema:
          - account_ref       : StringType()   — 16-char account/wire ref
          - transaction_amount: LongType()     — decoded PD amount (integer)
          - value_date        : StringType()   — 8-char settlement date
          - country_code      : StringType()   — 2-char country/routing code
          - currency_code     : StringType()   — 3-char ISO currency code
          - txn_type_code     : StringType()   — 3-char transaction type/status

    Returns
    -------
    DataFrame
        A single output DataFrame representing WIRE.SUMMARY.SEQ with schema:
          - account_ref       : StringType()   — positions  1-16  of output
          - currency_code     : StringType()   — positions 17-19  of output
          - summed_amount     : StringType()   — positions 20-31  of output
                                                 (12-char space-left-padded
                                                  signed integer string
                                                  representation of the FS
                                                  field; negative values carry
                                                  a leading '-' sign)
          - value_date        : StringType()   — positions 32-39  of output
          - country_code      : StringType()   — positions 40-41  of output
          - txn_type_code     : StringType()   — positions 42-44  of output
          - _padding          : StringType()   — positions 45-200 of output
                                                 (156 spaces; mirrors
                                                  DFSORT LRECL=200 pad)

    Key Field Mapping (Mainframe → PySpark Column)
    -----------------------------------------------
    +--------+-----+--------+----------------------+-------------------+
    | Offset | Len | Format | Mainframe Purpose    | PySpark Column    |
    +--------+-----+--------+----------------------+-------------------+
    |      1 |  16 | CH     | Account / wire ref   | account_ref       |
    |     17 |   9 | PD     | Transaction amount   | transaction_amount|
    |     44 |   8 | CH     | Value / settlement   | value_date        |
    |     55 |   2 | CH     | Country / routing    | country_code      |
    |     63 |   3 | CH     | Currency code        | currency_code     |
    |     66 |   3 | CH     | Txn type / status    | txn_type_code     |
    +--------+-----+--------+----------------------+-------------------+

    Original SYSIN (verbatim)
    --------------------------
    ::

        SORT FIELDS=(63,3,CH,A,17,9,PD,D)
        SUM FIELDS=(17,9,PD)
        OUTREC FIELDS=(1,16,
                       63,3,
                       17,9,PD,TO=FS,LENGTH=12,
                       44,8,
                       55,2,
                       66,3)

    Migration Notes
    ---------------
    * SORT + SUM semantics: DFSORT collapses records only when ALL sort key
      fields are equal — both ``currency_code`` AND ``transaction_amount``
      must match.  If the business intent is to sum amounts across the entire
      currency group regardless of individual amount values, the groupBy key
      should be ``currency_code`` alone.  Validate with business owners.

    * PD→FS conversion: DFSORT ``TO=FS,LENGTH=12`` converts the 9-byte packed
      decimal to a 12-byte signed binary integer.  In PySpark the decoded
      LongType column carries the same semantic; the ``summed_amount`` column
      in this implementation renders it as a space-left-padded 12-character
      string to faithfully represent the fixed-width flat-file field for
      downstream fixed-block consumers.  If an implied decimal scale applies
      (e.g., last 2 digits = cents), apply the appropriate divisor before
      writing.

    * Non-summed field retention: Where records are collapsed by SUM, DFSORT
      keeps the non-key, non-summed field values from the record that appears
      first after sorting — which, given the descending-amount sort, is the
      record originally carrying the largest amount.  A Window row_number()
      partitioned by (currency_code, transaction_amount) and ordered by
      transaction_amount DESC is used to deterministically tag and select the
      first record per group, guaranteeing correct field retention regardless
      of partition boundaries.

    * Output padding: LRECL=200 but only 44 bytes are explicitly mapped in
      OUTREC — the remaining 156 bytes are spaces.  The ``_padding`` column
      carries these spaces so the DataFrame can be serialised to a faithful
      200-byte flat file if required.  Downstream Parquet/Delta consumers may
      drop ``_padding`` as it carries no information.
    """

    # -------------------------------------------------------------------------
    # Step 1 — Validate that all required columns are present in the input.
    # -------------------------------------------------------------------------
    _required_columns = {
        ACCOUNT_REF,
        TRANSACTION_AMOUNT,
        VALUE_DATE,
        COUNTRY_CODE,
        CURRENCY_CODE,
        TXN_TYPE_CODE,
    }
    _missing = _required_columns - set(input_df.columns)
    if _missing:
        raise ValueError(
            f"STEP070: Input DataFrame is missing required columns: {sorted(_missing)}. "
            "Ensure the upstream extraction job has decoded all PD fields and "
            "transcoded all EBCDIC character fields before calling this function."
        )

    # -------------------------------------------------------------------------
    # Step 2 — Sort the data.
    #
    # Mainframe: SORT FIELDS=(63,3,CH,A,17,9,PD,D)
    #   Primary key  : currency_code     (offset 63, len 3, CH)  → ascending
    #   Secondary key: transaction_amount (offset 17, len 9, PD) → descending
    #
    # The sort groups same-currency records together and within each currency
    # group places the largest amounts first.  This ordering is critical for
    # correct non-summed-field retention (first record per group = record with
    # largest amount, as identified by the Window row_number in Step 3).
    #
    # NOTE: transaction_amount must already be a decoded numeric column (e.g.
    #       LongType) at this point — raw PD bytes cannot be sorted correctly
    #       as character data.
    # -------------------------------------------------------------------------
    df_sorted: DataFrame = input_df.orderBy(
        F.col(CURRENCY_CODE).asc(),
        F.col(TRANSACTION_AMOUNT).desc(),
    )

    # -------------------------------------------------------------------------
    # Step 3 — Aggregate / SUM with deterministic first-record retention.
    #
    # Mainframe: SUM FIELDS=(17,9,PD)
    #   Collapses all records whose sort key (currency_code, transaction_amount)
    #   is identical by summing their transaction_amount values.  All duplicate
    #   records after summation are eliminated; one consolidated record survives
    #   per unique (currency_code, transaction_amount) combination.
    #
    #   Non-key, non-summed fields (account_ref, value_date, country_code,
    #   txn_type_code) are retained from the first record in each group —
    #   which, after the descending-amount sort above, is the record that
    #   originally carried the largest amount within the group.
    #
    # FIX 3 (aggregation): Replaced the orderBy+groupBy+first() pattern with a
    # Window-based approach to guarantee deterministic first-record retention.
    # Spark's groupBy does not guarantee that row ordering established by a
    # prior orderBy is preserved within each partition group during aggregation,
    # making F.first() potentially non-deterministic across shuffle boundaries.
    # Using Window.partitionBy(CURRENCY_CODE, TRANSACTION_AMOUNT).orderBy(
    # TRANSACTION_AMOUNT DESC) with row_number() deterministically tags the
    # first record in each group.  We then:
    #   (a) compute the per-group SUM via a window sum, and
    #   (b) filter to row_number == 1 to retain that record's non-key fields,
    # replicating DFSORT's first-record retention semantics reliably.
    #
    # IMPORTANT: transaction_amount is both a sort key AND the SUM field.
    #   DFSORT sums it across duplicate key records, so the surviving record's
    #   amount equals the total of all contributing records.  Within a group
    #   every record has the same amount value (they are equal on the sort key)
    #   and the sum is simply N × that amount value.
    # -------------------------------------------------------------------------

    # Define the Window spec partitioned by the two sort-key fields, ordered
    # by transaction_amount descending — mirrors the DFSORT sort sequence and
    # defines which record is "first" for non-key field retention.
    _group_window = Window.partitionBy(
        F.col(CURRENCY_CODE),
        F.col(TRANSACTION_AMOUNT),
    ).orderBy(
        F.col(TRANSACTION_AMOUNT).desc(),
    )

    # Tag each row with its position within its (currency_code,
    # transaction_amount) group.  Row 1 is the "first" record per DFSORT
    # semantics and will supply the non-key field values for the output record.
    # Also compute the per-group SUM via a window aggregate so we can carry
    # both the numeric sum and the first-record non-key fields in a single pass
    # without a join.
    df_windowed: DataFrame = df_sorted.withColumn(
        _ROW_NUM_COL,
        F.row_number().over(_group_window),
    ).withColumn(
        # FIX 1 (sort_logic) / FIX 3 (aggregation): Compute SUMMED_AMOUNT_NUMERIC
        # as a true numeric (LongType) window sum so it can be used for correct
        # numeric ordering in the final sort step.  This column is retained
        # alongside the string-cast summed_amount to enable numeric orderBy.
        SUMMED_AMOUNT_NUMERIC,
        F.sum(F.col(TRANSACTION_AMOUNT)).over(
            Window.partitionBy(
                F.col(CURRENCY_CODE),
                F.col(TRANSACTION_AMOUNT),
            )
            # No orderBy on the sum window — unbounded partition sum is correct
            # and avoids a running-sum (rowsBetween default with orderBy would
            # give a cumulative sum, not the full-partition total).
        ),
    )

    # Filter to the first record per (currency_code, transaction_amount) group.
    # This record carries the correct non-key field values (account_ref,
    # value_date, country_code, txn_type_code) as DFSORT would retain them,
    # and its SUMMED_AMOUNT_NUMERIC column already holds the full group sum.
    df_aggregated: DataFrame = df_windowed.filter(
        F.col(_ROW_NUM_COL) == 1
    ).drop(_ROW_NUM_COL)

    # -------------------------------------------------------------------------
    # Step 4 — Reformat / OUTREC.
    #
    # Mainframe: OUTREC FIELDS=(1,16,
    #                            63,3,
    #                            17,9,PD,TO=FS,LENGTH=12,
    #                            44,8,
    #                            55,2,
    #                            66,3)
    #
    # Rebuilds each output record to LRECL=200 fixed format:
    #   Field 1 : bytes  1-16  → account_ref       (16 chars, CH verbatim)
    #   Field 2 : bytes 17-19  → currency_code     ( 3 chars, CH verbatim)
    #   Field 3 : bytes 20-31  → summed_amount      (12 chars, PD→FS signed)
    #   Field 4 : bytes 32-39  → value_date         ( 8 chars, CH verbatim)
    #   Field 5 : bytes 40-41  → country_code       ( 2 chars, CH verbatim)
    #   Field 6 : bytes 42-44  → txn_type_code      ( 3 chars, CH verbatim)
    #   Padding : bytes 45-200 → 156 spaces (DFSORT fills unmapped bytes)
    #
    # PD→FS conversion note:
    #   TO=FS,LENGTH=12 produces a 12-byte signed binary integer.  Here we
    #   cast the decoded LongType to a space-left-padded 12-character string to
    #   represent the fixed-width flat-file slot.  Negative values will carry a
    #   leading '-' character immediately adjacent to the digits (e.g.
    #   '       -1234' for -1234), which is the correct sign placement for a
    #   fixed-block mainframe reader.  If the amount carries an implied decimal
    #   scale (e.g. 2 implied decimal places for cents), confirm the scaling
    #   factor with field documentation before writing.
    # -------------------------------------------------------------------------

    # Represent the 12-byte FS (signed fixed-point) integer as a right-aligned,
    # space-left-padded 12-character string — faithful to the fixed-width
    # flat-file field.  Negative values will be prefixed with '-' immediately
    # adjacent to the digits because cast('string') on a negative Long produces
    # e.g. '-1234567', and lpad then pads the entire string (including the sign)
    # to 12 characters with leading spaces: '    -1234567'.
    #
    # FIX 1 (sort_logic): The _amount_fs_expr is a StringType expression used
    # ONLY for the output column value.  The final orderBy (Step 5) now uses
    # SUMMED_AMOUNT_NUMERIC (LongType) instead of this string column, avoiding
    # the lexicographic-sort bug for negative or variable-length values.
    _amount_fs_expr = (
        F.lpad(
            F.col(SUMMED_AMOUNT_NUMERIC).cast("string"),
            12,
            " ",
        )
    )

    # Padding column — 156 spaces to reach LRECL=200
    _padding_expr = F.lit(" " * OUTREC_PAD_BYTES)

    df_outrec: DataFrame = df_aggregated.select(
        # Field 1: account/wire reference (offset 1, len 16, CH)
        F.col(ACCOUNT_REF),

        # Field 2: currency code (offset 63, len 3, CH) — primary sort key
        F.col(CURRENCY_CODE),

        # Field 3: summed amount → 12-char space-left-padded signed FS string
        #          (offset 17, len 9, PD → TO=FS,LENGTH=12)
        #          StringType — see docstring Returns section.
        _amount_fs_expr.alias(SUMMED_AMOUNT),

        # Field 4: value/settlement date (offset 44, len 8, CH)
        F.col(VALUE_DATE),

        # Field 5: country/routing code (offset 55, len 2, CH)
        F.col(COUNTRY_CODE),

        # Field 6: transaction type/status code (offset 66, len 3, CH)
        F.col(TXN_TYPE_CODE),

        # Padding: remaining 156 bytes to reach LRECL=200 (spaces)
        _padding_expr.alias("_padding"),

        # FIX 1 (sort_logic): Carry the numeric sum through the select so the
        # final orderBy can reference it as a LongType column.  This column
        # will be dropped from the returned DataFrame after the sort.
        F.col(SUMMED_AMOUNT_NUMERIC),
    )

    # -------------------------------------------------------------------------
    # Step 5 — Final sort on output to match DFSORT's guaranteed output order.
    #
    # DFSORT preserves the sort sequence in the output dataset.  We apply the
    # same ordering to the final DataFrame so that downstream sequential
    # readers encounter records in currency-ascending, amount-descending order
    # — consistent with what WIRE.SUMMARY.SEQ would contain on the mainframe.
    #
    # FIX 1 (sort_logic): Changed the orderBy to use SUMMED_AMOUNT_NUMERIC
    # (LongType) instead of SUMMED_AMOUNT (StringType).  Sorting the lpad
    # string column lexicographically gives wrong results for negative values
    # (the '-' character sorts before digits, so negatives would appear before
    # positives in lexicographic order, inverting the expected numeric
    # descending sequence) and for values whose string representations differ
    # in length.  Sorting the numeric LongType column gives correct numeric
    # descending order for all values including negatives.
    # After the orderBy the SUMMED_AMOUNT_NUMERIC helper column is dropped so
    # the returned DataFrame contains only the six business columns and
    # _padding, matching the documented output schema.
    # -------------------------------------------------------------------------
    df_output: DataFrame = (
        df_outrec
        .orderBy(
            F.col(CURRENCY_CODE).asc(),
            F.col(SUMMED_AMOUNT_NUMERIC).desc(),   # FIX 1: numeric sort, not string
        )
        .drop(SUMMED_AMOUNT_NUMERIC)               # FIX 1: remove helper column from output
    )

    return df_output


