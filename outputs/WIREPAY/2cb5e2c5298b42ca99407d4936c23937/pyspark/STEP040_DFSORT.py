    # ------------------------------------------------------------------
    # Execute the DFSORT SORT + OUTFIL split logic.
    # ------------------------------------------------------------------
    result: Dict[str, DataFrame] = split_wire_transfers_by_value(input_df)

    df_high: DataFrame = result["HIGH"]
    df_low: DataFrame = result["LOW"]

    # ------------------------------------------------------------------
    # Write HIGHVAL output — equivalent to WIRE.WORK.HIGH.SEQ
    # RECFM=FB, LRECL=200, SPACE=(CYL,(5,2))
    # ------------------------------------------------------------------
    highval_output_path: str = "path/to/wire_work_high_seq"
    (
        df_high
        .write
        .mode("overwrite")
        .parquet(highval_output_path)
    )

    # ------------------------------------------------------------------
    # Write LOWVAL output — equivalent to WIRE.WORK.LOW.SEQ
    # RECFM=FB, LRECL=200, SPACE=(CYL,(5,2))
    # ------------------------------------------------------------------
    lowval_output_path: str = "path/to/wire_work_low_seq"
    (
        df_low
        .write
        .mode("overwrite")
        .parquet(lowval_output_path)
    )

    # ------------------------------------------------------------------
    # Diagnostic row counts — mirror the message-dataset record counts
    # that DFSORT prints to SYSOUT at the end of the job step.
    # ------------------------------------------------------------------
