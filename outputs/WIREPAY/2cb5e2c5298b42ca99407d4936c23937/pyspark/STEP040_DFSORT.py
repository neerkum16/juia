# Program      : SORT
# Utility Type : DFSORT
# Job Name     : wire_payment_batch.jcl
#
# Business Rule:
#   Processes a wire transfer extract file by sorting all records in descending
#   order by the packed-decimal wire transfer amount field (bytes 17-25). After
#   sorting, the stream is split into two output datasets based on a threshold
#   of 1,000,000:
#     - HIGHVAL (WIRE.WORK.HIGH.SEQ): records where amount > 1,000,000
#       (high-value wire transfers requiring separate downstream handling or
#       regulatory scrutiny)
#     - LOWVAL  (WIRE.WORK.LOW.SEQ) : records where amount <= 1,000,000
#       (standard or low-value wire transfers)
#   Both output files preserve the descending sort order of the source stream.
#   A record with an amount exactly equal to 1,000,000 is routed to LOWVAL
#   (LE boundary semantics, matching DFSORT OUTFIL INCLUDE behaviour).
#
# Generated by JUIA (JCL Universal Intelligence Adapter)
# =============================================================================

from pyspark.sql import DataFrame, SparkSession
from pyspark.sql import functions as F
from pyspark.sql.types import (
    LongType,
    StringType,
    StructField,
    StructType,
)
from typing import Dict


# =============================================================================
# COLUMN NAME CONSTANTS
# Each constant maps to a logical field in the wire transfer extract record.
# Mainframe offsets are 1-based; lengths are in bytes.
# =============================================================================

# Primary sort key and split criterion.
# Mainframe: offset 17, length 9, format PD (IBM Packed Decimal / BCD)
# NOTE: This column must hold the *decoded* integer value before this function
#       is called.  Raw packed-decimal bytes cannot be compared numerically by
#       PySpark.  Use a dedicated PD-decoding UDF or pre-processing step to
#       convert the 9-byte PD field to a Python int / LongType column.
WIRE_AMOUNT: str = "wire_amount"

# Convenience alias used in output routing comments.
# Both HIGHVAL and LOWVAL carry the full 200-byte fixed-block record unchanged;
# no column projection or reformatting is applied (matching DFSORT OUTFIL
# default behaviour — INCLUDE only, no OUTREC).
RAW_RECORD: str = "raw_record"  # optional: full fixed-length record, StringType

# Threshold value (matches DFSORT OUTFIL INCLUDE GT/LE +1000000)
_SPLIT_THRESHOLD: int = 1_000_000


def split_wire_transfers_by_value(
    input_df: DataFrame,
) -> Dict[str, DataFrame]:
    """
    Sort a wire transfer extract by amount (descending) and split into
    high-value and low-value output datasets.

    Business Rule
    -------------
    Implements DFSORT SORT FIELDS=(17,9,PD,D) followed by two OUTFIL
    statements that partition the sorted stream on the wire transfer amount:

        OUTFIL FNAMES=HIGHVAL, INCLUDE=(17,9,PD,GT,+1000000)
        OUTFIL FNAMES=LOWVAL,  INCLUDE=(17,9,PD,LE,+1000000)

    The GT / LE pair is exhaustive — every record is routed to exactly one
    output file.  A record whose amount equals 1,000,000 exactly is always
    written to LOWVAL (LE semantics).

    Parameters
    ----------
    input_df : DataFrame
        Spark DataFrame representing WIRE.WORK.EXTRT.SEQ.  Must contain at
        minimum the following column:

        Column Name   Type      Mainframe Layout
        -----------   --------  ------------------------------------
        wire_amount   LongType  Offset 17, Len 9, Format PD (decoded)

        Additional columns (e.g. the full raw_record) are carried through
        unchanged to both output DataFrames — no projection is applied.

        IMPORTANT: The ``wire_amount`` column must already hold the decoded
        integer value.  IBM Packed Decimal (BCD) bytes must be converted to a
        numeric type *before* calling this function.  See the companion module
        pd_decoder.py for a PD-to-int UDF implementation.

    Returns
    -------
    Dict[str, DataFrame]
        A dictionary with exactly two keys:

        "HIGH"  → DataFrame for WIRE.WORK.HIGH.SEQ (HIGHVAL)
                  Contains only records where wire_amount > 1,000,000,
                  sorted by wire_amount descending.

        "LOW"   → DataFrame for WIRE.WORK.LOW.SEQ  (LOWVAL)
                  Contains only records where wire_amount <= 1,000,000,
                  sorted by wire_amount descending.

    Key Field Mapping
    -----------------
    Mainframe Offset  Length  Format  Column Name    Notes
    ----------------  ------  ------  -------------  -------------------------
    17                9       PD      wire_amount    Decoded integer; sort key
                                                     and split criterion.

    Original SYSIN Control Cards
    ----------------------------
    # SORT FIELDS=(17,9,PD,D)
    # OUTFIL FNAMES=HIGHVAL,
    #        INCLUDE=(17,9,PD,GT,+1000000)
    # OUTFIL FNAMES=LOWVAL,
    #        INCLUDE=(17,9,PD,LE,+1000000)

    Raises
    ------
    ValueError
        If ``input_df`` does not contain the required ``wire_amount`` column.
    """
    _validate_schema(input_df)

    # ------------------------------------------------------------------
    # Mainframe: SORT FIELDS=(17,9,PD,D)
    # Sort the full input stream in descending order by the decoded wire
    # transfer amount.  Both OUTFIL outputs inherit this sort order because
    # DFSORT applies OUTFIL filtering after the global sort pass — replicated
    # here by performing orderBy before the DataFrame split.
    # NOTE: wire_amount column must be pre-decoded from PD format (LongType).
    # ------------------------------------------------------------------
    df_sorted: DataFrame = input_df.orderBy(
        F.col(WIRE_AMOUNT).desc()
    )

    # ------------------------------------------------------------------
    # Mainframe: OUTFIL FNAMES=HIGHVAL, INCLUDE=(17,9,PD,GT,+1000000)
    # Retain only records where the wire transfer amount is strictly greater
    # than 1,000,000.  These are high-value transactions routed to HIGHVAL
    # (WIRE.WORK.HIGH.SEQ) for regulatory review or priority processing.
    # Boundary value 1,000,000 is excluded (GT, not GE).
    # ------------------------------------------------------------------
    df_high: DataFrame = df_sorted.filter(
        F.col(WIRE_AMOUNT) > _SPLIT_THRESHOLD
    )

    # ------------------------------------------------------------------
    # Mainframe: OUTFIL FNAMES=LOWVAL, INCLUDE=(17,9,PD,LE,+1000000)
    # Retain only records where the wire transfer amount is less than or
    # equal to 1,000,000.  These are standard or low-value transactions
    # routed to LOWVAL (WIRE.WORK.LOW.SEQ).
    # Boundary value 1,000,000 is INCLUDED here (LE), ensuring the GT/LE
    # pair is exhaustive and no record is dropped or duplicated.
    # NOTE: Negative amounts (debit reversals, adjustments) also satisfy
    #       this condition and will be written to LOWVAL.  Confirm with the
    #       business whether negative-value records require separate handling.
    # ------------------------------------------------------------------
    df_low: DataFrame = df_sorted.filter(
        F.col(WIRE_AMOUNT) <= _SPLIT_THRESHOLD
    )

    return {
        "HIGH": df_high,
        "LOW": df_low,
    }


