    low_count: int = df_low.count()
    total_count: int = high_count + low_count

    print(
        f"STEP040 complete.\n"
        f"  SORTIN total records : {total_count:>12,}\n"
        f"  HIGHVAL records      : {high_count:>12,}  (wire_amount > {_SPLIT_THRESHOLD:,})\n"
        f"  LOWVAL  records      : {low_count:>12,}  (wire_amount <= {_SPLIT_THRESHOLD:,})"
    )

    spark.stop()