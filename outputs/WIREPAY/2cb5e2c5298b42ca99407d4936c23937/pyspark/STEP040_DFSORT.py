def _validate_schema(df: DataFrame) -> None:
    """
    Assert that the input DataFrame contains all columns required by
    split_wire_transfers_by_value.  Raises ValueError with a descriptive
    message if a required column is absent so that schema mismatches surface
    immediately rather than as obscure runtime AnalysisExceptions.

    Parameters
    ----------
    df : DataFrame
        The DataFrame to validate.

    Raises
    ------
    ValueError
        If any required column is missing from the DataFrame schema.
    """
    required_columns = {WIRE_AMOUNT}
    actual_columns = {field.name for field in df.schema.fields}
    missing = required_columns - actual_columns

    if missing:
        raise ValueError(
            f"Input DataFrame is missing required column(s): {sorted(missing)}. "
            f"Available columns: {sorted(actual_columns)}. "
            f"Ensure the '{WIRE_AMOUNT}' column has been decoded from IBM "
            f"Packed Decimal (PD) format before calling this function."
        )


def build_wire_extract_schema() -> StructType:
    """
    Return a reference StructType for the wire transfer extract after PD
    decoding.  Use this schema when reading the source data to enforce
    type correctness at ingestion time.

    The ``wire_amount`` field corresponds to the 9-byte Packed Decimal field
    at mainframe offset 17 (1-based), decoded to a signed 64-bit integer.
    A 9-byte PD field can hold up to 17 significant digits, which fits
    comfortably within a LongType (max ~9.2 × 10^18).

    Returns
    -------
    StructType
        Schema for the decoded wire transfer extract DataFrame.
    """
    return StructType(
        [
            # Full fixed-length record image (LRECL=200, RECFM=FB).
            # Carried through unchanged to both output files.
            StructField(RAW_RECORD, StringType(), nullable=False),
            # Mainframe: offset 17, length 9, format PD — decoded integer.
            # NOTE: column must be populated by a PD-decoding step upstream.
            StructField(WIRE_AMOUNT, LongType(), nullable=False),
        ]
    )


