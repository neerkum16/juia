# Primary public function — equivalent of the full STEP090 IDCAMS execution
# ---------------------------------------------------------------------------
def verify_wire_ksds_catalog_entries(
    spark: SparkSession,
    database: str = CATALOG_DATABASE,
    input_ksds_table: str = TABLE_WORK_INPUT_KSDS,
    extrt_ksds_table: str = TABLE_WORK_EXTRT_KSDS,
    raise_on_failure: bool = True,
) -> dict[str, CatalogEntryReport]:
    """
    Verify that the two wire-processing VSAM KSDS datasets are correctly
    registered in the Spark / Hive metastore, and emit a full catalogue
    listing to the application log.

    This function is the PySpark equivalent of the following IDCAMS
    LISTCAT control cards executed in STEP090:

        LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS)  ALL
        LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS)  ALL

    On the mainframe, IDCAMS writes its output to SYSPRINT and sets a
    condition code (RC) which downstream JCL IF-THEN-ELSE logic inspects.
    Here, all output is written to the Python logger at INFO level, and
    a RuntimeError is raised (by default) when any entry is not found —
    replicating the effect of IDCAMS RC=8 aborting the job step.

    Parameters
    ----------
    spark : SparkSession
        Active SparkSession with access to the target metastore database.
        For AWS Glue use the GlueContext-derived session; for Databricks
        use the cluster's default session; for local testing use a
        local[*] session with a configured Hive metastore.
    database : str, optional
        Metastore database name.  Defaults to ``wire_db``.
        Mainframe equivalent: VSAM catalog / ICF catalog name.
    input_ksds_table : str, optional
        Table name that corresponds to ``WIRE.WORK.INPUT.KSDS``.
        Defaults to ``work_input_ksds``.
    extrt_ksds_table : str, optional
        Table name that corresponds to ``WIRE.WORK.EXTRT.KSDS``.
        Defaults to ``work_extrt_ksds``.
    raise_on_failure : bool, optional
        When True (default) a ``RuntimeError`` is raised if any entry
        is missing or has RC > 0, aborting the Spark application in the
        same way IDCAMS RC=8 would abort the JCL job step.
        Set to False to collect results without raising (useful in
        pipeline orchestration frameworks that handle errors externally).

    Returns
    -------
    dict[str, CatalogEntryReport]
        Dictionary keyed by mainframe dataset name:

        .. code-block:: python

            {
                "WIRE.WORK.INPUT.KSDS": CatalogEntryReport(...),
                "WIRE.WORK.EXTRT.KSDS": CatalogEntryReport(...),
            }

        Inspect each report's ``return_code`` and ``is_successful()``
        method for per-entry status.

    Raises
    ------
    RuntimeError
        When ``raise_on_failure=True`` and any catalogue entry cannot
        be verified (equivalent to IDCAMS condition code 8 or 12).

    Key Field Mapping
    -----------------
    No key fields are defined in this step — LISTCAT is a metadata-only
    operation.  When migrating the associated DEFINE CLUSTER steps (not
    present here), map the KEYS(length, offset) parameter to the primary
    key column of the target Delta / Parquet table.

    Original SYSIN (verbatim)
    -------------------------
    ::

        LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS)  ALL
        LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS)  ALL

    Notes
    -----
    * No data transformation occurs — this is a pure metadata / audit step.
    * All SYSPRINT-equivalent output is written via the module logger.
    * The ``CatalogEntryReport.sysprint()`` method returns the full report
      as a string for downstream logging, alerting, or audit-trail storage.
    """

    logger.info(
        "STEP090 — IDCAMS LISTCAT ALL — beginning wire KSDS catalog verification"
    )
    logger.info("Equivalent SYSIN control cards:")
    logger.info("  LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS)  ALL")
    logger.info("  LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS)  ALL")

    results: dict[str, CatalogEntryReport] = {}

    # ------------------------------------------------------------------
    # Mainframe: LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS) ALL
    # Retrieves full catalogue entry for the wire-processing INPUT KSDS.
    # Validates the dataset is properly defined and catalogued before
    # downstream wire-transaction processing steps execute.
    # ------------------------------------------------------------------
    logger.info("─" * 78)
    logger.info("Processing: LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS) ALL")
    input_report = _inspect_catalog_entry(
        spark=spark,
        database=database,
        table=input_ksds_table,
        mainframe_dataset="WIRE.WORK.INPUT.KSDS",
    )
    results["WIRE.WORK.INPUT.KSDS"] = input_report

    # Emit the SYSPRINT-equivalent report to the application log
    for line in input_report.detail_lines:
        logger.info(line)

    logger.info(
        "WIRE.WORK.INPUT.KSDS verification complete — RC=%d  %s",
        input_report.return_code,
        input_report.condition,
    )

    # ------------------------------------------------------------------
    # Mainframe: LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS) ALL
    # Retrieves full catalogue entry for the wire-processing EXTRACT KSDS.
    # Confirms the extract dataset is correctly defined, sized, and
    # accessible before downstream jobs consume it or after an extraction
    # step has populated it.
    # ------------------------------------------------------------------
    logger.info("─" * 78)
    logger.info("Processing: LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS) ALL")
    extrt_report = _inspect_catalog_entry(
        spark=spark,
        database=database,
        table=extrt_ksds_table,
        mainframe_dataset="WIRE.WORK.EXTRT.KSDS",
    )
    results["WIRE.WORK.EXTRT.KSDS"] = extrt_report

    # Emit the SYSPRINT-equivalent report to the application log
    for line in extrt_report.detail_lines:
        logger.info(line)

    logger.info(
        "WIRE.WORK.EXTRT.KSDS verification complete — RC=%d  %s",
        extrt_report.return_code,
        extrt_report.condition,
    )

    # ------------------------------------------------------------------
    # Determine overall step return code — worst-case across both entries.
    # This mirrors the IDCAMS behaviour of setting the job-step condition
    # code to the highest RC encountered across all control statements.
    # ------------------------------------------------------------------
    overall_rc = max(r.return_code for r in results.values())
    failed_entries = [
        ds for ds, r in results.items() if not r.is_successful()
    ]

    logger.info("─" * 78)
    logger.info("STEP090 overall return code : RC=%d", overall_rc)

    if failed_entries:
        logger.error(
            "STEP090 — VERIFICATION FAILED for %d dataset(s): %s",
            len(failed_entries),
            failed_entries,
        )
        if raise_on_failure:
            raise RuntimeError(
                f"STEP090 IDCAMS LISTCAT FAILED — "
                f"the following dataset(s) could not be verified in the "
                f"'{database}' catalog (equivalent to IDCAMS RC={overall_rc}): "
                f"{failed_entries}.  "
                f"Ensure the tables are registered in the Spark metastore "
                f"before executing downstream wire-processing pipeline steps."
            )
    else:
        logger.info(
            "STEP090 — ALL CATALOG ENTRIES VERIFIED SUCCESSFULLY (RC=0)"
        )

    return results


