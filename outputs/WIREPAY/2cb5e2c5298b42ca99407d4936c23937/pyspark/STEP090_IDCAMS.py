# Core helper — inspect one catalog entry
# ---------------------------------------------------------------------------
def _inspect_catalog_entry(
    spark: SparkSession,
    database: str,
    table: str,
    mainframe_dataset: str,
) -> CatalogEntryReport:
    """
    Perform a deep inspection of a single Spark catalog table, collecting
    all available metadata and formatting it as a LISTCAT ALL-style report.

    Parameters
    ----------
    spark : SparkSession
        Active SparkSession with access to the target metastore.
    database : str
        Hive / Glue metastore database name.
    table : str
        Table name within that database.
    mainframe_dataset : str
        Original mainframe VSAM KSDS dataset name (for reporting only).

    Returns
    -------
    CatalogEntryReport
        Populated report object.  Inspect `return_code` for success/failure.
    """
    report = CatalogEntryReport(
        mainframe_dataset=mainframe_dataset,
        spark_database=database,
        spark_table=table,
    )
    lines: list[str] = []

    def _line(text: str = "") -> None:
        lines.append(text)

    header_bar = "=" * 78

    _line(header_bar)
    _line(f"  IDCAMS SYSTEM SERVICES — LISTCAT ALL (migrated)")
    _line(f"  Mainframe Dataset : {mainframe_dataset}")
    _line(f"  Spark Catalog     : {database}.{table}")
    _line(f"  Verified At (UTC) : {report.verified_at.isoformat()}")
    _line(header_bar)

    # ------------------------------------------------------------------
    # 1. Verify the database exists
    # ------------------------------------------------------------------
    try:
        available_databases = [
            db.name for db in spark.catalog.listDatabases()
        ]
    except Exception as exc:  # noqa: BLE001
        report.return_code = RC_ERROR
        report.condition = f"METASTORE UNAVAILABLE — {exc}"
        _line(f"  *** ERROR — Could not list databases: {exc}")
        _line(header_bar)
        report.detail_lines = lines
        return report

    if database not in available_databases:
        report.return_code = RC_NOT_FOUND
        report.condition = (
            f"DATABASE '{database}' NOT FOUND IN CATALOG "
            f"(equivalent: IDCAMS RC=8 — ENTRY NOT FOUND)"
        )
        _line(f"  *** RC=8  DATABASE NOT FOUND: {database!r}")
        _line(f"  *** Available databases: {sorted(available_databases)}")
        _line(header_bar)
        report.detail_lines = lines
        return report

    _line(f"  DATABASE         : {database}  [FOUND — OK]")

    # ------------------------------------------------------------------
    # 2. Verify the table exists in the database
    # ------------------------------------------------------------------
    try:
        available_tables = [
            t.name for t in spark.catalog.listTables(database)
        ]
    except Exception as exc:  # noqa: BLE001
        report.return_code = RC_ERROR
        report.condition = f"ERROR LISTING TABLES IN {database!r} — {exc}"
        _line(f"  *** ERROR — Could not list tables in {database!r}: {exc}")
        _line(header_bar)
        report.detail_lines = lines
        return report

    if table not in available_tables:
        report.return_code = RC_NOT_FOUND
        report.condition = (
            f"TABLE '{database}.{table}' NOT FOUND IN CATALOG "
            f"(equivalent: IDCAMS RC=8 — ENTRY NOT FOUND)"
        )
        _line(f"  *** RC=8  TABLE NOT FOUND: {database}.{table}")
        _line(f"  *** Available tables: {sorted(available_tables)}")
        _line(header_bar)
        report.detail_lines = lines
        return report

    _line(f"  TABLE            : {database}.{table}  [FOUND — OK]")

    # ------------------------------------------------------------------
    # 3. Retrieve column schema — equivalent to KSDS key/record layout
    # ------------------------------------------------------------------
    try:
        column_list = spark.catalog.listColumns(table, dbName=database)
        columns: list[dict[str, str]] = []
        for col in column_list:
            col_info: dict[str, str] = {
                "name": col.name,
                "dataType": col.dataType,
                "nullable": str(col.nullable),
                "description": col.description or "",
            }
            columns.append(col_info)
        report.columns = columns
    except Exception as exc:  # noqa: BLE001
        report.return_code = RC_WARNING
        report.condition = f"TABLE FOUND BUT COLUMN LISTING FAILED — {exc}"
        _line(f"  *** RC=4  Could not list columns: {exc}")
        columns = []

    _line("")
    _line("  CLUSTER ——————————————————————————————————————————————————————")
    _line(f"       CLUSTER NAME  : {mainframe_dataset}")
    _line(f"       SPARK TABLE   : {database}.{table}")
    _line("")
    _line("  DATA COMPONENT / COLUMN LAYOUT (equivalent to KSDS record layout):")
    if columns:
        _line(f"  {'#':<4} {'COLUMN NAME':<40} {'DATA TYPE':<20} {'NULLABLE':<10} DESCRIPTION")
        _line("  " + "-" * 76)
        for idx, col_info in enumerate(columns, start=1):
            _line(
                f"  {idx:<4} {col_info['name']:<40} {col_info['dataType']:<20}"
                f" {col_info['nullable']:<10} {col_info['description']}"
            )
    else:
        _line("  (no column information available)")

    # ------------------------------------------------------------------
    # 4. Retrieve extended table properties via DESCRIBE EXTENDED
    #    — equivalent to the allocation, statistics, extent, and
    #      volume-serial sections of LISTCAT ALL output.
    # ------------------------------------------------------------------
    _line("")
    _line("  STATISTICS / ALLOCATION (equivalent to LISTCAT ALL extended output):")
    _line("  " + "-" * 76)

    extended_metadata: dict[str, Any] = {}
    try:
        # Spark SQL DESCRIBE EXTENDED returns a DataFrame with
        # col_name, data_type, comment columns.  We use it here purely
        # to capture table properties; no spark.sql() string queries are
        # used — instead we fall back to catalog APIs and direct property
        # reading where available.
        table_detail_df = (
            spark.catalog.listTables(database)
        )
        # Capture isTemporary flag from the catalog listing
        for tbl in table_detail_df:
            if tbl.name == table:
                extended_metadata[META_KEY_IS_TEMPORARY] = tbl.isTemporary
                extended_metadata[META_KEY_TABLE_TYPE] = tbl.tableType
                extended_metadata[META_KEY_DESCRIPTION] = tbl.description or ""
                break
    except Exception as exc:  # noqa: BLE001
        _line(f"  (table-type metadata unavailable: {exc})")

    # Attempt to read Spark table properties (Hive-style TBLPROPERTIES)
    try:
        props_df = spark.sql(  # noqa: F841  — needed for property extraction
            f"SHOW TBLPROPERTIES {database}.{table}"
        )
        for row in props_df.collect():
            key = row[0]
            val = row[1]
            extended_metadata[key] = val
    except Exception as exc:  # noqa: BLE001
        _line(f"  (table properties unavailable — {exc})")

    # Report what we collected
    stat_keys_of_interest = [
        (META_KEY_TABLE_TYPE,      "TABLE TYPE         "),
        (META_KEY_IS_TEMPORARY,    "IS TEMPORARY       "),
        (META_KEY_DESCRIPTION,     "DESCRIPTION        "),
        (META_KEY_LOCATION,        "LOCATION (PATH)    "),
        (META_KEY_PROVIDER,        "DATA PROVIDER      "),
        (META_KEY_INPUT_FORMAT,    "INPUT FORMAT       "),
        (META_KEY_OUTPUT_FORMAT,   "OUTPUT FORMAT      "),
        (META_KEY_SERDE,           "SERDE LIBRARY      "),
        (META_KEY_RECORD_COUNT,    "NUM ROWS (records) "),
        (META_KEY_SIZE_BYTES,      "RAW DATA SIZE (B)  "),
        (META_KEY_TOTAL_SIZE,      "TOTAL SIZE (B)     "),
        (META_KEY_LAST_MODIFIED,   "LAST DDL TIMESTAMP "),
    ]

    any_stat_found = False
    for prop_key, label in stat_keys_of_interest:
        val = extended_metadata.get(prop_key)
        if val is not None:
            _line(f"  {label}: {val}")
            any_stat_found = True

    if not any_stat_found:
        _line("  (extended statistics not available for this table type)")

    report.metadata = extended_metadata

    # ------------------------------------------------------------------
    # 5. Partition information — equivalent to VSAM extent reporting
    # ------------------------------------------------------------------
    _line("")
    _line("  PARTITIONS / EXTENTS (equivalent to VSAM EXTENT records):")
    _line("  " + "-" * 76)
    try:
        partitions = spark.catalog.listPartitions(  # type: ignore[attr-defined]
            database + "." + table
        )
        partition_list = list(partitions)
        if partition_list:
            _line(f"  PARTITION COUNT  : {len(partition_list)}")
            for idx, part in enumerate(partition_list, start=1):
                _line(f"  PARTITION {idx:>4}   : {part}")
        else:
            _line("  (table is not partitioned or no partitions found)")
    except Exception as exc:  # noqa: BLE001
        _line(f"  (partition information unavailable — {exc})")

    # ------------------------------------------------------------------
    # 6. Final return-code determination
    # ------------------------------------------------------------------
    if report.return_code not in (RC_ERROR, RC_WARNING, RC_NOT_FOUND):
        # Everything passed
        report.return_code = RC_SUCCESS
        report.condition = (
            "ENTRY FOUND AND VERIFIED — "
            "EQUIVALENT TO IDCAMS RC=0 (NORMAL COMPLETION)"
        )

    _line("")
    _line(header_bar)
    _line(f"  RETURN CODE : {report.return_code}")
    _line(f"  CONDITION   : {report.condition}")
    _line(header_bar)

    report.detail_lines = lines
    report.metadata[META_KEY_VERIFIED_AT] = report.verified_at.isoformat()
    report.metadata[META_KEY_RETURN_CODE] = report.return_code
    report.metadata[META_KEY_CONDITION] = report.condition

    return report


