@dataclass
class CatalogEntryReport:
    """
    Holds the full catalogue inspection result for a single dataset,
    analogous to the SYSPRINT output produced by IDCAMS LISTCAT … ALL.

    Attributes
    ----------
    mainframe_dataset : str
        Original mainframe dataset name (e.g. WIRE.WORK.INPUT.KSDS).
    spark_database : str
        Target Spark / Hive metastore database name.
    spark_table : str
        Target Spark / Hive metastore table name.
    return_code : int
        IDCAMS-equivalent return code (0, 4, 8, or 12).
    condition : str
        Human-readable condition description.
    metadata : dict[str, Any]
        Full metadata dictionary gathered from the Spark catalog.
    columns : list[dict[str, str]]
        Column descriptors — name, dataType, nullable, comment.
    detail_lines : list[str]
        Human-readable report lines written to the logger (equivalent to
        SYSPRINT in the original JCL step).
    verified_at : datetime
        UTC timestamp at which the verification was performed.
    """

    mainframe_dataset: str
    spark_database: str
    spark_table: str
    return_code: int = RC_NOT_FOUND
    condition: str = "NOT VERIFIED"
    metadata: dict[str, Any] = field(default_factory=dict)
    columns: list[dict[str, str]] = field(default_factory=list)
    detail_lines: list[str] = field(default_factory=list)
    verified_at: datetime = field(
        default_factory=lambda: datetime.now(tz=timezone.utc)
    )

    # ------------------------------------------------------------------
    def is_successful(self) -> bool:
        """Return True when the catalogue entry was found and verified."""
        return self.return_code == RC_SUCCESS

    # ------------------------------------------------------------------
    def sysprint(self) -> str:
        """
        Return the full report as a single string, mirroring the content
        that IDCAMS LISTCAT writes to SYSPRINT / JESMSGLG.
        """
        return "\n".join(self.detail_lines)


