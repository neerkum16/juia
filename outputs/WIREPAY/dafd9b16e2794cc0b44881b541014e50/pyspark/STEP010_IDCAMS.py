def initialise_wire_work_datasets(
    spark: SparkSession,
    input_config: KSDSTableConfig = INPUT_KSDS_CONFIG,
    extrt_config: KSDSTableConfig = EXTRT_KSDS_CONFIG,
) -> Dict[str, InitialisationResult]:
    """
    Initialise (scratch-and-redefine) the two VSAM KSDS work datasets used in
    the wire-transfer processing pipeline.

    This function is the modern PySpark / Delta Lake equivalent of the IDCAMS
    control cards in JCL step STEP010 of wire_payment_batch.jcl.

    Business Rule
    -------------
    Two KSDS work files are created fresh before each pipeline run:

    1. WIRE.WORK.INPUT.KSDS  (→ Delta table: wire_work_input_ksds)
       Holds the full wire-transfer input population.
       CYLINDERS(20 5) — larger allocation.

    2. WIRE.WORK.EXTRT.KSDS  (→ Delta table: wire_work_extrt_ksds)
       Holds the extracted / filtered subset of wire records.
       CYLINDERS(10 5) — smaller allocation.

    Both clusters share the same record layout:
      • Fixed-length 200-byte records  (RECORDSIZE(200 200))
      • 16-byte character primary key at byte offset 0  (KEYS(16 0))
      • SHAREOPTIONS(2 3) — multi-reader/single-writer + unrestricted cross-OS

    Error Tolerance
    ---------------
    The original IDCAMS step includes:

        IF LASTCC > 8 THEN
          SET MAXCC = 0

    This means that even if a DELETE command returns a condition code greater
    than 8 (a genuine error such as an ICF catalog fault or a security
    violation), the maximum condition code is reset to 0 and execution
    continues.  This function replicates that behaviour: a failure during the
    drop of a table is logged as a warning, captured in the result, but does
    NOT raise an exception — the subsequent DEFINE step still runs.

    A failure during a DEFINE (CREATE) step IS treated as a hard error because
    there is no mainframe precedent for silently continuing when the target
    dataset cannot be created.

    Original IDCAMS SYSIN
    ---------------------
    ::

        DELETE WIRE.WORK.INPUT.KSDS  CLUSTER PURGE
        DELETE WIRE.WORK.EXTRT.KSDS  CLUSTER PURGE
        IF LASTCC > 8 THEN
          SET MAXCC = 0
        DEFINE CLUSTER                           -
          (NAME(WIRE.WORK.INPUT.KSDS)            -
           INDEXED                               -
           KEYS(16 0)                            -
           RECORDSIZE(200 200)                   -
           CYLINDERS(20 5)                       -
           SHAREOPTIONS(2 3))                    -
        DATA                                     -
          (NAME(WIRE.WORK.INPUT.KSDS.DATA))      -
        INDEX                                    -
          (NAME(WIRE.WORK.INPUT.KSDS.INDEX))
        DEFINE CLUSTER                           -
          (NAME(WIRE.WORK.EXTRT.KSDS)            -
           INDEXED                               -
           KEYS(16 0)                            -
           RECORDSIZE(200 200)                   -
           CYLINDERS(10 5)                       -
           SHAREOPTIONS(2 3))                    -
        DATA                                     -
          (NAME(WIRE.WORK.EXTRT.KSDS.DATA))      -
        INDEX                                    -
          (NAME(WIRE.WORK.EXTRT.KSDS.INDEX))

    Key Field Mapping
    -----------------
    +------------------+-------+-----+--------+-------------------+
    | Column Constant  | Off.  | Len | Format | Description       |
    +==================+=======+=====+========+===================+
    | WIRE_KEY         |  1    |  16 | CH     | Primary KSDS key  |
    | WIRE_PAYLOAD     | 17    | 184 | CH     | Record payload    |
    +------------------+-------+-----+--------+-------------------+
    (Offsets are 1-based, matching mainframe convention.)

    NOTE — EBCDIC fields: WIRE_KEY is a CHARACTER (EBCDIC) field on the
    mainframe.  The upstream ingestion layer must transcode it to UTF-8 before
    writing to Delta Lake.

    Parameters
    ----------
    spark        : Active SparkSession.
    input_config : Configuration for WIRE.WORK.INPUT.KSDS.  Defaults to the
                   static INPUT_KSDS_CONFIG constant which mirrors the JCL.
    extrt_config : Configuration for WIRE.WORK.EXTRT.KSDS.  Defaults to the
                   static EXTRT_KSDS_CONFIG constant which mirrors the JCL.

    Returns
    -------
    dict mapping cluster name → InitialisationResult:
    ::

        {
            "WIRE.WORK.INPUT.KSDS": InitialisationResult(
                table_name="wire_work_input_ksds",
                delete_skipped=True,   # first run — table did not exist
                delete_success=False,
                delete_error=None,
                define_success=True,
                define_error=None,
            ),
            "WIRE.WORK.EXTRT.KSDS": InitialisationResult(...),
        }

    Raises
    ------
    RuntimeError
        If any DEFINE (table creation) step fails.  The error detail is also
        captured in the returned InitialisationResult.define_error field.
    """
    results: Dict[str, InitialisationResult] = {}

    for config in (input_config, extrt_config):
        logger.info(
            "=== Processing cluster: %s ===", config.cluster_name
        )

        # ------------------------------------------------------------------
        # Phase 1: DELETE (equivalent to IDCAMS DELETE … CLUSTER PURGE)
        # Mainframe: DELETE WIRE.WORK.INPUT.KSDS  CLUSTER PURGE
        # Mainframe: DELETE WIRE.WORK.EXTRT.KSDS  CLUSTER PURGE
        # ------------------------------------------------------------------
        result = _delete_cluster(spark, config)

        # ------------------------------------------------------------------
        # Phase 2: DEFINE (equivalent to IDCAMS DEFINE CLUSTER)
        # Mainframe: DEFINE CLUSTER (NAME(...) INDEXED KEYS(16 0) ...)
        #
        # We proceed even when delete_error is set, mirroring:
        #   IF LASTCC > 8 THEN SET MAXCC = 0
        # ------------------------------------------------------------------
        result = _define_cluster(spark, config, result)

        results[config.cluster_name] = result

        # Raise on define failure — no mainframe analogue for silently
        # continuing when a DEFINE fails
        if result.define_error is not None:
            raise RuntimeError(
                f"DEFINE CLUSTER equivalent failed for '{config.cluster_name}'. "
                f"See InitialisationResult.define_error for details: "
                f"{result.define_error}"
            ) from result.define_error

        logger.info(
            "Cluster '%s' initialisation complete — "
            "delete_skipped=%s delete_success=%s delete_error=%s "
            "define_success=%s define_error=%s",
            config.cluster_name,
            result.delete_skipped,
            result.delete_success,
            result.delete_error,
            result.define_success,
            result.define_error,
        )

    return results


