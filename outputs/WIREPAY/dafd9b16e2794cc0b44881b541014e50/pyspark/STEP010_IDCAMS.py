def _delete_cluster(
    spark: SparkSession,
    config: KSDSTableConfig,
) -> InitialisationResult:
    """
    Drop a Delta table if it exists, replicating the IDCAMS DELETE … PURGE
    behaviour.

    Mainframe SYSIN equivalent
    --------------------------
      DELETE WIRE.WORK.INPUT.KSDS  CLUSTER PURGE
      DELETE WIRE.WORK.EXTRT.KSDS  CLUSTER PURGE
      IF LASTCC > 8 THEN
        SET MAXCC = 0

    PURGE on the mainframe overrides the retention/expiry date.  In Delta Lake
    there is no concept of an expiry date on a table, so the PURGE semantics
    translate directly to DROP TABLE IF EXISTS (always succeeds regardless of
    any table properties).

    The IDCAMS convention is:
      CC = 0  → dataset deleted successfully
      CC = 8  → dataset not found (tolerated — first run or clean environment)
      CC > 8  → genuine error (ICF catalog / security fault)

    Here:
      • If the table does not exist we record delete_skipped = True  (≡ CC=8).
      • If the DROP raises an unexpected exception we capture it in
        delete_error but do NOT re-raise, exactly matching SET MAXCC = 0
        (execution continues so that the subsequent DEFINE can still run).

    Parameters
    ----------
    spark  : Active SparkSession.
    config : KSDSTableConfig describing the cluster to delete.

    Returns
    -------
    InitialisationResult with delete outcome fields populated.
    """
    result = InitialisationResult(table_name=config.delta_table_name)

    # Mainframe: DELETE <cluster> CLUSTER PURGE
    logger.info(
        "DELETE equivalent — dropping Delta table '%s' (path: %s) if it exists. "
        "Mainframe original: DELETE %s CLUSTER PURGE",
        config.delta_table_name,
        config.delta_table_path,
        config.cluster_name,
    )

    try:
        # Check existence first so we can distinguish CC=8 from CC=0
        table_exists = DeltaTable.isDeltaTable(spark, config.delta_table_path)

        if not table_exists:
            # Equivalent to IDCAMS CC=8 — dataset not found, tolerated
            logger.info(
                "Table '%s' does not exist at '%s' — skipping delete "
                "(equivalent to IDCAMS CC=8: dataset not found, tolerated).",
                config.delta_table_name,
                config.delta_table_path,
            )
            result.delete_skipped = True
        else:
            # Table exists — drop it unconditionally (PURGE semantics)
            spark.sql(
                f"DROP TABLE IF EXISTS `{config.delta_table_name}`"  # noqa: S608
            )
            logger.info(
                "Table '%s' dropped successfully (equivalent to IDCAMS CC=0).",
                config.delta_table_name,
            )
            result.delete_success = True

    except Exception as exc:  # noqa: BLE001
        # Genuine error — equivalent to IDCAMS CC > 8.
        # We capture the error and continue, matching: IF LASTCC > 8 THEN SET MAXCC = 0
        logger.warning(
            "DELETE of table '%s' encountered a genuine error (equivalent to "
            "IDCAMS CC > 8).  Continuing as per SET MAXCC = 0 semantics.  "
            "Error: %s",
            config.delta_table_name,
            exc,
            exc_info=True,
        )
        result.delete_error = exc

    return result


