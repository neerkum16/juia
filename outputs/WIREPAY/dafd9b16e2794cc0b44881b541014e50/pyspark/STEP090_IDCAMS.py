def verify_wire_ksds_catalogue_entries(
    spark: SparkSession,
    *,
    input_ksds_database: str = CATALOG_DATABASE_INPUT,
    input_ksds_table: str = CATALOG_TABLE_INPUT,
    extrt_ksds_database: str = CATALOG_DATABASE_EXTRT,
    extrt_ksds_table: str = CATALOG_TABLE_EXTRT,
    raise_on_not_found: bool = True,
) -> DataFrame:
    """
    Replicate the IDCAMS LISTCAT ALL operation for the two wire-processing
    VSAM KSDS datasets.

    This function implements STEP090 of wire_payment_batch.jcl.  On the
    mainframe, IDCAMS is invoked with the following SYSIN control cards::

        LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS)  ALL
        LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS)  ALL

    Because LISTCAT is a pure metadata inspection operation (no data records
    are read or written), the migration equivalent queries the active Spark /
    Hive catalogue for table-level metadata and emits a structured report that
    mirrors the SYSPRINT output produced by the mainframe utility.

    Business rule
    -------------
    Confirm that both WIRE.WORK.INPUT.KSDS (inbound wire transfer records)
    and WIRE.WORK.EXTRT.KSDS (extracted wire records for downstream
    processing) exist in the active catalogue and are properly defined.
    Capture their current state — record counts, storage size, schema,
    partition keys, and timestamps — for operational verification before or
    after a wire-transfer batch run.

    Parameters
    ----------
    spark:
        Active SparkSession.  The session must be configured with access to
        the target data catalogue (Hive Metastore, AWS Glue, Unity Catalog).
    input_ksds_database:
        Catalogue database name for WIRE.WORK.INPUT.KSDS.
        Defaults to ``CATALOG_DATABASE_INPUT`` ("wire_work").
    input_ksds_table:
        Catalogue table name for WIRE.WORK.INPUT.KSDS.
        Defaults to ``CATALOG_TABLE_INPUT`` ("input_ksds").
    extrt_ksds_database:
        Catalogue database name for WIRE.WORK.EXTRT.KSDS.
        Defaults to ``CATALOG_DATABASE_EXTRT`` ("wire_work").
    extrt_ksds_table:
        Catalogue table name for WIRE.WORK.EXTRT.KSDS.
        Defaults to ``CATALOG_TABLE_EXTRT`` ("extrt_ksds").
    raise_on_not_found:
        If ``True`` (default), raise :class:`CatalogueEntryNotFoundError` if
        either dataset is missing — preserving the mainframe behaviour of
        returning condition code 8 when LISTCAT cannot find an entry.
        If ``False``, the missing-entry row is included in the result
        DataFrame with ``return_code=8`` and no exception is raised.

    Returns
    -------
    pyspark.sql.DataFrame
        A two-row DataFrame (one row per KSDS) conforming to
        :data:`LISTCAT_REPORT_SCHEMA`.  Each row contains the full set of
        catalogue attributes collected for that dataset, analogous to the
        IDCAMS LISTCAT ALL SYSPRINT report.

        Schema columns (all catalogue metadata — no data record fields):

        ========================  =========  ====================================
        Column                    Type       Mainframe LISTCAT analogue
        ========================  =========  ====================================
        dataset_name              STRING     Entry name passed to LISTCAT
        object_type               STRING     CLUSTER / DATA / INDEX
        table_database            STRING     Target catalogue database
        table_name                STRING     Target catalogue table
        location                  STRING     Physical path / S3 URI
        provider                  STRING     Storage format (parquet, delta)
        num_files                 LONG       EXTENTS count
        total_size_bytes          LONG       HI-U-RBA (high-used RBA)
        num_rows                  LONG       REC-TOTAL
        num_partitions            LONG       CI/CA partition count
        columns                   STRING     JSON — KEY / FIELDS definitions
        partition_columns         STRING     JSON — KEYRANGES / split keys
        table_properties          STRING     JSON — all TBLPROPERTIES / ICF attrs
        create_time               STRING     CREATION-DATE / CREATION-TIME
        last_modified_time        STRING     LAST-ALTTIME
        catalogue_source          STRING     Catalogue implementation queried
        listcat_timestamp         STRING     Timestamp of this LISTCAT run
        return_code               LONG       0 = success, 8 = not found (CC=8)
        return_message            STRING     Human-readable status message
        ========================  =========  ====================================

    Raises
    ------
    CatalogueEntryNotFoundError
        When ``raise_on_not_found=True`` and a required dataset is absent
        from the catalogue.  Callers implementing JCL conditional logic
        (IF LASTCC EQ 8) should catch this exception.

    Key field mapping
    -----------------
    No mainframe record-layout fields apply — LISTCAT operates on catalogue
    metadata only.  The column constants defined in this module map
    IDCAMS output attributes to their Spark DataFrame equivalents.

    Original SYSIN control cards
    ----------------------------
    ::

        LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS)  ALL
        LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS)  ALL
    """
    run_timestamp: str = _iso_now()
    entries: list[ListcatEntry] = []
    max_return_code: int = 0

    # -----------------------------------------------------------------------
    # Mainframe: LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS) ALL
    # Query the catalogue for the inbound wire transfer KSDS.
    # -----------------------------------------------------------------------
    logger.info(
        "LISTCAT ENTRIES(%s) ALL — querying catalogue for %s.%s",
        DSN_INPUT_KSDS,
        input_ksds_database,
        input_ksds_table,
    )
    try:
        input_entry = _query_spark_catalogue(
            spark,
            dsn=DSN_INPUT_KSDS,
            database=input_ksds_database,
            table=input_ksds_table,
            run_timestamp=run_timestamp,
        )
    except CatalogueEntryNotFoundError as exc:
        if raise_on_not_found:
            logger.error(
                "LISTCAT ENTRIES(%s) ALL — ENTRY NOT FOUND (CC=8): %s",
                DSN_INPUT_KSDS,
                exc,
            )
            raise
        input_entry = _build_not_found_entry(
            DSN_INPUT_KSDS, input_ksds_database, input_ksds_table, run_timestamp, exc
        )

    _emit_sysprint_report(input_entry)
    entries.append(input_entry)
    max_return_code = max(max_return_code, input_entry.return_code)

    # -----------------------------------------------------------------------
    # Mainframe: LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS) ALL
    # Query the catalogue for the extracted wire records KSDS.
    # -----------------------------------------------------------------------
    logger.info(
        "LISTCAT ENTRIES(%s) ALL — querying catalogue for %s.%s",
        DSN_EXTRT_KSDS,
        extrt_ksds_database,
        extrt_ksds_table,
    )
    try:
        extrt_entry = _query_spark_catalogue(
            spark,
            dsn=DSN_EXTRT_KSDS,
            database=extrt_ksds_database,
            table=extrt_ksds_table,
            run_timestamp=run_timestamp,
        )
    except CatalogueEntryNotFoundError as exc:
        if raise_on_not_found:
            logger.error(
                "LISTCAT ENTRIES(%s) ALL — ENTRY NOT FOUND (CC=8): %s",
                DSN_EXTRT_KSDS,
                exc,
            )
            raise
        extrt_entry = _build_not_found_entry(
            DSN_EXTRT_KSDS, extrt_ksds_database, extrt_ksds_table, run_timestamp, exc
        )

    _emit_sysprint_report(extrt_entry)
    entries.append(extrt_entry)
    max_return_code = max(max_return_code, extrt_entry.return_code)

    # -----------------------------------------------------------------------
    # Build the result DataFrame — one row per LISTCAT ENTRIES(...) ALL call
    # This is the structured analogue of the IDCAMS SYSPRINT output.
    # -----------------------------------------------------------------------
    logger.info(
        "STEP090 LISTCAT complete.  Max return code: %d  (%s)",
        max_return_code,
        "SUCCESS" if max_return_code == 0 else "FAILED",
    )

    report_df: DataFrame = spark.createDataFrame(
        [entry.as_row_dict() for entry in entries],
        schema=LISTCAT_REPORT_SCHEMA,
    )

    # -----------------------------------------------------------------------
    # Derive a human-readable summary column — equivalent to the IDCAMS
    # SYSPRINT banner line that leads each entry's printed section.
    # -----------------------------------------------------------------------
    summary_col = (
        F.concat_ws(
            " | ",
            F.col(COL_DATASET_NAME),
            F.concat(F.lit("RC="), F.col(COL_RETURN_CODE).cast(StringType())),
            F.concat(
                F.lit("ROWS="),
                F.when(F.col(COL_NUM_ROWS).isNotNull(), F.col(COL_NUM_ROWS).cast(StringType()))
                .otherwise(F.lit("N/A")),
            ),
            F.concat(
                F.lit("SIZE_BYTES="),
                F.when(
                    F.col(COL_TOTAL_SIZE_BYTES).isNotNull(),
                    F.col(COL_TOTAL_SIZE_BYTES).cast(StringType()),
                ).otherwise(F.lit("N/A")),
            ),
        )
    )

    report_df = report_df.withColumn("listcat_summary", summary_col)

    return report_df


