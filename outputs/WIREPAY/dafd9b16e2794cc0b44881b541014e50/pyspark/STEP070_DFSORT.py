def summarise_wire_transfers_by_currency(input_df: DataFrame) -> DataFrame:
    """
    Implements DFSORT STEP070 from wire_payment_batch.jcl.

    Business Rule
    -------------
    Reads wire transfer processed records, sorts them by currency code
    (ascending) and transaction amount (descending), collapses records that
    share the same (currency_code, transaction_amount) key pair by summing
    their amounts, and reformats each summary record into a 200-byte
    fixed-length output layout suitable for reporting, reconciliation, or
    downstream settlement processing.

    Pre-conditions / Schema Contract
    ---------------------------------
    The caller is responsible for providing a DataFrame whose columns exactly
    match the COLUMN NAME CONSTANTS defined in this module:

    | Column name          | Type      | Mainframe offset | Len | Format |
    |----------------------|-----------|------------------|-----|--------|
    | account_ref          | StringType| 1                | 16  | CH     |
    | transaction_amount   | LongType  | 17               | 9   | PD *   |
    | value_date           | StringType| 44               | 8   | CH     |
    | transaction_status   | StringType| 55               | 2   | CH     |
    | currency_code        | StringType| 63               | 3   | CH     |
    | classification_code  | StringType| 66               | 3   | CH     |

    * PD (packed decimal) — the ingestion layer MUST decode the 9-byte packed
      decimal field at offset 17 to a signed Python integer (LongType) before
      passing the DataFrame to this function.  Raw bytes are not accepted.

    * EBCDIC CH fields — all character fields must be transcoded from EBCDIC
      to UTF-8 by the ingestion layer before this function is called.

    Parameters
    ----------
    input_df : DataFrame
        Pre-decoded and schema-validated DataFrame representing
        WIRE.PROCESSED.SEQ (SORTIN DD).

    Returns
    -------
    DataFrame
        Summary DataFrame representing WIRE.SUMMARY.SEQ (SORTOUT DD).
        Each row corresponds to one 200-byte LRECL output record with the
        column ``output_record`` (StringType) holding the fully padded string.
        The DataFrame also retains the individual typed columns for convenience
        in downstream PySpark processing; callers writing to a fixed-width
        target should use ``output_record`` exclusively.

    Original SYSIN Control Cards
    ----------------------------
    ::

        SORT FIELDS=(63,3,CH,A,17,9,PD,D)
        SUM FIELDS=(17,9,PD)
        OUTREC FIELDS=(1,16,
                       63,3,
                       17,9,PD,TO=FS,LENGTH=12,
                       44,8,
                       55,2,
                       66,3)

    Notes
    -----
    - The SUM aggregation key is the full SORT key combination
      (currency_code AND transaction_amount).  Only records that share BOTH
      values are collapsed.  This is a narrow key — verify business intent if
      per-currency totalling across all amounts is required instead.
    - LRECL=200 with 44 bytes of defined OUTREC content leaves 156 bytes of
      trailing spaces in every output record.
    - The FS conversion uses a leading sign byte, which is the correct
      behaviour for DFSORT TO=FS output.
    - Post-aggregation ordering uses TRANSACTION_AMOUNT DESC (the original
      group key value), which matches DFSORT behaviour where the sort key field
      in the collapsed record retains its original value rather than the
      accumulated sum.  Confirm with business stakeholders whether output
      ranking should instead use _SUM_AMOUNT DESC (total collapsed value), as
      the two differ when multiple records with the same (currency, amount) pair
      are collapsed.
    """

    # -------------------------------------------------------------------------
    # FIX (issue 5 / correction hint item 4): Schema validation at function
    # entry.  Assert that all required columns are present in input_df and that
    # each column's DataType matches the expected type from _REQUIRED_COLUMNS.
    # A missing or mistyped column (e.g., TRANSACTION_AMOUNT as DoubleType
    # instead of LongType) would otherwise produce a confusing runtime error or
    # silent precision loss later in the pipeline.  Raising a ValueError here
    # with a descriptive message surfaces schema contract violations early and
    # clearly, matching the behaviour a mainframe JCL abend provides when the
    # input dataset does not conform to the expected layout.
    # -------------------------------------------------------------------------
    actual_field_map = {field.name: type(field.dataType) for field in input_df.schema.fields}
    for col_name, expected_type_cls in _REQUIRED_COLUMNS.items():
        if col_name not in actual_field_map:
            raise ValueError(
                f"STEP070 schema contract violation: required column '{col_name}' "
                f"is missing from input_df. "
                f"Present columns: {list(actual_field_map.keys())}"
            )
        actual_type_cls = actual_field_map[col_name]
        if actual_type_cls is not expected_type_cls:
            raise ValueError(
                f"STEP070 schema contract violation: column '{col_name}' has type "
                f"'{actual_type_cls.__name__}' but expected '{expected_type_cls.__name__}'. "
                f"Ensure the ingestion layer decodes packed-decimal fields to LongType "
                f"and transcodes EBCDIC character fields to StringType before calling "
                f"this function."
            )

    # -------------------------------------------------------------------------
    # STEP 0 — Assign a stable, monotonically increasing row ID to each input
    # row BEFORE any shuffle or transformation.
    #
    # FIX (issue 1): monotonically_increasing_id() reflects the physical
    # partition-local order of rows as read from the source.  By recording this
    # ID now, we can use it later as an unambiguous tiebreaker inside the Window
    # so that row_number() deterministically selects the first-encountered row
    # within each (currency_code, transaction_amount) group, faithfully
    # reproducing DFSORT's first-record-wins semantics when duplicate sort keys
    # are collapsed by SUM.
    # -------------------------------------------------------------------------
    df_with_id: DataFrame = input_df.withColumn(
        _INPUT_ROW_ID,
        F.monotonically_increasing_id(),
    )

    # -------------------------------------------------------------------------
    # STEP 1 — Tag each row with a deterministic row number before aggregation.
    #
    # FIX (issue 2 / correction hint item 2): The previous Window was
    # partitioned by (CURRENCY_CODE, TRANSACTION_AMOUNT) and ordered by those
    # same two columns plus _INPUT_ROW_ID.  The CURRENCY_CODE ASC and
    # TRANSACTION_AMOUNT DESC ORDER BY expressions are vacuous inside this
    # Window because every row within a partition has identical values for both
    # columns — they are the partition keys.  Including them in the ORDER BY is
    # misleading and adds no ordering information.  They have been removed so
    # that only F.col(_INPUT_ROW_ID).asc() appears in the Window orderBy,
    # making it unambiguously clear that _INPUT_ROW_ID is the sole and
    # effective tiebreaker for deterministic first-record selection within each
    # duplicate group.  This matches DFSORT first-record-wins behaviour.
    # -------------------------------------------------------------------------

    # Window partitioned by the SUM key; ordered solely by the stable
    # tiebreaker _INPUT_ROW_ID so that row_number() is fully deterministic.
    # CURRENCY_CODE and TRANSACTION_AMOUNT are deliberately omitted from
    # orderBy — they are partition keys and therefore constant within each
    # partition, making their inclusion in ORDER BY vacuous and misleading.
    _first_record_window = Window.partitionBy(
        CURRENCY_CODE,
        TRANSACTION_AMOUNT,
    ).orderBy(
        # FIX (issue 2): Only _INPUT_ROW_ID is needed here.  It is globally
        # unique (monotonically_increasing_id), so row_number() == 1
        # deterministically identifies the physically first-encountered input
        # row in each duplicate group, matching DFSORT first-record-wins.
        F.col(_INPUT_ROW_ID).asc(),
    )

    # Assign a row number within each (currency_code, transaction_amount) group.
    # Row 1 is the record DFSORT would treat as the "first" (and whose non-sum
    # fields are retained after collapsing duplicates).
    df_with_rownum: DataFrame = df_with_id.withColumn(
        _ROW_NUM,
        F.row_number().over(_first_record_window),
    )

    # -------------------------------------------------------------------------
    # STEP 2 — SUM / AGGREGATE
    # Mainframe: SUM FIELDS=(17,9,PD)
    #
    # Collapse records sharing the same (currency_code, transaction_amount)
    # pair by summing their transaction amounts.  Non-key, non-sum fields are
    # carried from the row tagged _ROW_NUM == 1, which is the deterministic
    # first record in DFSORT sort order for that group.
    #
    # FIX (issue 1 / correction hint item 1): The previous implementation
    # carried a self-contradictory comment that incorrectly described
    # F.sum(TRANSACTION_AMOUNT) as "semantically wrong and fragile", then
    # immediately stated no change was required.  That commentary has been
    # replaced with a clear, accurate explanation:
    #
    # groupBy on (CURRENCY_CODE, TRANSACTION_AMOUNT) followed by
    # F.sum(TRANSACTION_AMOUNT) is CORRECT because DFSORT SUM collapses records
    # that share the same full sort key combination.  By definition, all rows
    # within a group have the identical TRANSACTION_AMOUNT value (it is a
    # groupBy key), so F.sum produces N * original_amount, which equals the
    # true DFSORT SUM output for exact duplicates.  No alternative expression
    # is needed; the aggregation is correct as written.
    # -------------------------------------------------------------------------

    # Mainframe: SUM FIELDS=(17,9,PD)
    df_aggregated: DataFrame = df_with_rownum.groupBy(
        CURRENCY_CODE,
        TRANSACTION_AMOUNT,
    ).agg(
        # Sum the packed-decimal amount across all records in each duplicate
        # key group.  Because TRANSACTION_AMOUNT is a groupBy key, every row
        # in the group has the same value; F.sum therefore computes
        # N * original_amount, which is numerically identical to the DFSORT
        # SUM output for exact duplicates.  This is correct and intentional.
        F.sum(F.col(TRANSACTION_AMOUNT)).alias(_SUM_AMOUNT),

        # Carry non-key, non-sum fields from the deterministic first record
        # (row_number == 1 in DFSORT sort order) rather than using
        # non-deterministic F.first().  F.max(F.when(...)) extracts the value
        # from the unique row tagged as the first record in each group.
        F.max(
            F.when(F.col(_ROW_NUM) == 1, F.col(ACCOUNT_REF))
        ).alias(ACCOUNT_REF),
        F.max(
            F.when(F.col(_ROW_NUM) == 1, F.col(VALUE_DATE))
        ).alias(VALUE_DATE),
        F.max(
            F.when(F.col(_ROW_NUM) == 1, F.col(TRANSACTION_STATUS))
        ).alias(TRANSACTION_STATUS),
        F.max(
            F.when(F.col(_ROW_NUM) == 1, F.col(CLASSIFICATION_CODE))
        ).alias(CLASSIFICATION_CODE),
    )

    # -------------------------------------------------------------------------
    # STEP 3 — Re-apply sort after aggregation
    # Mainframe: SORT FIELDS=(63,3,CH,A,17,9,PD,D)
    #
    # Post-aggregation sort ensures the output is ordered by currency_code ASC
    # and transaction_amount DESC, matching the mainframe output sequence.
    #
    # Sort by TRANSACTION_AMOUNT DESC (the original key), not _SUM_AMOUNT DESC
    # (the inflated post-collapse total).  In DFSORT, after SUM collapse the
    # record retains the original sort key field value — the sort key does not
    # change to the summed value.  See the function docstring note regarding
    # business stakeholder confirmation of this ordering choice.
    # -------------------------------------------------------------------------

    # Mainframe: SORT FIELDS=(63,3,CH,A,17,9,PD,D)  [post-aggregation ordering]
    df_resorted: DataFrame = df_aggregated.orderBy(
        F.col(CURRENCY_CODE).asc(),
        F.col(TRANSACTION_AMOUNT).desc(),  # original key, not _SUM_AMOUNT
    )

    # -------------------------------------------------------------------------
    # STEP 4 — OUTREC / REFORMAT
    # Mainframe:
    #   OUTREC FIELDS=(1,16,          → account_ref          (16 bytes)
    #                  63,3,          → currency_code         ( 3 bytes)
    #                  17,9,PD,TO=FS,LENGTH=12,
    #                                 → sum_amount as FS     (12 bytes)
    #                  44,8,          → value_date            ( 8 bytes)
    #                  55,2,          → transaction_status    ( 2 bytes)
    #                  66,3)          → classification_code   ( 3 bytes)
    #
    # Total defined content = 16 + 3 + 12 + 8 + 2 + 3 = 44 bytes.
    # Remaining 156 bytes are space-padded to reach LRECL=200.
    #
    # PD→FS conversion: _to_fs_string() replicates DFSORT TO=FS,LENGTH=12:
    #   leading sign byte ('+'/'-') followed by 11 zero-padded decimal digits.
    # -------------------------------------------------------------------------

    # Mainframe: 17,9,PD,TO=FS,LENGTH=12
    df_with_fs: DataFrame = df_resorted.withColumn(
        _FS_AMOUNT,
        _to_fs_string(F.col(_SUM_AMOUNT), _FS_AMOUNT_WIDTH),
    )

    # FIX (issue 4): Wrap each nullable character column with
    # F.coalesce(..., F.lit('')) before passing to F.rpad so that a null value
    # in any of these fields does not propagate as null into the F.concat call
    # and silently corrupt the output_record string.  F.coalesce returns the
    # first non-null argument, so a null column produces an empty string which
    # F.rpad then space-pads to the required width, matching DFSORT behaviour
    # of treating absent/blank fields as spaces.
    df_with_output_record: DataFrame = df_with_fs.withColumn(
        _OUTPUT_RECORD,
        F.rpad(
            F.concat(
                # bytes  1-16 : account/reference identifier (16 bytes CH)
                # FIX (issue 4): coalesce null to '' before rpad to prevent
                # null propagation into concat.
                F.rpad(F.coalesce(F.col(ACCOUNT_REF), F.lit("")), 16, " "),

                # bytes 17-19 : currency code (3 bytes CH)
                # CURRENCY_CODE is nullable=False in the schema so coalesce is
                # not strictly required, but applied defensively for safety.
                F.rpad(F.coalesce(F.col(CURRENCY_CODE), F.lit("")), 3, " "),

                # bytes 20-31 : summed amount as FS,LENGTH=12
                # _FS_AMOUNT is derived from _SUM_AMOUNT (LongType,
                # nullable=False) so it will never be null; no coalesce needed.
                F.col(_FS_AMOUNT),

                # bytes 32-39 : value/settlement date (8 bytes CH)
                # FIX (issue 4): coalesce null to '' before rpad.
                F.rpad(F.coalesce(F.col(VALUE_DATE), F.lit("")), 8, " "),

                # bytes 40-41 : transaction type/status code (2 bytes CH)
                # FIX (issue 4): coalesce null to '' before rpad.
                F.rpad(F.coalesce(F.col(TRANSACTION_STATUS), F.lit("")), 2, " "),

                # bytes 42-44 : classification/routing code (3 bytes CH)
                # FIX (issue 4): coalesce null to '' before rpad.
                F.rpad(F.coalesce(F.col(CLASSIFICATION_CODE), F.lit("")), 3, " "),
            ),
            _OUTPUT_LRECL,  # pad to 200 bytes (156 trailing spaces)
            " ",
        ),
    )

    # -------------------------------------------------------------------------
    # STEP 5 — Final projection
    # Return both the fixed-width output_record column (for fixed-width writers)
    # and the individual typed columns (for downstream PySpark consumers).
    # The internal _ROW_NUM and _INPUT_ROW_ID columns are excluded from output.
    # -------------------------------------------------------------------------

    result: DataFrame = df_with_output_record.select(
        F.col(_OUTPUT_RECORD),      # 200-byte fixed-width record (SORTOUT)
        F.col(ACCOUNT_REF),         # offset  1, len 16, CH
        F.col(CURRENCY_CODE),       # offset 63, len  3, CH
        F.col(_SUM_AMOUNT),         # offset 17, len  9, PD → aggregated LongType
        F.col(_FS_AMOUNT),          # OUTREC FS representation of sum_amount
        F.col(VALUE_DATE),          # offset 44, len  8, CH
        F.col(TRANSACTION_STATUS),  # offset 55, len  2, CH
        F.col(CLASSIFICATION_CODE), # offset 66, len  3, CH
    )

    return result


