def build_input_schema() -> StructType:
    """
    Returns the expected StructType schema for the SORTIN dataset
    (WIRE.PROCESSED.SEQ) after ingestion and PD/EBCDIC decoding.

    This schema corresponds to the mainframe record layout described in the
    STEP070 field mapping table.  Pass this schema to the Spark reader to
    enforce type safety at load time.

    Returns
    -------
    StructType
        Schema definition for the decoded wire processed sequential file.
    """
    return StructType(
        [
            # offset  1, len 16, CH
            StructField(ACCOUNT_REF, StringType(), nullable=True),
            # offset 17, len  9, PD — decoded to signed integer
            StructField(TRANSACTION_AMOUNT, LongType(), nullable=False),
            # offset 44, len  8, CH
            StructField(VALUE_DATE, StringType(), nullable=True),
            # offset 55, len  2, CH
            StructField(TRANSACTION_STATUS, StringType(), nullable=True),
            # offset 63, len  3, CH
            StructField(CURRENCY_CODE, StringType(), nullable=False),
            # offset 66, len  3, CH
            StructField(CLASSIFICATION_CODE, StringType(), nullable=True),
        ]
    )


