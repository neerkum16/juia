# =============================================================================
# HELPER — packed-decimal integer  →  fixed-length signed numeric string
# =============================================================================

def _to_fs_string(amount_col: F.Column, width: int) -> F.Column:
    """
    Convert a decoded packed-decimal integer column to a fixed-length signed
    numeric string that replicates DFSORT's TO=FS,LENGTH=<width> behaviour.

    DFSORT TO=FS rules reproduced here:
      - Positive values (>= 0): leading '+' sign followed by zero-padded
        (width-1) digits → total width characters.
      - Negative values        : leading '-' sign followed by zero-padded
        (width-1) digits → total width characters.
      - The result is exactly <width> characters wide.

    FIX (issue 3): Added an overflow guard via F.substring so that if the
    absolute digit count of the amount exceeds digit_width (11 digits for
    LENGTH=12), the digit string is truncated to exactly digit_width
    characters before prepending the sign.  Without this guard, a summed
    amount with more than 11 digits would produce a field wider than 12
    characters and corrupt the fixed-width record layout.  DFSORT raises an
    error in this case; here we truncate consistently and the caller is
    responsible for ensuring amounts stay within range.

    Args:
        amount_col: Column expression holding the decoded integer amount.
        width:      Total output field width in characters (including sign byte).

    Returns:
        Column expression producing a fixed-width signed numeric string.
    """
    digit_width: int = width - 1  # one character reserved for sign

    # FIX (issue 4 / correction hint item 3): Use F.abs(amount_col) for the
    # positive_str digit portion to eliminate the latent defect where casting a
    # negative amount directly to StringType produces a string like '-123' which
    # would embed a minus sign inside the digit field if the branch logic were
    # ever modified.  Previously positive_str used F.cast(amount_col, ...) which
    # for negative values yields e.g. lpad('-123', 11, '0') = '0000000-123' —
    # malformed.  Although the WHEN predicate (amount_col < 0) ensures this
    # branch is never reached for negative values in the current code, always
    # using F.abs makes the helper intrinsically safe regardless of how the
    # conditional logic might evolve.  The negative_str branch already used
    # F.abs correctly; now positive_str matches that pattern.
    positive_str = F.substring(
        F.lpad(F.cast(F.abs(amount_col), StringType()), digit_width, "0"),
        1,
        digit_width,
    )
    negative_str = F.substring(
        F.lpad(F.cast(F.abs(amount_col), StringType()), digit_width, "0"),
        1,
        digit_width,
    )

    return F.when(
        amount_col < 0,
        F.concat(F.lit("-"), negative_str),
    ).otherwise(
        F.concat(F.lit("+"), positive_str),
    )


