def split_wire_transfers_by_value(
    input_df: DataFrame,
) -> Dict[str, DataFrame]:
    """Sort wire transfer records by amount and split into high-value / low-value partitions.

    Business Rule:
        Implements DFSORT STEP040 from wire_payment_batch.jcl.  All records
        from WIRE.WORK.EXTRT.SEQ are sorted in descending order of the wire
        transfer monetary amount (packed-decimal field, mainframe bytes 17-25).
        The sorted stream is then divided into two mutually exclusive output
        files using OUTFIL INCLUDE conditions:

            HIGHVAL (WIRE.WORK.HIGH.SEQ)
                amount_pd > 1,000,000
                Large / high-risk wire transfers for specialised downstream
                processing or regulatory review.

            LOWVAL  (WIRE.WORK.LOW.SEQ)
                amount_pd <= 1,000,000
                Standard wire transfers for normal downstream processing.

        Invariant:
            len(HIGH) + len(LOW)  ==  len(input)   (no record is lost or
            duplicated — the conditions are exhaustive and mutually exclusive).

    Parameters:
        input_df (DataFrame):
            The input DataFrame representing WIRE.WORK.EXTRT.SEQ records.

            Expected schema (minimum required columns):

            +--------------------+-----------+---------------------------------------+
            | Column             | Type      | Notes                                 |
            +--------------------+-----------+---------------------------------------+
            | amount_pd          | LongType  | Decoded PD amount (mainframe off 17,  |
            |                    |           | len 9).  Must be pre-decoded from raw |
            |                    |           | Packed Decimal bytes before calling   |
            |                    |           | this function.  Negative values are   |
            |                    |           | valid (sign nibble 0xD) and will be   |
            |                    |           | routed to LOWVAL (≤ 1,000,000).       |
            +--------------------+-----------+---------------------------------------+
            | (all other cols)   | any       | Passed through unchanged; records are |
            |                    |           | written as-is (FB LRECL=200 equivalent|
            |                    |           | — no reformatting).                   |
            +--------------------+-----------+---------------------------------------+

    Returns:
        dict[str, DataFrame] with exactly two keys:

            "HIGH"  →  DataFrame of records where amount_pd > 1,000,000,
                        sorted descending by amount_pd.
                        Corresponds to WIRE.WORK.HIGH.SEQ (DD: HIGHVAL).

            "LOW"   →  DataFrame of records where amount_pd <= 1,000,000,
                        sorted descending by amount_pd.
                        Corresponds to WIRE.WORK.LOW.SEQ (DD: LOWVAL).

    Key Field Mapping (mainframe → DataFrame column):
        Mainframe Offset  Length  Format  Column Name   Description
        ----------------  ------  ------  ------------  ----------------------------
        17 (1-based)      9       PD      amount_pd     Wire transfer monetary amount
                                                        (decoded to signed integer)

    Original SYSIN control cards (verbatim):
        SORT FIELDS=(17,9,PD,D)
        OUTFIL FNAMES=HIGHVAL,
               INCLUDE=(17,9,PD,GT,+1000000)
        OUTFIL FNAMES=LOWVAL,
               INCLUDE=(17,9,PD,LE,+1000000)

    Notes:
        - SORT ORDER PRESERVATION: PySpark write operations do not guarantee
          physical row order across multiple output partitions.  If the
          downstream consumer requires strictly ordered input (as a mainframe
          DFSORT output would be), write each DataFrame with .coalesce(1) and
          document that constraint.  See the __main__ block for an example.
        - COMPLETENESS CHECK: After writing, validate that
          high_count + low_count == input_count.  A helper
          validate_partition_completeness() is provided below.
        - NEGATIVE AMOUNTS: PD sign nibble 0xD produces a negative decoded
          integer.  The SYSIN compares to +1,000,000 (explicit positive), so
          negative amounts will always satisfy the LE condition and be routed
          to LOWVAL — consistent with mainframe behaviour.
    """

    # ------------------------------------------------------------------
    # STEP 1 — Sort all records by amount_pd descending
    # Mainframe: SORT FIELDS=(17,9,PD,D)
    #
    # NOTE: amount_pd must be the *decoded* integer value (LongType) at this
    # point.  Raw PD bytes would sort lexicographically, not numerically.
    # ------------------------------------------------------------------
    sorted_df: DataFrame = input_df.orderBy(F.col(AMOUNT_PD).desc())

    # ------------------------------------------------------------------
    # STEP 2 — OUTFIL HIGHVAL
    # Mainframe: OUTFIL FNAMES=HIGHVAL, INCLUDE=(17,9,PD,GT,+1000000)
    #
    # Retain only records where the decoded amount exceeds $1,000,000.
    # These are large / high-risk wire transfers (WIRE.WORK.HIGH.SEQ).
    # ------------------------------------------------------------------
    df_high: DataFrame = sorted_df.filter(
        F.col(AMOUNT_PD) > _HIGH_VALUE_THRESHOLD
    )

    # ------------------------------------------------------------------
    # STEP 3 — OUTFIL LOWVAL
    # Mainframe: OUTFIL FNAMES=LOWVAL, INCLUDE=(17,9,PD,LE,+1000000)
    #
    # Retain only records where the decoded amount is <= $1,000,000.
    # These are standard wire transfers (WIRE.WORK.LOW.SEQ).
    # The two INCLUDE conditions are exhaustive and mutually exclusive,
    # guaranteeing every input record appears in exactly one output file.
    # ------------------------------------------------------------------
    df_low: DataFrame = sorted_df.filter(
        F.col(AMOUNT_PD) <= _HIGH_VALUE_THRESHOLD
    )

    return {
        _PARTITION_HIGH: df_high,
        _PARTITION_LOW: df_low,
    }


