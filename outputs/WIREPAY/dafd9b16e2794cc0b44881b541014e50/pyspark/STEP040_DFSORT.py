def validate_partition_completeness(
    input_df: DataFrame,
    result: Dict[str, DataFrame],
) -> bool:
    """Verify that HIGH count + LOW count equals the total input record count.

    Implements the completeness invariant described in MIGRATION NOTE 5:
        "HIGH count + LOW count must equal SORTIN count."

    Args:
        input_df: The original input DataFrame (before splitting).
        result:   The dict returned by split_wire_transfers_by_value().

    Returns:
        True if the invariant holds; raises AssertionError otherwise.

    Raises:
        AssertionError: If record counts do not reconcile.
    """
    total_input: int = input_df.count()
    high_count: int = result[_PARTITION_HIGH].count()
    low_count: int = result[_PARTITION_LOW].count()
    combined: int = high_count + low_count

    assert combined == total_input, (
        f"Partition completeness check FAILED: "
        f"HIGH({high_count}) + LOW({low_count}) = {combined} "
        f"!= SORTIN({total_input}).  "
        f"Delta = {total_input - combined} record(s) unaccounted for."
    )

    print(
        f"[VALIDATE] Partition completeness OK — "
        f"SORTIN={total_input:,} | "
        f"HIGHVAL={high_count:,} | "
        f"LOWVAL={low_count:,}"
    )
    return True


