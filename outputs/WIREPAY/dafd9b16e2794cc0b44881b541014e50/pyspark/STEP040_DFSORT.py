# =============================================================================
# PACKED-DECIMAL DECODE UTILITY
# Provided here as a reference implementation and to support unit testing or
# ad-hoc ingestion pipelines.  In production, PD decoding should occur in the
# Bronze / raw-ingestion layer, before DataFrames reach this function.
# =============================================================================

def decode_packed_decimal(raw_bytes: bytes) -> int:
    """Decode a mainframe Packed Decimal (PD) byte string to a Python integer.

    Packed Decimal encoding:
      - Each byte holds two decimal digits as 4-bit nibbles (BCD).
      - The *last* half-byte (low nibble of the final byte) is the sign:
            0xC  →  positive  (preferred positive)
            0xF  →  positive  (unsigned / zone)
            0xA  →  positive  (alternate)
            0xE  →  positive  (alternate)
            0xD  →  negative
      - A 9-byte PD field holds up to 17 significant digits.

    Args:
        raw_bytes: Raw bytes extracted from the mainframe record at the
                   correct offset and length (e.g. record[16:25] for a
                   1-based offset-17, length-9 field).

    Returns:
        Signed Python integer representing the decoded value.

    Raises:
        ValueError: If the sign nibble is not a recognised BCD sign code,
                    or if any digit nibble exceeds 9.
    """
    if not raw_bytes:
        raise ValueError("Cannot decode an empty byte string as Packed Decimal.")

    hex_str: str = raw_bytes.hex()  # e.g. b'\x00\x01\x23\x45\x67\x89\x00\x00\x1c' → '000123456789000001c'

    # All nibbles except the last form the digit string
    digit_nibbles: str = hex_str[:-1]
    sign_nibble: str = hex_str[-1].upper()

    # Validate and parse digit nibbles
    for nibble in digit_nibbles:
        if nibble not in "0123456789":
            raise ValueError(
                f"Invalid BCD digit nibble '{nibble}' in packed decimal field: {raw_bytes.hex()}"
            )

    integer_value: int = int(digit_nibbles) if digit_nibbles else 0

    # Apply sign
    positive_signs = {"C", "F", "A", "E"}
    negative_signs = {"D"}

    if sign_nibble in positive_signs:
        return integer_value
    elif sign_nibble in negative_signs:
        return -integer_value
    else:
        raise ValueError(
            f"Unrecognised Packed Decimal sign nibble '0x{sign_nibble}' "
            f"in field: {raw_bytes.hex()}"
        )


