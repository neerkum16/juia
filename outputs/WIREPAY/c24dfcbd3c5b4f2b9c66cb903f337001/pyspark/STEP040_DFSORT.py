    #      OUTFIL FNAMES=HIGHVAL,
    #             INCLUDE=(17,9,PD,GT,+1000000)   ← strictly greater than
    #      OUTFIL FNAMES=LOWVAL,
    #             INCLUDE=(17,9,PD,LE,+1000000)   ← less than or equal to
    #
    #    The two conditions are mutually exclusive (GT vs LE) and
    #    collectively exhaustive for all non-null amounts, so every record
    #    is written to exactly one output file — mirroring DFSORT behaviour.
    #
    #    Boundary value: amount == 1,000,000 satisfies LE, so it is routed
    #    to LOWVAL (not HIGHVAL).  This matches the GT / LE split exactly.
    # ------------------------------------------------------------------

    # Mainframe: OUTFIL FNAMES=HIGHVAL, INCLUDE=(17,9,PD,GT,+1000000)
    # TRANSACTION_AMOUNT column is pre-decoded from PD — see note above.
    df_high = df_sorted.filter(F.col(TRANSACTION_AMOUNT) > HIGH_VALUE_THRESHOLD)

    # Mainframe: OUTFIL FNAMES=LOWVAL, INCLUDE=(17,9,PD,LE,+1000000)
    # TRANSACTION_AMOUNT column is pre-decoded from PD — see note above.
    df_low = df_sorted.filter(F.col(TRANSACTION_AMOUNT) <= HIGH_VALUE_THRESHOLD)

    logger.info(
        "STEP040 — Split applied: HIGH (amount > %d) → WIRE.WORK.HIGH.SEQ; "
        "LOW  (amount <= %d) → WIRE.WORK.LOW.SEQ.",
        HIGH_VALUE_THRESHOLD,
        HIGH_VALUE_THRESHOLD,
    )

    return {
        "HIGH": df_high,
        "LOW": df_low,
    }


