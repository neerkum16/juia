def read_wire_extract(
    spark: SparkSession,
    input_path: str,
    record_length: int = 200,
    pd_field_offset_0based: int = 16,  # 0-based → mainframe offset 17 (1-based)
    pd_field_length: int = 9,
) -> DataFrame:
    """Load WIRE.WORK.EXTRT.SEQ (FB LRECL=200) and decode the Packed Decimal
    transaction amount field into the `transaction_amount` column.

    This loader handles the PD-decoding pre-requisite described in
    split_wire_transfers_by_value().  It is provided as a reference
    implementation; in production you may already have the data in Parquet
    or another columnar format with PD already decoded.

    The function reads the input as raw binary lines, extracts the 9-byte PD
    slice at the correct offset, decodes it using _pd_decoder_udf, and
    attaches it as a LongType column.  The full 200-byte record is retained
    in `raw_record` (as a string) so that output files can reproduce the
    original fixed-width payload unchanged.

    Args:
        spark            : Active SparkSession.
        input_path       : Path to the input flat file (local, HDFS, S3, etc.).
        record_length    : Fixed logical record length in bytes (LRECL=200).
        pd_field_offset_0based: 0-based byte offset of the PD field (default 16,
                          which is mainframe 1-based offset 17).
        pd_field_length  : Length in bytes of the PD field (default 9).

    Returns:
        DataFrame with columns:
            raw_record         (StringType) — full 200-byte record as a string
            pd_amount_bytes    (BinaryType) — raw PD bytes (diagnostic; may be
                               dropped after validation)
            transaction_amount (LongType)   — decoded signed integer amount
    """
    logger.info(
        "read_wire_extract: loading '%s' (LRECL=%d, PD offset=%d len=%d)",
        input_path,
        record_length,
        pd_field_offset_0based + 1,  # log as 1-based for mainframe readability
        pd_field_length,
    )

    # Read raw binary records — one fixed-width line per wire transfer record.
    # 'binaryFile' format gives us the raw bytes without encoding assumptions.
    raw_df = (
        spark.read.format("binaryFile")
        .option("pathGlobFilter", "*")
        .load(input_path)
        .select(F.col("content").alias("file_content"))
    )

    # Explode the file content into individual fixed-width records.
    # Each record is `record_length` bytes long.
    # We use a UDF to split the binary blob into a list of fixed-width chunks.
    from pyspark.sql.types import ArrayType

    @F.udf(ArrayType(BinaryType()))
    def split_fixed_records(content: bytes) -> list[bytes] | None:
        if content is None:
            return None
        chunks = [
            content[i : i + record_length]
            for i in range(0, len(content), record_length)
            if len(content[i : i + record_length]) == record_length
        ]
        return chunks if chunks else None

    records_df = (
        raw_df.select(F.explode(split_fixed_records(F.col("file_content"))).alias("record_bytes"))
        .filter(F.col("record_bytes").isNotNull())
    )

    # Extract the PD field slice as binary, decode the full record as a string.
    pd_end = pd_field_offset_0based + pd_field_length

    decoded_df = records_df.select(
        # Retain full record as a string (Latin-1 / ISO-8859-1 preserves all
        # 256 byte values losslessly when the target is a string column; use
        # your organisation's transcoding approach for EBCDIC if required).
        F.col("record_bytes").cast(StringType()).alias(RAW_RECORD),
        # Extract the raw PD bytes for decoding
        F.expr(
            f"slice(record_bytes, {pd_field_offset_0based + 1}, {pd_field_length})"
        ).alias("pd_amount_bytes"),
    )

    # Apply the Packed Decimal decoder UDF.
    # NOTE: After this step, `transaction_amount` is a signed LongType integer.
    # The raw `pd_amount_bytes` column is retained for auditability.
    result_df = decoded_df.withColumn(
        TRANSACTION_AMOUNT, _pd_decoder_udf(F.col("pd_amount_bytes"))
    )

    logger.info(
        "read_wire_extract: schema after PD decode — %s",
        result_df.schema.simpleString(),
    )
    return result_df


