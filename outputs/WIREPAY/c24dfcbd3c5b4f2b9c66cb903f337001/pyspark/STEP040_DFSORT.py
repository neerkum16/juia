def decode_packed_decimal(pd_bytes: bytes) -> int:
    """Decode a mainframe Packed Decimal (BCD) byte string into a Python int.

    Packed Decimal encoding rules:
      • Each byte holds two decimal digits (one per nibble).
      • The low nibble of the LAST byte is the sign:
          0x0C → positive  (+)
          0x0D → negative  (-)
          0x0F → unsigned  (treated as positive)
          Any other value is treated as positive per IBM convention.
      • All other nibbles are decimal digits 0–9.

    Args:
        pd_bytes: Raw bytes extracted from the mainframe record at the
                  packed decimal field position.

    Returns:
        Signed Python integer representing the decoded value.

    Raises:
        ValueError: If any digit nibble is outside 0–9.
    """
    if not pd_bytes:
        raise ValueError("decode_packed_decimal received empty bytes")

    digits: list[int] = []
    for byte in pd_bytes:
        high_nibble = (byte >> 4) & 0x0F
        low_nibble = byte & 0x0F
        digits.append(high_nibble)
        digits.append(low_nibble)

    # Last nibble is the sign indicator, not a digit
    sign_nibble = digits.pop()
    negative = sign_nibble == 0x0D

    for pos, digit in enumerate(digits):
        if digit > 9:
            raise ValueError(
                f"Invalid packed decimal digit {digit:#x} at nibble position {pos}"
            )

    value = int("".join(str(d) for d in digits))
    return -value if negative else value


def _make_pd_decoder_udf():
    """Return a PySpark UDF that decodes a BinaryType column of Packed Decimal
    bytes into a LongType signed integer.

    The UDF is created once and reused; callers should cache the returned
    object rather than invoking this factory repeatedly.
    """
    import pyspark.sql.functions as _F
    from pyspark.sql.types import LongType as _LongType

    def _udf_impl(pd_bytes: bytes) -> int | None:
        if pd_bytes is None:
            return None
        try:
            return decode_packed_decimal(bytes(pd_bytes))
        except (ValueError, TypeError) as exc:
            # Surface corrupt records as NULL so they can be quarantined
            # rather than crashing the job.  Log the error in the driver.
            logger.warning("PD decode error: %s", exc)
            return None

    return _F.udf(_udf_impl, _LongType())


