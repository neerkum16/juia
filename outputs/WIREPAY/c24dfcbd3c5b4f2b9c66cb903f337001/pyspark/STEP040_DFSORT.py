def split_wire_transfers_by_value(
    input_df: DataFrame,
) -> Dict[str, DataFrame]:
    """Sort wire transfer records by descending transaction amount and split
    them into high-value and low-value output datasets.

    This function is the direct PySpark equivalent of the following DFSORT
    SYSIN control cards (sourced from SYS2.CNTL(WIRESPL)):

    .. code-block:: text

        SORT FIELDS=(17,9,PD,D)
        OUTFIL FNAMES=HIGHVAL,
               INCLUDE=(17,9,PD,GT,+1000000)
        OUTFIL FNAMES=LOWVAL,
               INCLUDE=(17,9,PD,LE,+1000000)

    Business Rule:
        Reads WIRE.WORK.EXTRT.SEQ, sorts all records in descending order by
        the Packed Decimal transaction amount at offset 17 (9 bytes), then
        routes:
          • Records with amount  > 1,000,000 → WIRE.WORK.HIGH.SEQ (high-risk)
          • Records with amount <= 1,000,000 → WIRE.WORK.LOW.SEQ  (standard)

        Both outputs are collectively exhaustive and mutually exclusive for
        all non-null amounts.  Both outputs preserve the descending sort order.

    Parameters:
        input_df (DataFrame):
            Input DataFrame representing WIRE.WORK.EXTRT.SEQ.  Expected schema:

            ┌─────────────────────┬──────────┬──────────────────────────────────────────┐
            │ Column              │ Type     │ Notes                                    │
            ├─────────────────────┼──────────┼──────────────────────────────────────────┤
            │ transaction_amount  │ LongType │ Pre-decoded from PD (offset 17, len 9).  │
            │                     │          │ Must be a signed integer, NOT raw bytes. │
            │ raw_record          │ StringType│ Full 200-byte record payload (LRECL=200).│
            │ (any other cols)    │ any      │ Passed through unchanged to both outputs.│
            └─────────────────────┴──────────┴──────────────────────────────────────────┘

            IMPORTANT — Packed Decimal pre-requisite:
                The `transaction_amount` column MUST already hold the decoded
                integer value before this function is called.  Use
                read_wire_extract() (below) or your own equivalent loader that
                applies _pd_decoder_udf to the raw binary PD bytes.

    Returns:
        dict[str, DataFrame]: A dictionary with exactly two keys:

            "HIGH" → DataFrame equivalent to WIRE.WORK.HIGH.SEQ
                     Contains records where transaction_amount > 1,000,000.
                     Sorted descending by transaction_amount.

            "LOW"  → DataFrame equivalent to WIRE.WORK.LOW.SEQ
                     Contains records where transaction_amount <= 1,000,000
                     (including zero and negative amounts — see Migration
                     Note 4 regarding reversals/credits).
                     Sorted descending by transaction_amount.

    Key Field Mapping (mainframe layout → PySpark column):
        ┌─────────┬────────┬────────┬─────────────────────┬────────────────────────────┐
        │ Offset  │ Length │ Format │ Column Name          │ Role                       │
        │ (1-based│ (bytes)│        │ (Python constant)    │                            │
        ├─────────┼────────┼────────┼─────────────────────┼────────────────────────────┤
        │   17    │   9    │  PD    │ TRANSACTION_AMOUNT   │ Sort key + split criterion │
        └─────────┴────────┴────────┴─────────────────────┴────────────────────────────┘

    Original SYSIN (verbatim from SYS2.CNTL(WIRESPL)):
        SORT FIELDS=(17,9,PD,D)
        OUTFIL FNAMES=HIGHVAL,
               INCLUDE=(17,9,PD,GT,+1000000)
        OUTFIL FNAMES=LOWVAL,
               INCLUDE=(17,9,PD,LE,+1000000)

    Migration Notes:
        • Negative amounts (e.g. reversals) satisfy LE +1,000,000 and always
          route to LOWVAL.  Validate this behaviour against business rules for
          your organisation.
        • NULL transaction_amount values are excluded from both outputs and
          written to neither file.  Add a separate quarantine sink if needed.
        • Both output files are FB LRECL=200; no column projection or record
          reformatting is applied — all columns from input_df are preserved.
        • Sort order is applied once before splitting so both child DataFrames
          inherit the same descending order, mirroring DFSORT behaviour where
          OUTFIL consumers operate on the already-sorted stream.
    """
