def extract_and_sort_pending_wire_entries(input_df: DataFrame) -> DataFrame:
    """Filter and sort daily wire transfer records to produce the PE extract.

    Business Rule
    -------------
    Reads every record from the daily wire input (WIRE.DAILY.INPUT.SEQ) and
    applies the following two-part include condition (AND logic):

      1. **Transaction type code** (offset 55, length 2, CH) must equal the
         literal string ``'PE'`` (Payment Entry / Pending Entry wire type).
      2. **Transaction amount** (offset 17, length 9, PD, decoded to integer)
         must be strictly greater than zero — zero-value and negative-amount
         records are excluded.

    Records passing both conditions are sorted by:
      - Primary key   : ``wire_reference_key`` (offset 44, len 8, CH) **ascending**
      - Secondary key : ``transaction_amount``  (offset 17, len 9, PD) **descending**

    The resulting DataFrame represents the content of WIRE.WORK.EXTRT.SEQ
    (RECFM=FB, LRECL=200, 10+5 cylinders) ready for downstream processing.

    .. note::
        **EBCDIC transcoding** — Both character fields (``transaction_type_code``
        and ``wire_reference_key``) must be transcoded from EBCDIC to UTF-8
        during ingestion, *before* this function is called.  The filter literal
        ``'PE'`` is the UTF-8 representation of EBCDIC C'PE' (X'D7C5').

    .. note::
        **Packed Decimal decoding** — ``transaction_amount`` must contain the
        *decoded* signed integer value, not raw packed-decimal bytes.  Use
        ``decode_packed_decimal()`` or the companion UDF
        ``_make_pd_decoder_udf()`` in the ingestion pipeline to populate this
        column.  Negative amounts are implicitly excluded by the GT +0
        condition; confirm with business stakeholders whether negative wire
        amounts represent valid credits that should be routed elsewhere rather
        than silently dropped.

    .. note::
        **Configurable parameters** — The original SYSIN was externalised to
        ``SYS2.CNTL(WIREEXT)``.  The filter values ``FILTER_TYPE_CODE_VALUE``
        and ``FILTER_AMOUNT_THRESHOLD`` are module-level constants in this file
        and should be treated as configurable business parameters.

    Parameters
    ----------
    input_df : DataFrame
        Spark DataFrame representing WIRE.DAILY.INPUT.SEQ.  Expected columns:

        +-------------------------+----------+------------------------------+
        | Column Name             | Type     | Description                  |
        +=========================+==========+==============================+
        | transaction_type_code   | StringType | Offset 55, len 2, CH       |
        |                         |            | (EBCDIC → UTF-8 decoded)   |
        +-------------------------+----------+------------------------------+
        | transaction_amount      | LongType   | Offset 17, len 9, PD       |
        |                         |            | (packed decimal decoded)   |
        +-------------------------+----------+------------------------------+
        | wire_reference_key      | StringType | Offset 44, len 8, CH       |
        |                         |            | (EBCDIC → UTF-8 decoded)   |
        +-------------------------+----------+------------------------------+

        All other columns present in the DataFrame are preserved in the output.

    Returns
    -------
    DataFrame
        Filtered and sorted DataFrame equivalent to WIRE.WORK.EXTRT.SEQ.
        Row ordering is guaranteed within a single Spark action; downstream
        steps that write partitioned output should use ``coalesce(1)`` or
        ``repartition(1)`` and set ``spark.sql.shuffle.partitions``
        appropriately to preserve the sort order in the output file.

    Key Field Mapping (Mainframe → PySpark)
    ----------------------------------------
    +----------------+-----+-----+--------+--------------------------+
    | Mainframe Off. | Len | Fmt | Role   | Column Name              |
    +================+=====+=====+========+==========================+
    | 55 (1-based)   |  2  | CH  | Filter | transaction_type_code    |
    |                |     |     |        | Python slice [54:56]     |
    +----------------+-----+-----+--------+--------------------------+
    | 17 (1-based)   |  9  | PD  | Filter | transaction_amount       |
    |                |     |     | + Sort | Python slice [16:25]     |
    +----------------+-----+-----+--------+--------------------------+
    | 44 (1-based)   |  8  | CH  | Sort   | wire_reference_key       |
    |                |     |     |        | Python slice [43:51]     |
    +----------------+-----+-----+--------+--------------------------+

    Original SYSIN Control Cards (SYS2.CNTL(WIREEXT))
    --------------------------------------------------
    ::

        INCLUDE COND=(55,2,CH,EQ,C'PE',AND,17,9,PD,GT,+0)
        SORT FIELDS=(44,8,CH,A,17,9,PD,D)

    """
    # ------------------------------------------------------------------
    # STEP 1 — FILTER
    # Mainframe: INCLUDE COND=(55,2,CH,EQ,C'PE',AND,17,9,PD,GT,+0)
    #
    # Condition breakdown (AND logic — both must be true):
    #   • (55,2,CH,EQ,C'PE') → transaction_type_code == 'PE'
    #                          [EBCDIC → UTF-8 transcoding handled at ingest]
    #   • (17,9,PD,GT,+0)   → transaction_amount  >  0
    #                          [PD decoding handled at ingest; negatives dropped]
    # ------------------------------------------------------------------
    type_code_condition = (
        F.col(TRANSACTION_TYPE_CODE) == F.lit(FILTER_TYPE_CODE_VALUE)
    )
    amount_condition = (
        F.col(TRANSACTION_AMOUNT) > F.lit(FILTER_AMOUNT_THRESHOLD)
    )

    # NOTE: transaction_amount must be the decoded integer value (not raw PD
    #       bytes).  If this column is still binary, apply the PD decoder UDF
    #       before invoking this function.
    df_filtered: DataFrame = input_df.filter(
        type_code_condition & amount_condition
    )

    # ------------------------------------------------------------------
    # STEP 2 — SORT
    # Mainframe: SORT FIELDS=(44,8,CH,A,17,9,PD,D)
    #
    # Sort key 1: (44,8,CH,A) → wire_reference_key  ASCENDING
    #             Groups related wire records by reference/account key.
    # Sort key 2: (17,9,PD,D) → transaction_amount  DESCENDING
    #             Within each group, largest amounts ranked first.
    #
    # NOTE: Spark's orderBy() guarantees a total ordering of the *logical*
    #       result set.  To preserve this order in a written file, write with
    #       coalesce(1) to a single partition.
    # ------------------------------------------------------------------
    df_sorted: DataFrame = df_filtered.orderBy(
        F.col(WIRE_REFERENCE_KEY).asc(),    # Primary key   — (44,8,CH,A)
        F.col(TRANSACTION_AMOUNT).desc(),   # Secondary key — (17,9,PD,D)
    )

    return df_sorted


