def decode_packed_decimal(pd_bytes: Optional[bytes]) -> Optional[int]:
    """Decode a mainframe packed-decimal (PD) byte string to a Python int.

    Packed-decimal encoding:
      • Each byte stores two BCD digits (high nibble = left digit,
        low nibble = right digit).
      • The *last* byte stores one digit in the high nibble and the sign in
        the low nibble:
          C (0xC) → positive
          D (0xD) → negative
          F (0xF) → unsigned (treated as positive)
      • A 9-byte PD field can represent up to 17 significant digits.

    Args:
        pd_bytes: Raw packed-decimal bytes extracted from the fixed-width
                  mainframe record (length 9 for this step's amount field).

    Returns:
        The decoded integer value (positive, negative, or zero), or ``None``
        if ``pd_bytes`` is ``None`` or empty.

    Raises:
        ValueError: If any nibble contains an invalid BCD digit (0xA–0xE in a
                    digit position, or an unrecognised sign nibble).
    """
    if pd_bytes is None or len(pd_bytes) == 0:
        return None

    digits: list[int] = []

    for byte in pd_bytes[:-1]:
        high = (byte >> 4) & 0x0F
        low = byte & 0x0F
        if high > 9 or low > 9:
            raise ValueError(
                f"Invalid BCD digit in packed-decimal byte 0x{byte:02X}"
            )
        digits.extend([high, low])

    # Last byte: one digit + sign nibble
    last_byte = pd_bytes[-1]
    last_digit = (last_byte >> 4) & 0x0F
    sign_nibble = last_byte & 0x0F

    if last_digit > 9:
        raise ValueError(
            f"Invalid BCD digit in last packed-decimal byte 0x{last_byte:02X}"
        )
    digits.append(last_digit)

    sign_nibble_map = {0xC: 1, 0xD: -1, 0xF: 1}
    if sign_nibble not in sign_nibble_map:
        raise ValueError(
            f"Unrecognised sign nibble 0x{sign_nibble:X} in packed-decimal field"
        )
    sign = sign_nibble_map[sign_nibble]

    magnitude = int("".join(str(d) for d in digits))
    return sign * magnitude


def _make_pd_decoder_udf():
    """Return a PySpark UDF that wraps ``decode_packed_decimal``.

    The UDF accepts a BinaryType column (raw PD bytes) and returns a LongType
    (decoded signed integer).  For amounts that exceed Python's int range as
    represented in LongType, consider switching to DecimalType(38, 0).
    """
    import pyspark.sql.functions as _F
    from pyspark.sql.types import LongType as _LongType

    @_F.udf(returnType=_LongType())
    def _pd_udf(pd_bytes: Optional[bytes]) -> Optional[int]:
        # Inline copy so the closure is self-contained for Spark serialisation.
        if pd_bytes is None or len(pd_bytes) == 0:
            return None
        digits = []
        for byte in pd_bytes[:-1]:
            high = (byte >> 4) & 0x0F
            low = byte & 0x0F
            if high > 9 or low > 9:
                return None  # Gracefully skip malformed records in production
            digits.extend([high, low])
        last_byte = pd_bytes[-1]
        last_digit = (last_byte >> 4) & 0x0F
        sign_nibble = last_byte & 0x0F
        if last_digit > 9:
            return None
        digits.append(last_digit)
        sign_map = {0xC: 1, 0xD: -1, 0xF: 1}
        sign = sign_map.get(sign_nibble)
        if sign is None:
            return None
        return sign * int("".join(str(d) for d in digits))

    return _pd_udf


