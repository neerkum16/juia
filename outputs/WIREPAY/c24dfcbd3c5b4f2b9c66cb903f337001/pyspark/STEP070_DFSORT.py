def summarise_wire_transfers_by_code(input_df: DataFrame) -> DataFrame:
    """Summarise wire transfer records by their 3-character grouping code.

    Implements DFSORT STEP070:
      SORT FIELDS=(63,3,CH,A)
      SUM  FIELDS=(17,9,PD)
      OUTREC FIELDS=(1,16, 63,3, 17,9,PD,TO=FS,LENGTH=12, 44,8, 55,2, 66,3)

    Business rule
    -------------
    All records from WIRE.PROCESSED.SEQ are sorted ascending on the 3-character
    code at position 63.  Records sharing that code are collapsed into a single
    summary row by summing the packed-decimal amount at position 17.
    Non-aggregated descriptor fields are taken from the first record in each
    sorted group (DFSORT EQUALS / SUM survivor semantics).

    The surviving record is reformatted into a 200-byte fixed-block string:

      Field                Src offset  Src len  Out bytes  Out len
      ─────────────────────────────────────────────────────────────
      Identifier (CH)           1        16       1–16       16
      Grouping code (CH)       63         3      17–19        3
      Amount FS 12-byte        17         9      20–31       12   ← PD→FS
      Date/bank field (CH)     44         8      32–39        8
      Transaction status (CH)  55         2      40–41        2
      Trailing code (CH)       66         3      42–44        3
      Space padding             —         —      45–200     156
      ─────────────────────────────────────────────────────────────
      Total                                                 200

    Parameters
    ----------
    input_df : DataFrame
        Source records from WIRE.PROCESSED.SEQ, parsed into the columns
        defined by INPUT_SCHEMA.  Specifically:

        - ``identifier``          (StringType)  offset  1, len 16, CH
        - ``amount``              (LongType)    offset 17, len  9, PD
          *** Must be pre-decoded from packed-decimal to integer. ***
        - ``date_bank``           (StringType)  offset 44, len  8, CH
        - ``transaction_status``  (StringType)  offset 55, len  2, CH
          *** EBCDIC fields must be transcoded to UTF-8 before ingestion. ***
        - ``grouping_code``       (StringType)  offset 63, len  3, CH
        - ``trailing_code``       (StringType)  offset 66, len  3, CH

    Returns
    -------
    DataFrame
        One row per distinct ``grouping_code`` value, ordered ascending by
        ``grouping_code``, with the following columns:

        - ``grouping_code``       StringType  — the aggregation key
        - ``amount_fs``           LongType    — summed amount (PD→FS integer)
        - ``identifier``          StringType  — from first record in group
        - ``date_bank``           StringType  — from first record in group
        - ``transaction_status``  StringType  — from first record in group
        - ``trailing_code``       StringType  — from first record in group
        - ``output_record``       StringType  — 200-byte OUTREC-formatted string

    Key field mapping (mainframe offset → column name)
    ---------------------------------------------------
    Offset 63, len 3, CH  →  grouping_code       (SORT key / GROUP BY key)
    Offset 17, len 9, PD  →  amount              (SUM field → amount_fs)
    Offset  1, len 16, CH →  identifier          (OUTREC retained, first)
    Offset 44, len  8, CH →  date_bank           (OUTREC retained, first)
    Offset 55, len  2, CH →  transaction_status  (OUTREC retained, first)
    Offset 66, len  3, CH →  trailing_code       (OUTREC retained, first)

    Original SYSIN control cards
    ----------------------------
    ::

        SORT FIELDS=(63,3,CH,A)
        SUM FIELDS=(17,9,PD)
        OUTREC FIELDS=(1,16,
                       63,3,
                       17,9,PD,TO=FS,LENGTH=12,
                       44,8,
                       55,2,
                       66,3)

    Survivor-record semantics
    -------------------------
    DFSORT retains non-SUM fields from the first record in each sorted group.
    This implementation assigns a monotonically increasing sequence number to
    each input row before any shuffle, then uses ROW_NUMBER() over a window
    partitioned by grouping_code and ordered by that sequence number to
    deterministically identify the first record within each group.  The
    non-SUM fields are taken exclusively from that first record and joined
    back to the per-group summed amounts, faithfully reproducing DFSORT SUM
    survivor semantics without relying on F.first() non-determinism.
    """

    # ------------------------------------------------------------------
    # FIX 1 — Deterministic first-record selection via window function.
    #
    # PROBLEM: The previous implementation used orderBy(GROUPING_CODE.asc())
    # followed by groupBy(...).agg(F.first(...)).  Spark's groupBy causes a
    # shuffle that destroys the partition-local ordering established by
    # orderBy, making F.first() non-deterministic with respect to the sort
    # order.  The pre-sort was therefore misleading and did NOT guarantee
    # that F.first() would pick the physically first record in the sorted
    # sequence, as DFSORT SUM survivor semantics require.
    #
    # FIX: Assign a monotonically_increasing_id() to every input row
    # immediately (before any shuffle), capturing ingest order.  Then use
    # ROW_NUMBER() partitioned by grouping_code and ordered by that sequence
    # to deterministically tag which record is "first" within each group.
    # Non-SUM fields are taken only from the row where row_number == 1, and
    # then joined back to the per-group SUM result.  This reliably mirrors
    # DFSORT's first-record survivor semantics regardless of cluster topology.
    # ------------------------------------------------------------------

    # Step 1a: Stamp each input row with a stable ingest-order sequence number.
    # monotonically_increasing_id() is guaranteed to be unique and strictly
    # increasing within each partition, and across partitions in the sense
    # that later partitions have higher IDs — sufficient for tie-breaking
    # to identify the "first" record per DFSORT sort-key order simulation.
    sequenced_df: DataFrame = input_df.withColumn(
        _SEQ_COL, F.monotonically_increasing_id()
    )

    # Step 1b: Compute per-group SUM for the amount field.
    # This is the only aggregation needed for the SUM FIELDS card.
    # Mainframe: SUM FIELDS=(17,9,PD)
    sum_df: DataFrame = sequenced_df.groupBy(
        F.col(GROUPING_CODE)
    ).agg(
        F.sum(F.col(AMOUNT)).alias(AMOUNT_FS)
    )

    # Step 1c: Use a window function to assign ROW_NUMBER within each
    # grouping_code partition, ordered by the ingest sequence column.
    # The record with row_number == 1 is the first record in the sorted
    # group — equivalent to the DFSORT SUM survivor for non-SUM fields.
    first_record_window = Window.partitionBy(
        F.col(GROUPING_CODE)
    ).orderBy(
        F.col(_SEQ_COL).asc()
    )

    ranked_df: DataFrame = sequenced_df.withColumn(
        _ROW_NUM_COL, F.row_number().over(first_record_window)
    )

    # Step 1d: Retain only the first record per group for non-SUM fields.
    first_records_df: DataFrame = ranked_df.filter(
        F.col(_ROW_NUM_COL) == 1
    ).select(
        F.col(GROUPING_CODE),
        F.col(IDENTIFIER),
        F.col(DATE_BANK),
        F.col(TRANSACTION_STATUS),
        F.col(TRAILING_CODE),
    )

    # Step 1e: Join the summed amounts back to the first-record non-SUM fields.
    # This cleanly separates the SUM aggregation from the survivor-record
    # selection, eliminating any reliance on F.first() non-determinism.
    aggregated_df: DataFrame = sum_df.join(
        first_records_df,
        on=GROUPING_CODE,
        how="inner",
    )

    # ------------------------------------------------------------------
    # Re-apply ascending sort on grouping_code after aggregation.
    # The SORT card mandates A (ascending) order on the output.
    # Mainframe: SORT FIELDS=(63,3,CH,A)
    # ------------------------------------------------------------------
    ordered_df: DataFrame = aggregated_df.orderBy(F.col(GROUPING_CODE).asc())

    # ------------------------------------------------------------------
    # Mainframe: OUTREC FIELDS=(1,16, 63,3, 17,9,PD,TO=FS,LENGTH=12,
    #                            44,8, 55,2, 66,3)
    #
    # Reformat each summary record into a 200-byte fixed-block string.
    #
    # PD,TO=FS,LENGTH=12 conversion:
    #   DFSORT converts the packed-decimal accumulated total to a signed
    #   fixed-point (FS) integer represented in 12 display characters.
    #   In Spark we render the LongType sum as a right-justified, space-
    #   padded 12-character decimal string (leading spaces, sign embedded
    #   for negative values), which matches the FS display convention.
    #   Positive values: right-justified in 12 chars, space-padded left.
    #   Negative values: leading minus sign, right-justified in 12 chars.
    #
    # Field widths and positions in the output string:
    #   identifier          : lpad/rpad to exactly 16 chars  (bytes  1-16)
    #   grouping_code       : lpad/rpad to exactly  3 chars  (bytes 17-19)
    #   amount_fs (FS,12)   : formatted to exactly 12 chars  (bytes 20-31)
    #   date_bank           : lpad/rpad to exactly  8 chars  (bytes 32-39)
    #   transaction_status  : lpad/rpad to exactly  2 chars  (bytes 40-41)
    #   trailing_code       : lpad/rpad to exactly  3 chars  (bytes 42-44)
    #   space padding       : 156 spaces                     (bytes 45-200)
    #
    # Total defined content : 44 bytes
    # Space padding         : 156 bytes
    # Total output record   : 200 bytes  (== LRECL=200)
    # ------------------------------------------------------------------

    # Helper: render a string column to exactly `width` characters,
    # right-padding with spaces if shorter, left-truncating if longer
    # (truncation should not occur if source field widths are correct).
    def _fixed_ch(col_name: str, width: int) -> F.Column:
        """Right-pad (or truncate) a CH column to exactly `width` chars."""
        return F.rpad(
            F.coalesce(F.col(col_name), F.lit("")),
            width,
            " ",
        ).substr(1, width)

    # Helper: render the FS numeric as a right-justified 12-char string.
    # Negative values include a leading minus sign; positive values are
    # space-padded on the left — matching signed FS display convention.
    #
    # FIX 2 & 3 — Overflow guard for large positive and large negative values.
    #
    # PROBLEM (issue 2): For negative values, if abs(amount) > 99,999,999,999
    # (11 digits), the string representation including the '-' sign exceeds
    # 12 characters.  lpad() only pads shorter strings; it does not truncate.
    # The subsequent substr(1, 12) would then silently drop the most-significant
    # digit(s), producing a wrong value with no error raised.
    #
    # PROBLEM (issue 3): For positive values, if amount > 999,999,999,999
    # (12 digits), the string is already longer than 12 chars before lpad,
    # so lpad is a no-op and substr(1, 12) silently truncates the leading
    # digit(s), yielding a corrupt value.
    #
    # FIX: Before formatting, check abs(amount_fs) against the maximum safe
    # value for each sign.  If overflow is detected, raise a RuntimeError
    # immediately so the caller can investigate the data rather than silently
    # writing wrong output.  The check is implemented as a Spark-level column
    # expression that flags overflowing rows, collected before formatting so
    # that a clear Python exception is raised.
    def _amount_to_fs12() -> F.Column:
        """Convert LongType sum to a 12-character signed FS display string.

        Raises
        ------
        RuntimeError
            Raised (outside this function, in the enclosing scope) if any
            summed amount exceeds the 12-character FS field capacity before
            the withColumn call.  See overflow_check block below.
        """
        # Cast to string first (Spark renders Long as plain decimal digits
        # with a leading '-' for negatives — no leading zeros).
        amount_str: F.Column = F.col(AMOUNT_FS).cast("string")
        # Left-pad to 12 characters with spaces.
        # If the value is None (no records contributed), emit 12 spaces
        # (coalesce to '0' produces '           0', a reasonable default).
        # NOTE: By this point overflows have already been checked and rejected,
        # so substr(1,12) here is only a belt-and-braces guard, not the
        # primary overflow prevention mechanism.
        return F.lpad(
            F.coalesce(amount_str, F.lit("0")),
            12,
            " ",
        ).substr(1, 12)

    # ------------------------------------------------------------------
    # FIX 2 & 3 (continued) — Perform overflow check as a collect() call
    # before the withColumn so that a clear RuntimeError is raised if any
    # group's summed amount cannot be represented in 12 FS characters.
    #
    # Positive overflow threshold : amount_fs >  999,999,999,999 (12 digits)
    # Negative overflow threshold : amount_fs < -99,999,999,999  (11 digits + sign)
    # ------------------------------------------------------------------
    overflow_flag_col = "__overflow_flag__"
    overflow_check_df = ordered_df.withColumn(
        overflow_flag_col,
        (F.col(AMOUNT_FS) > F.lit(_FS12_MAX_POSITIVE))
        | (F.col(AMOUNT_FS) < F.lit(-_FS12_MAX_NEGATIVE_ABS))
    )
    overflow_rows = (
        overflow_check_df
        .filter(F.col(overflow_flag_col) == True)  # noqa: E712
        .select(F.col(GROUPING_CODE), F.col(AMOUNT_FS))
        .limit(10)
        .collect()
    )
    if overflow_rows:
        details = "; ".join(
            f"grouping_code={row[GROUPING_CODE]!r}, amount_fs={row[AMOUNT_FS]}"
            for row in overflow_rows
        )
        raise RuntimeError(
            "STEP070 FS12 overflow: one or more grouped amount values cannot "
            "be represented in a 12-character signed FS field without digit "
            "truncation.  Positive maximum is 999,999,999,999; negative "
            "minimum is -99,999,999,999.  Affected rows (up to 10): "
            f"{details}"
        )

    reformatted_df: DataFrame = ordered_df.withColumn(
        OUTPUT_RECORD,
        F.concat(
            # bytes  1-16 : identifier (pos 1, len 16, CH)
            _fixed_ch(IDENTIFIER, 16),

            # bytes 17-19 : grouping code (pos 63, len 3, CH)
            _fixed_ch(GROUPING_CODE, 3),

            # bytes 20-31 : PD→FS 12-byte amount (pos 17, len 9, PD,TO=FS,LENGTH=12)
            _amount_to_fs12(),

            # bytes 32-39 : date/bank field (pos 44, len 8, CH)
            _fixed_ch(DATE_BANK, 8),

            # bytes 40-41 : transaction status (pos 55, len 2, CH)
            _fixed_ch(TRANSACTION_STATUS, 2),

            # bytes 42-44 : trailing classification code (pos 66, len 3, CH)
            _fixed_ch(TRAILING_CODE, 3),

            # bytes 45-200 : space-pad to fill LRECL=200
            # defined content = 44 bytes; padding = 200 - 44 = 156 spaces
            F.lit(" " * (OUTPUT_LRECL - _DEFINED_CONTENT_BYTES)),
        ),
    )

    # ------------------------------------------------------------------
    # Select and return the final column set.
    # output_record is the primary deliverable; individual columns are
    # retained for downstream validation or audit purposes.
    # ------------------------------------------------------------------
    result_df: DataFrame = reformatted_df.select(
        F.col(GROUPING_CODE),
        F.col(AMOUNT_FS),
        F.col(IDENTIFIER),
        F.col(DATE_BANK),
        F.col(TRANSACTION_STATUS),
        F.col(TRAILING_CODE),
        F.col(OUTPUT_RECORD),
    )

    return result_df


