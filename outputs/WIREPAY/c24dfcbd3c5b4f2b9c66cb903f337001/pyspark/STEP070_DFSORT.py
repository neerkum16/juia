def validate_output_record_width(df: DataFrame, sample_size: int = 100) -> None:
    """Assert that every sampled output_record is exactly OUTPUT_LRECL bytes.

    Parameters
    ----------
    df : DataFrame
        The DataFrame returned by summarise_wire_transfers_by_code().
    sample_size : int
        Number of rows to sample for validation.  Default 100.

    Raises
    ------
    ValueError
        If any sampled row has an output_record length != OUTPUT_LRECL.
    """
    length_col = "__rec_len__"
    violations = (
        df.withColumn(length_col, F.length(F.col(OUTPUT_RECORD)))
        .filter(F.col(length_col) != OUTPUT_LRECL)
        .limit(sample_size)
        .collect()
    )
    if violations:
        bad_lengths = {row[length_col] for row in violations}
        raise ValueError(
            f"Output record width violation: expected {OUTPUT_LRECL} bytes, "
            f"found lengths {bad_lengths}. "
            "Check source field widths and PD decoding."
        )


