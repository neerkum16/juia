def _drop_cluster(
    spark: SparkSession,
    spec: KsdsClusterSpec,
    catalog: str,
    database: str,
) -> int:
    """
    Delete (DROP) an existing Delta/Hive table that represents a VSAM KSDS
    cluster, suppressing "table not found" errors exactly as IDCAMS suppresses
    condition code 8 (dataset not found) when PURGE is specified.

    Mainframe SYSIN equivalent::

        DELETE WIRE.WORK.INPUT.KSDS  CLUSTER PURGE
        IF LASTCC > 8 THEN
          SET MAXCC = 0

    Parameters
    ----------
    spark    : Active SparkSession.
    spec     : Cluster specification (cluster_name, purge flag, …).
    catalog  : Unity Catalog / Hive metastore catalog name.
    database : Target database / schema name.

    Returns
    -------
    int
        Simulated IDCAMS condition code:
          0 = table dropped successfully.
          8 = table did not exist (tolerated, mirrors IDCAMS CC=8).
         16 = unexpected error (re-raised after logging).
    """
    fq_table = f"`{catalog}`.`{database}`.`{spec.table_name}`"
    logger.info(
        "DELETE cluster=%s  purge=%s  → DROP TABLE IF EXISTS %s",
        spec.cluster_name,
        spec.purge,
        fq_table,
    )

    try:
        # Check existence first so we can return a meaningful condition code
        # that mirrors the IDCAMS CC=8 "dataset not found" semantics.
        table_exists = spark.catalog.tableExists(
            f"{catalog}.{database}.{spec.table_name}"
        )

        if not table_exists:
            logger.info(
                "Cluster %s does not exist — condition code 8 suppressed "
                "(mirrors IDCAMS PURGE / SET MAXCC=0 logic).",
                spec.cluster_name,
            )
            return 8  # analogous to IDCAMS CC=8: dataset not found

        # Drop the primary (data) table.  The index component is represented
        # as a separate table following IDCAMS naming conventions.
        spark.sql(f"DROP TABLE IF EXISTS {fq_table}")
        logger.info("Dropped primary table %s", fq_table)

        # Drop the named DATA component table if it exists separately.
        fq_data = f"`{catalog}`.`{database}`.`{spec.data_table_name}`"
        if spark.catalog.tableExists(f"{catalog}.{database}.{spec.data_table_name}"):
            spark.sql(f"DROP TABLE IF EXISTS {fq_data}")
            logger.info("Dropped DATA component table %s", fq_data)

        # Drop the named INDEX component table if it exists separately.
        fq_index = f"`{catalog}`.`{database}`.`{spec.index_table_name}`"
        if spark.catalog.tableExists(f"{catalog}.{database}.{spec.index_table_name}"):
            spark.sql(f"DROP TABLE IF EXISTS {fq_index}")
            logger.info("Dropped INDEX component table %s", fq_index)

        return 0  # analogous to IDCAMS CC=0: successful

    except Exception as exc:  # pylint: disable=broad-except
        logger.error(
            "Unexpected error dropping cluster %s: %s",
            spec.cluster_name,
            exc,
            exc_info=True,
        )
        return 16  # analogous to IDCAMS CC=16: serious error


def _define_cluster(
    spark: SparkSession,
    spec: KsdsClusterSpec,
    catalog: str,
    database: str,
) -> None:
    """
    Create a new, empty Delta Lake table that represents a VSAM KSDS cluster.

    Mirrors the IDCAMS DEFINE CLUSTER command with INDEXED, KEYS, RECORDSIZE,
    CYLINDERS, and SHAREOPTIONS parameters.  Delta Lake optimistic concurrency
    control provides the equivalent of SHAREOPTIONS(2 3).

    Mainframe SYSIN equivalent::

        DEFINE CLUSTER                           -
          (NAME(WIRE.WORK.INPUT.KSDS)            -
           INDEXED                               -
           KEYS(16 0)                            -
           RECORDSIZE(200 200)                   -
           CYLINDERS(20 5)                       -
           SHAREOPTIONS(2 3))                    -
        DATA                                     -
          (NAME(WIRE.WORK.INPUT.KSDS.DATA))      -
        INDEX                                    -
          (NAME(WIRE.WORK.INPUT.KSDS.INDEX))

    Parameters
    ----------
    spark    : Active SparkSession.
    spec     : Cluster specification including name, schema, and allocation.
    catalog  : Unity Catalog / Hive metastore catalog name.
    database : Target database / schema name.

    Notes
    -----
    • SHAREOPTIONS(2 3) — Delta Lake implements optimistic concurrency:
      multiple concurrent readers are always permitted; concurrent writers use
      transaction isolation to prevent corruption, satisfying the spirit of
      same-system option 2.  Cross-system option 3 is satisfied by Delta's
      cloud-storage-based architecture.
    • CYLINDERS(primary secondary) — recorded in table properties for
      documentation and capacity-planning purposes only; cloud storage is
      elastic and does not require pre-allocation.
    • RECORDSIZE(200 200) — fixed-length 200 bytes per record; enforced by
      the schema (COL_KEY length=16 + COL_RECORD length=184).
    • KEYS(16 0) — zero-based offset 0, length 16; the key column is declared
      NOT NULL and the table is partitioned/Z-ordered on it (if Databricks
      Z-ORDER OPTIMIZE is available) to replicate KSDS sequential-key access
      performance.
    • The DATA and INDEX component names are recorded as table properties to
      maintain traceability back to the mainframe object hierarchy.
    """
    fq_table = f"`{catalog}`.`{database}`.`{spec.table_name}`"

    logger.info(
        "DEFINE CLUSTER  name=%s  keys=(%d %d)  recordsize=%d  "
        "cylinders=(%d %d)  shareoptions=(%d %d)",
        spec.cluster_name,
        spec.key_spec.length,
        spec.key_spec.offset,
        spec.record_size,
        spec.allocation.primary_cylinders,
        spec.allocation.secondary_cylinders,
        spec.share_options.same_system,
        spec.share_options.cross_system,
    )

    # Build a DDL string using the schema constants — no hard-coded column names.
    #
    # Note: spark.sql() is used here intentionally because CREATE TABLE DDL is
    # an infrastructure operation, not a data-transformation query.  All column
    # names come from the module-level constants.
    created_at_literal = datetime.now(tz=timezone.utc).isoformat()

    ddl = f"""
        CREATE TABLE IF NOT EXISTS {fq_table} (
            `{COL_KEY}`           STRING    NOT NULL COMMENT 'Primary key: 16-byte wire transfer reference (IDCAMS KEYS(16 0))',
            `{COL_RECORD}`        BINARY             COMMENT 'Record payload: bytes 17-200 (184 bytes), raw fixed-length body',
            `{COL_CLUSTER_NAME}`  STRING    NOT NULL COMMENT 'VSAM cluster name for traceability',
            `{COL_RECORD_LENGTH}` INT       NOT NULL COMMENT 'Fixed record length = 200 (RECORDSIZE(200 200))',
            `{COL_CREATED_AT}`    TIMESTAMP NOT NULL COMMENT 'Row creation timestamp (audit)'
        )
        USING DELTA
        LOCATION '{spec.storage_path}'
        COMMENT 'VSAM KSDS migration: {spec.cluster_name} | KEYS({spec.key_spec.length} {spec.key_spec.offset}) | RECORDSIZE({spec.record_size} {spec.record_size}) | CYLINDERS({spec.allocation.primary_cylinders} {spec.allocation.secondary_cylinders}) | SHAREOPTIONS({spec.share_options.same_system} {spec.share_options.cross_system})'
        TBLPROPERTIES (
            'delta.enableChangeDataFeed'           = 'true',
            'delta.isolationLevel'                 = 'Serializable',
            'vsam.clusterName'                     = '{spec.cluster_name}',
            'vsam.dataComponentName'               = '{spec.data_name}',
            'vsam.indexComponentName'              = '{spec.index_name}',
            'vsam.keyLength'                       = '{spec.key_spec.length}',
            'vsam.keyOffset'                       = '{spec.key_spec.offset}',
            'vsam.recordSize'                      = '{spec.record_size}',
            'vsam.primaryCylinders'                = '{spec.allocation.primary_cylinders}',
            'vsam.secondaryCylinders'              = '{spec.allocation.secondary_cylinders}',
            'vsam.shareOptionsSameSystem'          = '{spec.share_options.same_system}',
            'vsam.shareOptionsCrossSystem'         = '{spec.share_options.cross_system}',
            'vsam.purgeOnDelete'                   = '{str(spec.purge).lower()}',
            'migration.sourcePlatform'             = 'IBM z/OS IDCAMS',
            'migration.createdAt'                  = '{created_at_literal}',
            'migration.tool'                       = 'JUIA'
        )
    """
    spark.sql(ddl)
    logger.info("Created Delta table %s at %s", fq_table, spec.storage_path)

    # Verify the table was created and is accessible.
    if not spark.catalog.tableExists(f"{catalog}.{database}.{spec.table_name}"):
        raise RuntimeError(
            f"Table {fq_table} was not found in the catalog immediately after "
            f"CREATE TABLE.  Check storage permissions and catalog configuration."
        )

    row_count = spark.table(f"{catalog}.{database}.{spec.table_name}").count()
    logger.info(
        "Table %s verified: %d rows (expected 0 for empty initialisation).",
        fq_table,
        row_count,
    )
    if row_count != 0:
        raise RuntimeError(
            f"Freshly created table {fq_table} contains {row_count} rows.  "
            f"The table was not empty after DEFINE — check for lingering data "
            f"at the storage path {spec.storage_path}."
        )


def _condition_code_check(last_cc: int, max_cc: int) -> tuple[int, int]:
    """
    Implement the IDCAMS condition-code suppression logic::

        IF LASTCC > 8 THEN
          SET MAXCC = 0

    In the mainframe context this means: if the previous command's condition
    code was 8 or below (e.g. "dataset not found"), reset the running maximum
    to 0 so that downstream steps see a clean return code.  Only a CC > 8
    (genuine error, CC=12 or CC=16) propagates as a failure.

    Parameters
    ----------
    last_cc : Condition code from the most recent operation (0, 8, 12, 16).
    max_cc  : Running maximum condition code accumulated so far.

    Returns
    -------
    tuple[int, int]
        (adjusted_last_cc, adjusted_max_cc) after applying suppression logic.
    """
    if last_cc > 8:
        logger.warning(
            "Condition code %d exceeds threshold 8 — this is a genuine error "
            "and will NOT be suppressed.  (IDCAMS: LASTCC=%d > 8, no SET MAXCC=0 applied.)",
            last_cc,
            last_cc,
        )
        return last_cc, max(max_cc, last_cc)

    # CC ≤ 8: suppress.  Mirrors: IF LASTCC > 8 THEN SET MAXCC = 0
    if last_cc == 8:
        logger.info(
            "Condition code 8 (dataset not found / table did not exist) — "
            "suppressed per IDCAMS IF LASTCC > 8 / SET MAXCC=0 logic."
        )
    adjusted_max = min(max_cc, last_cc) if last_cc == 0 else max_cc
    return last_cc, adjusted_max


