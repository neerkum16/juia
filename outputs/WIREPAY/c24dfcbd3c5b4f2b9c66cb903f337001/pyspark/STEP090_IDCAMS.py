def audit_vsam_ksds_catalogue(spark: SparkSession) -> DataFrame:
    """
    Equivalent of IDCAMS LISTCAT ALL for WIRE.WORK.INPUT.KSDS and
    WIRE.WORK.EXTRT.KSDS.

    Business Rule
    -------------
    This is the final step of the wire transfer batch job.  It reads no data
    and modifies no data.  Its sole purpose is to verify that the two VSAM
    KSDS working datasets used during the run exist in the system catalogue
    and to capture their current metadata — record counts, allocation, key
    attributes, space usage, I/O statistics, and temporal markers — as a
    post-processing audit trail.

    On the mainframe this is achieved with IDCAMS LISTCAT, which writes a
    formatted report to SYSPRINT.  In the modern Spark / Delta Lake platform
    the equivalent is:
      - a metastore existence check for each migrated table,
      - collection of schema, storage, and statistical metadata,
      - return of a structured audit DataFrame that can be written to a
        persistent audit log table.

    Original SYSIN (authoritative)
    ------------------------------
    ::

        LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS)  ALL
        LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS)  ALL

    Parameters
    ----------
    spark : SparkSession
        Active SparkSession with access to the Hive metastore / Unity Catalog
        that holds the migrated wire transfer tables.

    Returns
    -------
    DataFrame
        One row per catalogued VSAM entry (two rows for the two datasets).
        Schema is defined by ``AUDIT_SCHEMA``.  Key columns:

        +-----------------------+---------------------------------------------+
        | Column                | Mainframe LISTCAT equivalent                |
        +=======================+=============================================+
        | dataset_name          | Entry name (WIRE.WORK.INPUT.KSDS …)        |
        | dataset_exists        | Entry found in ICF catalogue (TRUE/FALSE)  |
        | record_count          | NUMBER-OF-RECORDS                          |
        | key_column            | KEY-OFFSET / KEY-LENGTH (heuristic)        |
        | num_columns           | Schema field count                         |
        | size_bytes            | HI-U-RBA (high-used relative byte address) |
        | num_files             | Number of data extents (approx.)           |
        | table_format          | Dataset organisation (VSAM KSDS → Delta)   |
        | creation_date         | CREDT (creation date)                      |
        | last_modified         | REFD  (last-reference date)                |
        | rows_inserted         | INSERTS statistic                          |
        | rows_updated          | UPDATES statistic                          |
        | rows_deleted          | DELETES statistic                          |
        | audit_status          | SUCCESS / WARNING / ERROR                  |
        +-----------------------+---------------------------------------------+

    Raises
    ------
    RuntimeError
        If the SparkSession is invalid or the metastore is completely
        unreachable (not merely a missing table, which is a WARNING).

    Notes
    -----
    * This function is read-only and idempotent — it can be called multiple
      times without side effects, exactly like the original LISTCAT step.
    * If either table is missing the corresponding row will have
      ``audit_status = "WARNING"`` rather than raising an exception, matching
      the IDCAMS behaviour where a missing entry produces RC=4 (warning) not
      RC=12 (severe error).
    * Packed-decimal (PD) decoding is not relevant here — this step carries
      no input data records.  EBCDIC transcoding is also not applicable.
    """

    check_ts: datetime = datetime.now(tz=timezone.utc)
    audit_rows: List[Dict[str, object]] = []

    # -----------------------------------------------------------------------
    # Mainframe: LISTCAT ENTRIES(WIRE.WORK.INPUT.KSDS)  ALL
    # Mainframe: LISTCAT ENTRIES(WIRE.WORK.EXTRT.KSDS)  ALL
    #
    # Each iteration below corresponds to one LISTCAT control card.
    # The VSAM_TO_HIVE mapping resolves the mainframe dataset name to the
    # equivalent Hive / Delta table so that the same metadata attributes
    # can be collected from the modern platform's catalogue service.
    # -----------------------------------------------------------------------
    for vsam_name, meta in VSAM_TO_HIVE.items():

        logger.info(
            "[%s] LISTCAT ENTRIES(%s) ALL — collecting catalogue metadata …",
            _STEP_NAME,
            vsam_name,
        )

        # Gather all available metadata for this entry.
        props = _collect_table_properties(
            spark=spark,
            database=meta["database"],
            table=meta["table"],
        )

        # Merge fixed catalogue fields with the collected properties.
        row: Dict[str, object] = {
            DATASET_NAME:       vsam_name,
            DATASET_TYPE:       meta["type"],    # KSDS
            ENTRY_TYPE:         meta["entry"],   # CLUSTER
            EXISTENCE_CHECK_TS: check_ts,
            JOB_NAME:           _JOB_NAME,
            STEP_NAME:          _STEP_NAME,
            **props,
        }

        _log_listcat_report(vsam_name, row)
        audit_rows.append(row)

    # -----------------------------------------------------------------------
    # Build the structured audit DataFrame from collected rows.
    # The schema is explicit so that downstream writers receive a fully typed
    # DataFrame even when some optional fields could not be collected.
    # -----------------------------------------------------------------------
    audit_df: DataFrame = spark.createDataFrame(
        data=[_row_to_tuple(r) for r in audit_rows],
        schema=AUDIT_SCHEMA,
    )

    return audit_df


