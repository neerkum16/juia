def _collect_table_properties(
    spark: SparkSession,
    database: str,
    table: str,
) -> Dict[str, object]:
    """
    Collect all available metadata for a single Hive / Delta Lake table.

    Equivalent to the information that LISTCAT ALL returns for a single VSAM
    KSDS cluster entry (allocation, statistics, temporal metadata, schema).

    Parameters
    ----------
    spark    : active SparkSession
    database : Hive database (schema) name
    table    : Hive / Delta table name

    Returns
    -------
    dict with keys matching AUDIT_SCHEMA column names (snake_case).
    Returns a dict with ``dataset_exists = "FALSE"`` when the table is absent.
    """
    qualified = f"{database}.{table}"
    props: Dict[str, object] = {
        DATASET_EXISTS:     "FALSE",
        RECORD_COUNT:       None,
        KEY_COLUMN:         None,
        NUM_COLUMNS:        None,
        SIZE_BYTES:         None,
        NUM_PARTITIONS:     None,
        NUM_FILES:          None,
        TABLE_FORMAT:       None,
        TABLE_LOCATION:     None,
        DATABASE_NAME:      database,
        TABLE_NAME:         table,
        CREATION_DATE:      None,
        LAST_MODIFIED:      None,
        LAST_ACCESSED:      None,
        ROWS_INSERTED:      None,
        ROWS_DELETED:       None,
        ROWS_UPDATED:       None,
        ROWS_READ:          None,
        AUDIT_STATUS:       "SUCCESS",
        AUDIT_MESSAGE:      None,
    }

    # ------------------------------------------------------------------
    # 1. Existence check — mirrors the core purpose of LISTCAT: confirm
    #    that the named entry exists in the catalogue.
    # ------------------------------------------------------------------
    try:
        table_exists: bool = spark.catalog.tableExists(qualified)
    except Exception as exc:  # noqa: BLE001
        props[AUDIT_STATUS]   = "ERROR"
        props[AUDIT_MESSAGE]  = f"Metastore error checking {qualified}: {exc}"
        logger.error("Metastore error for %s: %s", qualified, exc)
        return props

    if not table_exists:
        props[AUDIT_STATUS]  = "WARNING"
        props[AUDIT_MESSAGE] = (
            f"Table {qualified} not found in the metastore — "
            "equivalent to IDCAMS RC=4 (entry not found in ICF catalogue)."
        )
        logger.warning("Table not found: %s", qualified)
        return props

    props[DATASET_EXISTS] = "TRUE"

    # ------------------------------------------------------------------
    # 2. Schema introspection — mirrors LISTCAT KEYLEN / NUMBER-OF-FIELDS
    # ------------------------------------------------------------------
    try:
        schema = spark.table(qualified).schema
        props[NUM_COLUMNS] = len(schema.fields)

        # Heuristic: treat the first field named 'key', '*_id', or '*_key'
        # as the primary key — analogous to VSAM key-offset / key-length.
        key_candidates: List[str] = [
            f.name for f in schema.fields
            if f.name.lower() in {"key", "id"}
            or f.name.lower().endswith("_id")
            or f.name.lower().endswith("_key")
        ]
        props[KEY_COLUMN] = key_candidates[0] if key_candidates else None
    except Exception as exc:  # noqa: BLE001
        logger.warning("Could not read schema for %s: %s", qualified, exc)

    # ------------------------------------------------------------------
    # 3. Table properties / storage metadata — mirrors LISTCAT allocation
    #    and volume information (HI-U-RBA, HI-A-RBA, VOLSER, CISIZE …)
    # ------------------------------------------------------------------
    try:
        tbl_detail_df = spark.sql(f"DESCRIBE DETAIL {qualified}")  # Delta-specific
        if tbl_detail_df.count() > 0:
            row = tbl_detail_df.first()
            props[TABLE_FORMAT]    = _safe_get(row, "format")
            props[TABLE_LOCATION]  = _safe_get(row, "location")
            props[SIZE_BYTES]      = _safe_get(row, "sizeInBytes")
            props[NUM_FILES]       = _safe_get(row, "numFiles")
            props[NUM_PARTITIONS]  = _safe_get(row, "numPartitions")

            # Creation / last-modified timestamps → LISTCAT CREDT / REFD
            created_val = _safe_get(row, "createdAt")
            modified_val = _safe_get(row, "lastModified")
            props[CREATION_DATE] = _coerce_timestamp(created_val)
            props[LAST_MODIFIED] = _coerce_timestamp(modified_val)
    except Exception:  # noqa: BLE001
        # DESCRIBE DETAIL is Delta-specific; fall back to DESCRIBE EXTENDED
        try:
            ext_df = spark.sql(f"DESCRIBE EXTENDED {qualified}")
            kv: Dict[str, str] = {
                r["col_name"].strip(): r["data_type"].strip()
                for r in ext_df.collect()
                if r["col_name"] and r["data_type"]
            }
            props[TABLE_FORMAT]   = kv.get("Provider") or kv.get("Type")
            props[TABLE_LOCATION] = kv.get("Location")
        except Exception as exc2:  # noqa: BLE001
            logger.warning(
                "Could not retrieve table properties for %s: %s", qualified, exc2
            )

    # ------------------------------------------------------------------
    # 4. Row count — mirrors LISTCAT NUMBER-OF-RECORDS
    # ------------------------------------------------------------------
    try:
        props[RECORD_COUNT] = spark.table(qualified).count()
    except Exception as exc:  # noqa: BLE001
        logger.warning("Could not count rows for %s: %s", qualified, exc)

    # ------------------------------------------------------------------
    # 5. Delta Lake transaction history — mirrors LISTCAT I/O statistics
    #    (INSERTS, UPDATES, DELETES, RETRIEVALS).
    #    Only available for Delta format tables; silently skipped otherwise.
    # ------------------------------------------------------------------
    if props.get(TABLE_FORMAT, "").lower() == "delta":
        try:
            history_df = spark.sql(f"DESCRIBE HISTORY {qualified}")
            ops = (
                history_df
                .groupBy(F.col("operation").alias("op"))
                .agg(F.count("*").alias("op_count"))
                .collect()
            )
            op_map: Dict[str, int] = {r["op"].upper(): r["op_count"] for r in ops}
            props[ROWS_INSERTED] = op_map.get("WRITE", 0) + op_map.get("INSERT", 0)
            props[ROWS_UPDATED]  = op_map.get("UPDATE", 0) + op_map.get("MERGE", 0)
            props[ROWS_DELETED]  = op_map.get("DELETE", 0)
            # Reads are not tracked in Delta history; set advisory value.
            props[ROWS_READ]     = None  # Not available from Delta history
        except Exception as exc:  # noqa: BLE001
            logger.warning("Could not read Delta history for %s: %s", qualified, exc)

    return props


def _safe_get(row, field: str) -> Optional[object]:
    """Return row[field] or None if the field is absent (handles schema variance)."""
    try:
        return getattr(row, field, None)
    except Exception:  # noqa: BLE001
        return None


def _coerce_timestamp(value: object) -> Optional[datetime]:
    """
    Coerce a metastore timestamp value to a timezone-aware datetime.
    Accepts datetime, int (epoch-ms), and string (ISO-8601) inputs.
    """
    if value is None:
        return None
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=timezone.utc)
    if isinstance(value, (int, float)):
        # Delta returns epoch-milliseconds
        return datetime.fromtimestamp(value / 1000, tz=timezone.utc)
    if isinstance(value, str):
        try:
            return datetime.fromisoformat(value).replace(tzinfo=timezone.utc)
        except ValueError:
            return None
    return None


