def _log_listcat_report(vsam_name: str, row: Dict[str, object]) -> None:
    """
    Emit a SYSPRINT-style log entry for one LISTCAT result.

    On the mainframe LISTCAT writes a formatted multi-line report to the
    SYSPRINT DD.  Here we replicate that human-readable output to the
    Python logger so that job logs contain an equivalent audit trail.
    """
    status = row.get(AUDIT_STATUS, "UNKNOWN")
    exists = row.get(DATASET_EXISTS, "FALSE")
    sep = "-" * 72

    lines = [
        "",
        sep,
        f" LISTCAT — ENTRIES({vsam_name})  ALL",
        sep,
        f"  DATASET-NAME  . . . . {vsam_name}",
        f"  DATASET-TYPE  . . . . {row.get(DATASET_TYPE)}",
        f"  ENTRY-TYPE    . . . . {row.get(ENTRY_TYPE)}",
        f"  EXISTS-IN-CAT . . . . {exists}",
        f"  DATABASE-NAME . . . . {row.get(DATABASE_NAME)}",
        f"  TABLE-NAME    . . . . {row.get(TABLE_NAME)}",
        f"  TABLE-FORMAT  . . . . {row.get(TABLE_FORMAT)}",
        f"  TABLE-LOCATION. . . . {row.get(TABLE_LOCATION)}",
        "  ---",
        f"  NUMBER-OF-RECORDS . . {row.get(RECORD_COUNT)}",
        f"  NUM-COLUMNS   . . . . {row.get(NUM_COLUMNS)}",
        f"  KEY-COLUMN    . . . . {row.get(KEY_COLUMN)}",
        f"  SIZE-BYTES    . . . . {row.get(SIZE_BYTES)}          (≈ HI-U-RBA)",
        f"  NUM-PARTITIONS. . . . {row.get(NUM_PARTITIONS)}",
        f"  NUM-FILES     . . . . {row.get(NUM_FILES)}           (≈ EXTENTS)",
        "  ---",
        f"  CREATION-DATE . . . . {row.get(CREATION_DATE)}      (≈ CREDT)",
        f"  LAST-MODIFIED . . . . {row.get(LAST_MODIFIED)}      (≈ REFD)",
        f"  LAST-ACCESSED . . . . {row.get(LAST_ACCESSED)}",
        "  ---",
        f"  ROWS-INSERTED . . . . {row.get(ROWS_INSERTED)}      (≈ INSERTS)",
        f"  ROWS-UPDATED  . . . . {row.get(ROWS_UPDATED)}       (≈ UPDATES)",
        f"  ROWS-DELETED  . . . . {row.get(ROWS_DELETED)}       (≈ DELETES)",
        f"  ROWS-READ     . . . . {row.get(ROWS_READ)}          (≈ RETRIEVALS)",
        "  ---",
        f"  AUDIT-STATUS  . . . . {status}",
        f"  AUDIT-MESSAGE . . . . {row.get(AUDIT_MESSAGE)}",
        sep,
        "",
    ]

    report = "\n".join(lines)
    if status == "ERROR":
        logger.error(report)
    elif status == "WARNING":
        logger.warning(report)
    else:
        logger.info(report)


def _row_to_tuple(row: Dict[str, object]) -> tuple:
    """
    Convert an audit-row dict to a tuple ordered by AUDIT_SCHEMA field order.

    Using a positional tuple rather than a Row object ensures that the
    createDataFrame call respects the explicit schema regardless of dict
    ordering (which matters on Python < 3.7 and in some Spark versions).
    """
    return tuple(row.get(field.name) for field in AUDIT_SCHEMA.fields)


