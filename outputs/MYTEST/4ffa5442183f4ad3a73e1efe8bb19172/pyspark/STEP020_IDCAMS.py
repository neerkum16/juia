def load_wire_daily_input_to_ksds(
    input_df: DataFrame,
    *,
    target_path: str = TARGET_PATH,
    ksds_primary_key: List[str] = KSDS_PRIMARY_KEY,
    allow_append: bool = False,
) -> DataFrame:
    """
    Implement IDCAMS REPRO: bulk-load all records from the daily wire transfer
    sequential input file into the target Delta Lake table (KSDS equivalent).

    Business Rule
    -------------
    REPRO INFILE(SEQIN) OUTFILE(VSAMOUT) copies every record verbatim from
    WIRE.DAILY.INPUT.SEQ into WIRE.WORK.INPUT.KSDS without any filtering,
    transformation, or selection.  Records are inserted into the KSDS and
    automatically ordered by the KSDS primary key as defined at cluster
    definition time.  No field-level logic is applied by this step itself.

    Original SYSIN (authoritative):
    --------------------------------
        REPRO INFILE(SEQIN)      -
              OUTFILE(VSAMOUT)

    Parameters
    ----------
    input_df : DataFrame
        Spark DataFrame representing WIRE.DAILY.INPUT.SEQ.  Expected columns:

            Column            Type        Notes
            ────────────────  ──────────  ────────────────────────────────────
            wire_record_key   StringType  KSDS primary key, already transcoded
                                          from EBCDIC to UTF-8 by the upstream
                                          ingestion layer.  Offset/length are
                                          placeholders — verify from the DEFINE
                                          CLUSTER catalogue entry.
            raw_record        StringType  Full fixed-width record, verbatim.
                                          Replace with discrete copybook columns
                                          once the layout is confirmed.

        NOTE: Any packed-decimal (PD) fields in the underlying record must be
        decoded to their integer or decimal Python equivalents BEFORE this
        function is called.  This function treats all columns as already-decoded
        values; it does not perform PD decoding internally.

    target_path : str, optional
        Delta Lake path to write to (default: TARGET_PATH constant).

    ksds_primary_key : list of str, optional
        Column name(s) forming the KSDS primary key (default: KSDS_PRIMARY_KEY).
        Used for duplicate detection prior to the write operation.

    allow_append : bool, optional
        When False (default), the function raises a ValueError if any record
        in *input_df* would produce a duplicate primary key against records
        already present in the target table, mirroring REPRO's behaviour when
        REPLACE/REUSE is not specified.  Set to True only if the caller has
        confirmed the target table is empty or has been pre-truncated.

    Returns
    -------
    DataFrame
        The unmodified input DataFrame, returned as a confirmation artefact so
        callers can inspect the data that was written (e.g. count rows, sample
        records).  The actual persistence side-effect is the Delta Lake write.

    Key Field Mapping (from KSDS DEFINE CLUSTER — PLACEHOLDER)
    -----------------------------------------------------------
        Mainframe Offset  Length  Format  Column Name
        ────────────────  ──────  ──────  ──────────────────
        1                 16      CH      wire_record_key   ← verify from catalogue
        1                 LRECL   CH      raw_record

    Raises
    ------
    ValueError
        If duplicate primary keys are found within *input_df* itself (intra-
        batch duplicates) or, when *allow_append* is False, if duplicate keys
        exist against the existing target table.
    RuntimeError
        If the Delta Lake write fails for any reason.
    """

    logger.info(
        "STEP020 IDCAMS REPRO — begin bulk load: WIRE.DAILY.INPUT.SEQ → "
        "WIRE.WORK.INPUT.KSDS"
    )

    # -------------------------------------------------------------------------
    # SECTION 1: INPUT VALIDATION
    # Verify the DataFrame has the columns the KSDS key definition requires.
    # This guards against upstream schema drift, which on the mainframe would
    # surface as an IDCAMS error during the REPRO execution.
    # -------------------------------------------------------------------------

    missing_key_columns = [
        col for col in ksds_primary_key if col not in input_df.columns
    ]
    if missing_key_columns:
        raise ValueError(
            f"Input DataFrame is missing KSDS primary key column(s): "
            f"{missing_key_columns}.  Update KSDS_PRIMARY_KEY or the ingestion "
            f"schema to match the DEFINE CLUSTER catalogue entry."
        )

    logger.info(
        "Input schema validated — KSDS primary key column(s): %s",
        ksds_primary_key,
    )

    # Cache the input so that duplicate-check aggregations and the final write
    # do not re-read the source twice.  The sequential input file is read once
    # on the mainframe; caching mirrors that single-pass behaviour.
    input_df.cache()

    total_input_records = input_df.count()
    logger.info("Total input records from WIRE.DAILY.INPUT.SEQ: %d", total_input_records)

    if total_input_records == 0:
        logger.warning(
            "STEP020: Input dataset WIRE.DAILY.INPUT.SEQ is empty — nothing to "
            "load.  On the mainframe REPRO would complete with RC=0 but write "
            "zero records.  Exiting without writing to target."
        )
        input_df.unpersist()
        return input_df

    # -------------------------------------------------------------------------
    # SECTION 2: INTRA-BATCH DUPLICATE KEY DETECTION
    # Mainframe REPRO (without REPLACE) raises an error if any two records in
    # the input share the same KSDS primary key.  Detect this condition before
    # attempting the write so the error is surfaced clearly.
    #
    # groupBy shuffles rows with equal key values to the same partition, then
    # count() measures how many records share each key.  Any key with count > 1
    # is a duplicate.
    # -------------------------------------------------------------------------

    # Mainframe: REPRO INFILE(SEQIN) — implicit constraint: key uniqueness
    duplicate_check_df = (
        input_df
        .groupBy(*[F.col(k) for k in ksds_primary_key])
        # count() here is a PySpark aggregation that tallies records per key group
        .agg(F.count(F.lit(1)).alias(RECORD_COUNT))
        .filter(F.col(RECORD_COUNT) > F.lit(1))
    )

    intra_batch_duplicates = duplicate_check_df.count()

    if intra_batch_duplicates > 0:
        logger.error(
            "STEP020 ABEND equivalent: %d duplicate primary key(s) detected "
            "within the input batch — mirroring REPRO duplicate-key error "
            "(no REPLACE/REUSE specified).  Sample duplicates follow.",
            intra_batch_duplicates,
        )
        duplicate_check_df.show(20, truncate=False)
        input_df.unpersist()
        raise ValueError(
            f"STEP020: {intra_batch_duplicates} duplicate KSDS primary key(s) "
            f"found in WIRE.DAILY.INPUT.SEQ.  REPRO without REPLACE/REUSE "
            f"would fail.  Resolve duplicate keys before re-running."
        )

    logger.info(
        "Intra-batch duplicate key check passed — all %d records have unique "
        "primary keys.",
        total_input_records,
    )

    # -------------------------------------------------------------------------
    # SECTION 3: INTER-BATCH DUPLICATE KEY DETECTION (target table check)
    # When allow_append is False (the default, matching REPRO semantics without
    # REPLACE/REUSE), verify that none of the incoming keys already exist in
    # the target Delta Lake table.  If the table does not yet exist this check
    # is skipped — equivalent to loading into an empty KSDS.
    # -------------------------------------------------------------------------

    spark: SparkSession = input_df.sparkSession

    if not allow_append:
        target_table_exists = DeltaTable.isDeltaTable(spark, target_path)

        if target_table_exists:
            logger.info(
                "Target Delta Lake table exists at %s — checking for "
                "inter-batch duplicate keys.",
                target_path,
            )

            existing_keys_df = (
                spark.read.format("delta")
                .load(target_path)
                # Select only the key columns to minimise the shuffle footprint
                .select(*[F.col(k) for k in ksds_primary_key])
            )

            # A join between incoming keys and existing keys identifies
            # conflicts.  An inner join retains only rows where both sides
            # agree on the key value — those rows are the collision set.
            # Mainframe: REPRO would raise "duplicate key" at insert time;
            # we raise pre-emptively here with a descriptive message.
            incoming_keys_df = input_df.select(
                *[F.col(k) for k in ksds_primary_key]
            )

            collision_df = incoming_keys_df.join(
                existing_keys_df,
                on=ksds_primary_key,
                how="inner",
            )

            collision_count = collision_df.count()

            if collision_count > 0:
                logger.error(
                    "STEP020 ABEND equivalent: %d incoming record(s) would "
                    "create duplicate KSDS primary key(s) against the existing "
                    "target table — mirroring REPRO duplicate-key error.  "
                    "Sample collisions:",
                    collision_count,
                )
                collision_df.show(20, truncate=False)
                input_df.unpersist()
                raise ValueError(
                    f"STEP020: {collision_count} record(s) in the incoming batch "
                    f"share primary key(s) with records already present in "
                    f"{target_path}.  REPRO without REPLACE/REUSE would fail.  "
                    f"Pre-truncate the target table or set allow_append=True after "
                    f"confirming the target is empty."
                )

            logger.info(
                "Inter-batch duplicate key check passed — no collisions with "
                "existing target records."
            )
        else:
            logger.info(
                "Target Delta Lake table does not yet exist at %s — first-time "
                "load, no inter-batch duplicate check required.",
                target_path,
            )

    # -------------------------------------------------------------------------
    # SECTION 4: WRITE TO DELTA LAKE (KSDS EQUIVALENT)
    # Mainframe: REPRO OUTFILE(VSAMOUT)
    # All records are written verbatim to the target Delta Lake table.
    # - mode("append") mirrors REPRO's additive insert behaviour.  The Delta
    #   Lake transaction log provides atomicity (all-or-nothing), equivalent
    #   to the VSAM journal that REPRO uses internally.
    # - sortWithinPartitions on the KSDS primary key preserves key-ordered
    #   storage within each Parquet file, supporting fast downstream key-range
    #   scans — the Spark analogue of the KSDS physical ordering guarantee.
    # -------------------------------------------------------------------------

    logger.info(
        "STEP020: Writing %d record(s) to Delta Lake table at %s "
        "(REPRO OUTFILE(VSAMOUT) equivalent).",
        total_input_records,
        target_path,
    )

    try:
        # Mainframe: REPRO INFILE(SEQIN) OUTFILE(VSAMOUT) — verbatim copy,
        # records ordered by KSDS primary key within each storage unit.
        (
            input_df
            # Sort within each partition so that the Parquet row-group layout
            # mirrors the KSDS key-ordered physical organisation, enabling
            # efficient keyed retrieval by downstream consumers.
            .sortWithinPartitions(*[F.col(k) for k in ksds_primary_key])
            .write
            .format("delta")
            # "append" is the correct mode: REPRO adds records to the KSDS;
            # it does NOT truncate-and-reload unless REUSE is specified.
            .mode("append")
            .option("mergeSchema", "false")   # schema drift must be explicit
            .save(target_path)
        )
    except Exception as exc:
        logger.exception(
            "STEP020: Delta Lake write failed — treating as REPRO step failure."
        )
        input_df.unpersist()
        raise RuntimeError(
            f"STEP020: Failed to write records to {target_path}."
        ) from exc

    logger.info(
        "STEP020: Successfully loaded %d record(s) into %s.",
        total_input_records,
        target_path,
    )

    # -------------------------------------------------------------------------
    # SECTION 5: POST-WRITE VERIFICATION
    # Confirm the number of records written matches the number of input records.
    # On the mainframe, IDCAMS prints a statistics summary to SYSPRINT after
    # REPRO completes; this section provides the equivalent audit trail.
    # -------------------------------------------------------------------------

    written_df = spark.read.format("delta").load(target_path)
    total_target_records = written_df.count()

    logger.info(
        "STEP020 post-write verification — "
        "records in target table: %d  |  "
        "records loaded this run: %d",
        total_target_records,
        total_input_records,
    )

    # Release the cached input now that both the write and verification are done.
    input_df.unpersist()

    logger.info("STEP020 IDCAMS REPRO — completed successfully.")

    # Return the input DataFrame as a confirmation artefact; the caller may
    # use it for row sampling, auditing, or chaining into a downstream step.
    return input_df


