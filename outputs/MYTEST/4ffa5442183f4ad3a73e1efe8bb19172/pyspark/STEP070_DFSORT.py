def summarise_wire_transfers_by_key(input_df: DataFrame) -> DataFrame:
    """Summarise wire transfer records by grouping key with aggregated amounts.

    Implements the DFSORT SORT/SUM/OUTREC logic from JCL step STEP070:

        SORT FIELDS=(63,3,CH,A)
        SUM FIELDS=(17,9,PD)
        OUTREC FIELDS=(1,16,
                       63,3,
                       17,9,PD,TO=FS,LENGTH=12,
                       44,8,
                       55,2,
                       66,3)

    Business Rule
    -------------
    All input records are sorted in ascending order on the 3-byte character
    field at positions 63-65 (``group_key``).  Records that share the same
    ``group_key`` are collapsed into one output record by summing the 9-byte
    packed decimal amount field (``amount``).  The aggregated record is then
    reformatted into a 200-byte fixed-width layout.

    Key Field Mapping (mainframe offset → column name)
    --------------------------------------------------
    Offset  1, len 16, CH  → ``identifier``   (output bytes  1-16)
    Offset 17, len  9, PD  → ``amount``        (summed → ``sum_amount``, output bytes 20-31)
    Offset 44, len  8, CH  → ``date_ref``      (output bytes 32-39)
    Offset 55, len  2, CH  → ``status_code``   (output bytes 40-41)
    Offset 63, len  3, CH  → ``group_key``     (output bytes 17-19)
    Offset 66, len  3, CH  → ``supp_code``     (output bytes 42-44)

    Parameters
    ----------
    input_df : DataFrame
        Input DataFrame representing WIRE.PROCESSED.SEQ.  The caller is
        responsible for reading the fixed-width flat file and populating the
        columns listed below **before** calling this function.

        Expected columns and types
        ~~~~~~~~~~~~~~~~~~~~~~~~~~
        ``identifier``  (StringType)  — 16-byte CH field, already transcoded
                                        from EBCDIC to UTF-8.
        ``amount``      (LongType)    — 9-byte PD field **already decoded** to
                                        a signed 64-bit integer.  Raw PD bytes
                                        must be decoded upstream using the
                                        ``decode_packed_decimal`` helper (or
                                        equivalent) before this function runs.
                                        Do NOT pass raw binary bytes here.
        ``date_ref``    (StringType)  — 8-byte CH field, EBCDIC→UTF-8.
        ``status_code`` (StringType)  — 2-byte CH field, EBCDIC→UTF-8.
        ``group_key``   (StringType)  — 3-byte CH field, EBCDIC→UTF-8.
        ``supp_code``   (StringType)  — 3-byte CH field, EBCDIC→UTF-8.

        EBCDIC note: All CH fields must be transcoded from EBCDIC to UTF-8
        before this function is called.  Filtering or comparison on untranscoded
        EBCDIC bytes will produce incorrect results.

    Returns
    -------
    DataFrame
        One row per unique ``group_key`` value, with columns:

        ``identifier``  (StringType)  — 16-byte identifier (from first record
                                        in key group — see caveats below).
        ``group_key``   (StringType)  — 3-byte grouping key.
        ``sum_amount``  (LongType)    — Aggregated monetary total for the group.
        ``date_ref``    (StringType)  — 8-byte date/reference (from first record
                                        in key group — see caveats below).
        ``status_code`` (StringType)  — 2-byte code (from first record in key
                                        group — see caveats below).
        ``supp_code``   (StringType)  — 3-byte supplementary code (from first
                                        record in key group — see caveats below).
        ``output_record`` (StringType) — 200-byte fixed-width output record
                                         matching WIRE.SUMMARY.SEQ LRECL=200.

    Non-key Field Selection Caveat
    ------------------------------
    DFSORT's SUM directive retains non-key, non-sum fields from the **first**
    record in each sort-key group (i.e. the record with the lowest natural
    input sequence within that key).  In a distributed Spark environment there
    is no guaranteed stable input order within a partition, so ``F.first()``
    may not always select the same record as DFSORT would have on the
    mainframe.  If deterministic field selection is required, the caller should
    add a tie-breaking column (e.g. an input sequence number or file offset)
    and replace ``F.first()`` with a ``Window`` min/max expression.
    """

    # ── Section 1: Validate incoming schema ──────────────────────────────────
    # Fail fast with a clear message rather than surfacing a cryptic Spark
    # AnalysisException deep inside the DAG.
    required_columns = {
        IDENTIFIER, AMOUNT, DATE_REF, STATUS_CODE, GROUP_KEY, SUPP_CODE
    }
    missing = required_columns - set(input_df.columns)
    if missing:
        raise ValueError(
            f"summarise_wire_transfers_by_key: input_df is missing required "
            f"column(s): {sorted(missing)}.  Ensure the fixed-width file has "
            f"been parsed and PD fields decoded before calling this function."
        )

    # ── Section 2: Sort ascending on the 3-byte grouping key ─────────────────
    # Mainframe: SORT FIELDS=(63,3,CH,A)
    #
    # In DFSORT, sorting before SUM is what places records with identical keys
    # adjacent to each other so they can be collapsed.  In Spark, groupBy
    # performs a shuffle that achieves the same logical grouping without
    # requiring a physical pre-sort; we therefore defer the ORDER BY to the
    # final step so that Spark can optimise the overall plan.  We note the
    # sort intent here for documentation fidelity.
    #
    # The effective ordering is applied at the end of the pipeline via
    # .orderBy(GROUP_KEY) so the output dataset is sorted ascending on
    # group_key, matching the DFSORT output sequence.

    # ── Section 3: Aggregate — SUM amount, carry through non-key fields ───────
    # Mainframe: SUM FIELDS=(17,9,PD)
    #
    # groupBy shuffles all rows to executors that own the same GROUP_KEY hash
    # bucket, then agg() performs the per-group computations in parallel.
    #
    # F.sum(AMOUNT)   — accumulates the decoded PD integer across all records
    #                   sharing the same GROUP_KEY; this is the core SUM FIELDS
    #                   directive.  The column must already be LongType (decoded
    #                   from PD) — raw binary PD bytes cannot be summed.
    #
    # F.first(...)    — carries a representative value of each non-key,
    #                   non-sum field from one record in the group to the output,
    #                   mirroring DFSORT behaviour.  See the "Non-key Field
    #                   Selection Caveat" in the docstring for determinism notes.
    #                   ignorenulls=True prevents a null from being chosen when
    #                   a non-null alternative exists within the group.
    df_aggregated = (
        input_df
        .groupBy(GROUP_KEY)                                        # group on sort key
        .agg(
            F.sum(AMOUNT)              .alias(SUM_AMOUNT),         # SUM FIELDS=(17,9,PD)
            F.first(IDENTIFIER,        ignorenulls=True).alias(IDENTIFIER),
            F.first(DATE_REF,          ignorenulls=True).alias(DATE_REF),
            F.first(STATUS_CODE,       ignorenulls=True).alias(STATUS_CODE),
            F.first(SUPP_CODE,         ignorenulls=True).alias(SUPP_CODE),
        )
    )

    # ── Section 4: Sort output ascending on the grouping key ──────────────────
    # Mainframe: SORT FIELDS=(63,3,CH,A)
    #
    # Applying orderBy after aggregation is semantically equivalent to the
    # DFSORT sort-then-sum sequence and avoids a redundant pre-sort pass.
    df_sorted = df_aggregated.orderBy(F.col(GROUP_KEY).asc())

    # ── Section 5: Reformat to 200-byte fixed-width output record ────────────
    # Mainframe: OUTREC FIELDS=(1,16, 63,3, 17,9,PD,TO=FS,LENGTH=12,
    #                           44,8, 55,2, 66,3)
    #
    # Output layout (1-based byte positions, total = 44 defined + 156 padding):
    #   bytes  1-16 : identifier   (16 chars, left-justified, space-padded)
    #   bytes 17-19 : group_key    ( 3 chars, left-justified, space-padded)
    #   bytes 20-31 : sum_amount   (12 chars, right-justified, zero-padded,
    #                               with leading '-' for negatives — FS format)
    #   bytes 32-39 : date_ref     ( 8 chars, left-justified, space-padded)
    #   bytes 40-41 : status_code  ( 2 chars, left-justified, space-padded)
    #   bytes 42-44 : supp_code    ( 3 chars, left-justified, space-padded)
    #   bytes 45-200: blank-padded (156 spaces) to reach LRECL=200
    #
    # OUTREC field widths: 16 + 3 + 12 + 8 + 2 + 3 = 44 defined bytes.
    # Remaining: 200 - 44 = 156 bytes of trailing space padding.
    #
    # FS (Fixed-point Signed) conversion of the PD amount to 12 bytes:
    #   DFSORT FS format right-justifies the decimal integer in a 12-byte field
    #   and zero-fills unused digit positions.  For negative values the
    #   leftmost byte is '-' followed by 11 zero-padded digits (e.g.
    #   '-00000012345' for -12345).  For non-negative values all 12 bytes are
    #   zero-padded digits (e.g. '000000012345' for 12345).  There is NO
    #   space-padding in DFSORT FS output — only zero-fill and a leading '-'
    #   sign for negatives.
    #
    # Null-safety: coalesce() replaces any null in a carry-through CH field
    # with spaces so the output record always has a predictable fixed width.
    # A null sum_amount is replaced with 0 before formatting.

    # FIX (issues 1, 2, 3): Replaced the incorrect lpad(..., 12, ' ') expression
    # with logic that correctly implements DFSORT FS 12-byte signed integer
    # format:
    #
    #   • Negative values → '-' + absolute value zero-padded to 11 digits
    #     e.g. -12345  → '-00000012345'  (was: '      -12345' with old code)
    #
    #   • Non-negative values → value zero-padded to 12 digits
    #     e.g.  12345  → '000000012345'  (was: '      012345' with old code)
    #
    # The old code used lpad with a space fill character (' '), which produced
    # space-left-padded output inconsistent with DFSORT FS zero-fill behaviour.
    # The docstring comment previously stated 'positive values are space-prefixed'
    # which was incorrect — FS format always zero-fills digit positions.
    amount_fs_expr = F.when(
        F.col(SUM_AMOUNT) < 0,
        # Negative: leading '-' sign + absolute value zero-padded to 11 digits
        # e.g. -12345 → '-' + lpad('12345', 11, '0') → '-00000012345'
        F.concat(
            F.lit("-"),
            F.lpad((-F.col(SUM_AMOUNT)).cast(StringType()), 11, "0")
        )
    ).otherwise(
        # Non-negative: zero-padded to full 12 digits (no sign character)
        # e.g. 12345 → lpad('12345', 12, '0') → '000000012345'
        # coalesce ensures a null sum_amount is treated as 0 before formatting
        F.lpad(
            F.coalesce(F.col(SUM_AMOUNT), F.lit(0)).cast(StringType()),
            12,
            "0"
        )
    )

    # Assemble the fixed-width output record by concatenating each field,
    # padding shorter CH values with trailing spaces to their defined widths,
    # and appending the 156-byte blank trailer.
    output_expr = F.concat(
        # bytes  1-16 : identifier (rpad to 16)
        F.rpad(F.coalesce(F.col(IDENTIFIER),  F.lit("")), ID_WIDTH,     " "),
        # bytes 17-19 : group_key  (rpad to 3)
        F.rpad(F.coalesce(F.col(GROUP_KEY),   F.lit("")), KEY_WIDTH,    " "),
        # bytes 20-31 : sum_amount as 12-byte FS signed integer (zero-padded,
        #               leading '-' for negatives — matches DFSORT FS format)
        amount_fs_expr,
        # bytes 32-39 : date_ref   (rpad to 8)
        F.rpad(F.coalesce(F.col(DATE_REF),    F.lit("")), DATE_WIDTH,   " "),
        # bytes 40-41 : status_code (rpad to 2)
        F.rpad(F.coalesce(F.col(STATUS_CODE), F.lit("")), STATUS_WIDTH, " "),
        # bytes 42-44 : supp_code  (rpad to 3)
        F.rpad(F.coalesce(F.col(SUPP_CODE),   F.lit("")), SUPP_WIDTH,  " "),
        # bytes 45-200: 156 trailing spaces — DFSORT blank-fills to LRECL
        F.lit(" " * PADDING_WIDTH),
    )

    df_reformatted = df_sorted.withColumn(OUTPUT_RECORD, output_expr)

    # ── Section 6: Select final output columns ────────────────────────────────
    # Return both the structured columns (useful for downstream Spark consumers)
    # and the output_record column (useful when writing a flat file that must
    # match WIRE.SUMMARY.SEQ LRECL=200 byte-for-byte).
    df_output = df_reformatted.select(
        F.col(IDENTIFIER),    # 16-byte identifier
        F.col(GROUP_KEY),     # 3-byte grouping/sort key
        F.col(SUM_AMOUNT),    # aggregated monetary total (LongType)
        F.col(DATE_REF),      # 8-byte date/reference
        F.col(STATUS_CODE),   # 2-byte status/type code
        F.col(SUPP_CODE),     # 3-byte supplementary code
        F.col(OUTPUT_RECORD), # 200-byte fixed-width record for flat-file output
    )

    return df_output


