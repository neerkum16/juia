def parse_wire_processed_seq(raw_df: DataFrame) -> DataFrame:
    """Parse a fixed-width WIRE.PROCESSED.SEQ record into structured columns.

    This function bridges the gap between the raw binary/string flat file
    (as ingested from HDFS, S3, or a landing zone) and the structured DataFrame
    expected by ``summarise_wire_transfers_by_key``.

    It handles:
      - CH field extraction via substring (offsets are 1-based in DFSORT but
        0-based in PySpark's ``substr``; we adjust accordingly).
      - PD field extraction as a binary slice, followed by decoding via the
        ``_decode_pd_udf`` UDF.
      - EBCDIC→UTF-8 transcoding is assumed to have been applied at ingest time
        (e.g. by the file reader or a prior ETL step); if not, apply a
        transcoding UDF to each CH column before returning.

    Parameters
    ----------
    raw_df : DataFrame
        DataFrame with a single column named ``"value"`` (StringType) where
        each row is one EBCDIC-transcoded fixed-width input record.  The record
        must be at least 68 bytes wide to cover all referenced fields.

    Returns
    -------
    DataFrame
        Structured DataFrame with columns ready for
        ``summarise_wire_transfers_by_key``.
    """

    # PySpark substr uses 1-based start positions and a length, matching
    # DFSORT offset conventions directly — no adjustment needed.
    VALUE_COL = "value"

    # Extract all CH (character) fields via substring.
    # Mainframe offsets are 1-based; PySpark substr(start, length) is also
    # 1-based, so the numbers match the SYSIN control card offsets exactly.
    df_parsed = (
        raw_df
        # offset 1, len 16, CH → identifier
        .withColumn(IDENTIFIER,   F.substr(F.col(VALUE_COL),  1, 16))
        # offset 17, len 9, PD  → decode packed decimal to LongType
        # We extract 9 bytes as a substring; the _decode_pd_udf expects bytes.
        # NOTE: if the file was read as StringType the substr result is a char
        # slice; for true binary PD the file must be read as BinaryType and a
        # binary-aware slice must be used.  Adjust the read path accordingly.
        .withColumn(AMOUNT,
            _decode_pd_udf(
                F.substr(F.col(VALUE_COL), 17, 9).cast(BinaryType())
            )
        )
        # offset 44, len 8, CH → date_ref
        .withColumn(DATE_REF,     F.substr(F.col(VALUE_COL), 44,  8))
        # offset 55, len 2, CH → status_code
        .withColumn(STATUS_CODE,  F.substr(F.col(VALUE_COL), 55,  2))
        # offset 63, len 3, CH → group_key (SORT/SUM key)
        .withColumn(GROUP_KEY,    F.substr(F.col(VALUE_COL), 63,  3))
        # offset 66, len 3, CH → supp_code
        .withColumn(SUPP_CODE,    F.substr(F.col(VALUE_COL), 66,  3))
        .drop(VALUE_COL)
    )

    return df_parsed


