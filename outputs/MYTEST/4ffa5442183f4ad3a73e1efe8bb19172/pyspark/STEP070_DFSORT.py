# PACKED DECIMAL HELPER
# =============================================================================

def decode_packed_decimal(raw_bytes: bytes) -> Optional[int]:
    """Decode an IBM mainframe packed decimal (PD) byte string to a Python int.

    IBM packed decimal stores two decimal digits per byte, with the final
    nibble holding the sign:  0xC or 0xF → positive,  0xD → negative.

    Args:
        raw_bytes: Raw bytes extracted from the mainframe record at the PD
                   field position.  For a 9-byte PD field the value can hold
                   up to 17 significant digits.

    Returns:
        The decoded signed integer, or None if ``raw_bytes`` is None/empty.

    Raises:
        ValueError: If any nibble contains an invalid BCD digit (0-9 only for
                    digit nibbles) or an unrecognised sign nibble.
    """
    if not raw_bytes:
        return None

    digits: list[int] = []
    for i, byte in enumerate(raw_bytes):
        high_nibble = (byte >> 4) & 0x0F
        low_nibble  =  byte       & 0x0F

        if i < len(raw_bytes) - 1:
            # All bytes except the last contribute two digit nibbles.
            if high_nibble > 9 or low_nibble > 9:
                raise ValueError(
                    f"Invalid BCD digit nibbles 0x{byte:02X} at byte index {i}"
                )
            digits.append(high_nibble)
            digits.append(low_nibble)
        else:
            # Last byte: high nibble is the final digit, low nibble is sign.
            if high_nibble > 9:
                raise ValueError(
                    f"Invalid BCD digit nibble 0x{high_nibble:X} in final byte"
                )
            sign_nibble = low_nibble
            if sign_nibble not in (0xA, 0xC, 0xE, 0xF):  # positive signs
                if sign_nibble not in (0xB, 0xD):          # negative signs
                    raise ValueError(
                        f"Unrecognised PD sign nibble 0x{sign_nibble:X}"
                    )
            digits.append(high_nibble)
            negative = sign_nibble in (0xB, 0xD)

    value = int("".join(str(d) for d in digits))
    return -value if negative else value


# Register the PD decoder as a Spark UDF so it can be applied to a DataFrame
# column that holds the raw 9-byte PD binary field.  The return type is
# LongType because the maximum 17-digit PD value (999_999_999_999_999_99)
# exceeds a 32-bit integer but fits comfortably in a 64-bit signed long.
_decode_pd_udf = F.udf(decode_packed_decimal, LongType())


