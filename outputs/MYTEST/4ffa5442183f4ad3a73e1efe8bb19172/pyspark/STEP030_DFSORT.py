# ---------------------------------------------------------------------------
# Packed-decimal decoding helper
#
# This utility is provided so that the ingestion layer (or a unit-test harness)
# can decode the 9-byte PD field before passing a DataFrame to the main
# business-logic function.  It is intentionally kept separate from the core
# filter/sort logic so that each concern is independently testable.
# ---------------------------------------------------------------------------

def unpack_packed_decimal(packed_bytes: bytes) -> int:
    """Decode a signed IBM packed-decimal byte string to a Python int.

    Packed-decimal encoding stores two decimal digits per byte, with the final
    nibble holding the sign:
      • 0xC  → positive  (DFSORT treats C and F as positive)
      • 0xD  → negative
      • 0xF  → unsigned / positive

    Args:
        packed_bytes: Raw bytes from the mainframe record, e.g. b'\\x00\\x00\\x01\\x23\\x4C'

    Returns:
        A signed Python integer representing the decoded value.

    Raises:
        ValueError: If the byte string is empty or the sign nibble is
                    unrecognised (not C, D, or F).
    """
    if not packed_bytes:
        raise ValueError("packed_bytes must be a non-empty bytes object")

    # Build the decimal digit string from the high nibble of every byte and
    # the low nibble of every byte except the last (which holds the sign).
    digits: list[str] = []
    for i, byte_val in enumerate(packed_bytes):
        high_nibble = (byte_val >> 4) & 0x0F
        low_nibble = byte_val & 0x0F
        digits.append(str(high_nibble))
        if i < len(packed_bytes) - 1:
            # Middle and leading bytes: both nibbles are digit nibbles.
            digits.append(str(low_nibble))
        else:
            # Last byte: low nibble is the sign nibble, not a digit.
            sign_nibble = low_nibble

    value = int("".join(digits))

    if sign_nibble in (0xC, 0xF):
        # Positive (0xF is unsigned, treated as positive by DFSORT)
        return value
    elif sign_nibble == 0xD:
        # Negative
        return -value
    else:
        raise ValueError(
            f"Unrecognised packed-decimal sign nibble: 0x{sign_nibble:X}. "
            "Expected 0xC (positive), 0xD (negative), or 0xF (unsigned)."
        )


def _make_unpack_udf():
    """Return a PySpark UDF that decodes a PD byte column to LongType.

    Defined as a factory so the UDF is only created when actually needed,
    and the dependency on unpack_packed_decimal() is kept explicit.
    """
    from pyspark.sql.functions import udf  # local import keeps top-level clean

    @udf(returnType=LongType())
    def _udf(packed_bytes: bytes):  # type: ignore[return]
        if packed_bytes is None:
            return None
        try:
            return unpack_packed_decimal(bytes(packed_bytes))
        except (ValueError, IndexError):
            return None

    return _udf


