# ---------------------------------------------------------------------------
# Raw-record parsing helper
#
# Converts a DataFrame of binary 80-byte rows into a typed DataFrame that
# extract_positive_pe_wire_transactions() can consume.  Call this function in
# the ingestion layer — it is not part of the core business logic.
# ---------------------------------------------------------------------------

def parse_wire_records(raw_df: DataFrame) -> DataFrame:
    """Parse a DataFrame of raw 80-byte EBCDIC wire records into typed columns.

    Extracts the three fields referenced by STEP030, decoding packed-decimal
    and transcoding EBCDIC character fields to UTF-8.

    Mainframe field layout (1-based offsets, per DFSORT convention):
      ┌────────────┬────────┬────┬────────┬──────────────────────────────────────┐
      │ Column     │ Offset │ Len│ Format │ Notes                                │
      ├────────────┼────────┼────┼────────┼──────────────────────────────────────┤
      │ AMOUNT     │  17    │  9 │ PD     │ Decoded via unpack_packed_decimal()  │
      │ ACCOUNT_KEY│  44    │  8 │ CH     │ EBCDIC → UTF-8 (latin-1 used here)  │
      │ TRAN_TYPE  │  55    │  2 │ CH     │ EBCDIC → UTF-8 (latin-1 used here)  │
      └────────────┴────────┴────┴────────┴──────────────────────────────────────┘

    Args:
        raw_df: DataFrame with a single BinaryType column named ``raw_record``
                containing exactly 80 bytes per row.

    Returns:
        A DataFrame with columns: raw_record, transaction_type, amount,
        account_key — matching WIRE_RECORD_SCHEMA.
    """
    unpack_udf = _make_unpack_udf()

    # ------------------------------------------------------------------
    # 1. Extract the 2-byte character transaction type code.
    #    Offset 55 (1-based) → slice [54:56] (0-based).
    #    F.substring operates on string columns; for binary columns we use
    #    F.expr with substr, then decode from latin-1 which is a safe
    #    byte-preserving codec for EBCDIC-transcoded data loaded via
    #    a connector that already applied CP037→UTF-8 conversion.
    #    If the source is raw EBCDIC bytes, replace decode('latin-1') with
    #    the appropriate EBCDIC codec in the ingestion layer.
    # ------------------------------------------------------------------
    parsed_df = raw_df.withColumn(
        TRANSACTION_TYPE,
        F.decode(F.substring(F.col(RAW_RECORD).cast("binary"), 55, 2), "latin-1"),
    )

    # ------------------------------------------------------------------
    # 2. Extract the 8-byte character account/routing key.
    #    Offset 44 (1-based) → slice [43:51] (0-based).
    # ------------------------------------------------------------------
    parsed_df = parsed_df.withColumn(
        ACCOUNT_KEY,
        F.decode(F.substring(F.col(RAW_RECORD).cast("binary"), 44, 8), "latin-1"),
    )

    # ------------------------------------------------------------------
    # 3. Extract the 9-byte packed-decimal amount and decode it to a
    #    signed 64-bit integer.
    #    Offset 17 (1-based) → slice [16:25] (0-based).
    #    The UDF returns None for null input or malformed PD bytes so that
    #    bad records are excluded by the downstream GT-zero filter rather
    #    than causing a job failure.
    # ------------------------------------------------------------------
    parsed_df = parsed_df.withColumn(
        AMOUNT,
        unpack_udf(F.substring(F.col(RAW_RECORD).cast("binary"), 17, 9)),
    )

    return parsed_df


