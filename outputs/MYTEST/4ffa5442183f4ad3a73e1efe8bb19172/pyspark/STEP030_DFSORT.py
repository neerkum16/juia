def extract_positive_pe_wire_transactions(input_df: DataFrame) -> DataFrame:
    """Filter and sort daily wire records to produce the PE positive-amount extract.

    Implements the DFSORT control cards from STEP030 verbatim:

        INCLUDE COND=(55,2,CH,EQ,C'PE',AND,17,9,PD,GT,+0)
        SORT FIELDS=(44,8,CH,A,17,9,PD,D)

    Business Rule
    -------------
    Retain only wire transfer records that simultaneously satisfy **both**
    conditions:

    1. The 2-byte transaction type code at positions 55–56 equals the literal
       string ``'PE'`` (Payment Executed / Periodic Entry).  Records with any
       other type code are discarded.

    2. The signed transaction amount at positions 17–25 (packed decimal,
       decoded to integer before ingestion) is strictly greater than zero.
       Zero-value records (voids, reversals placeholders) and negative-value
       records (credits or debit memos) are excluded, matching the DFSORT
       ``GT +0`` semantics.

    The surviving records are sorted by two keys in priority order:

    * **Primary  (ascending)**  — 8-character account/routing key at
      positions 44–51.  Groups related wire transactions together so that
      all activity for the same beneficiary or account appears contiguously.

    * **Secondary (descending)** — decoded transaction amount at positions
      17–25.  Within each account group the largest amounts are ranked first,
      supporting downstream processing that may prefer high-value-first
      ordering.

    No SUM, REFORMAT, or field transformation is applied — output records
    are identical in content to input records; only the row set and ordering
    change.

    Pre-conditions
    --------------
    The caller **must** ensure that:

    * ``amount`` (column ``AMOUNT``) holds a decoded signed integer
      (LongType), **not** raw packed-decimal bytes.  Use
      ``parse_wire_records()`` or an equivalent ingestion step.
    * ``transaction_type`` (column ``TRANSACTION_TYPE``) holds a UTF-8
      string.  EBCDIC transcoding must be completed before this function
      is called.
    * ``account_key`` (column ``ACCOUNT_KEY``) holds a UTF-8 string of
      up to 8 characters, left-padded or right-padded to match mainframe
      collation if strict byte ordering is required.

    Parameters
    ----------
    input_df : DataFrame
        Typed wire record DataFrame.  Expected columns (at minimum):

        ┌─────────────────┬───────────────────┬────────┬──────┬────────┐
        │ Constant        │ Column name        │ Offset │  Len │ Format │
        ├─────────────────┼───────────────────┼────────┼──────┼────────┤
        │ TRANSACTION_TYPE│ transaction_type   │   55   │   2  │ CH     │
        │ AMOUNT          │ amount             │   17   │   9  │ PD→int │
        │ ACCOUNT_KEY     │ account_key        │   44   │   8  │ CH     │
        └─────────────────┴───────────────────┴────────┴──────┴────────┘

    Returns
    -------
    DataFrame
        Filtered and sorted DataFrame containing only positive-value PE-type
        wire transaction records, ordered by (account_key ASC, amount DESC).
        Row content is unchanged from the input.  Equivalent to writing
        WIRE.WORK.EXTRT.SEQ in the mainframe job.

    Notes
    -----
    * Spark's ``orderBy`` performs a total sort across all partitions
      (triggers a full shuffle).  For very large datasets consider whether
      a range-partition sort (``repartitionByRange`` + per-partition sort)
      meets the downstream contract.
    * The output is NOT repartitioned to a single file automatically.  To
      mimic LRECL=80 FB sequential output write to a single-partition
      text or binary sink (``coalesce(1)``), but be aware of driver-memory
      implications at scale.
    """

    # ------------------------------------------------------------------
    # SECTION 1 — INCLUDE filter
    #
    # Mainframe: INCLUDE COND=(55,2,CH,EQ,C'PE',AND,17,9,PD,GT,+0)
    #
    # Two predicates joined by AND; BOTH must be true for a record to
    # survive.  Spark's filter() evaluates the combined boolean column
    # expression and drops rows where it is False or null.
    # ------------------------------------------------------------------

    # Predicate A — transaction_type == 'PE'
    # CH EQ C'PE': exact equality on the 2-byte character field.
    # EBCDIC note: 'PE' in EBCDIC is 0xD7C5; the value must have been
    # transcoded to UTF-8 ('PE') by the ingestion layer before this test.
    is_pe_type = F.col(TRANSACTION_TYPE) == F.lit("PE")

    # Predicate B — amount > 0
    # PD GT +0: strictly greater than zero on the decoded signed integer.
    # Excludes zero-value records (0xF sign nibble with all-zero digits)
    # and negative records (sign nibble 0xD).
    # The AMOUNT column must hold a decoded LongType integer — not raw bytes.
    is_positive_amount = F.col(AMOUNT) > F.lit(0)

    # Apply both conditions simultaneously with AND logic, exactly
    # mirroring the DFSORT INCLUDE COND comma-separated AND clause.
    # filter() keeps rows where the expression evaluates to True;
    # rows where either predicate is False or either column is null are
    # discarded, which is the correct behaviour (null-safe exclusion).
    filtered_df = input_df.filter(is_pe_type & is_positive_amount)

    # ------------------------------------------------------------------
    # SECTION 2 — SORT
    #
    # Mainframe: SORT FIELDS=(44,8,CH,A,17,9,PD,D)
    #
    # Two-key sort:
    #   Key 1 — account_key (CH, offset 44, len 8) ASCENDING
    #           Groups all activity for the same account/beneficiary
    #           contiguously in the output file.
    #   Key 2 — amount (PD, offset 17, len 9)    DESCENDING
    #           Within each account group, larger amounts rank first
    #           (largest-first ordering for downstream high-value
    #           processing).
    #
    # orderBy() triggers a full distributed sort (global shuffle) across
    # all Spark partitions, producing a total ordering equivalent to
    # DFSORT's sequential output.
    # ------------------------------------------------------------------

    sorted_df = filtered_df.orderBy(
        # Primary key: account_key ascending — groups wire records by
        # beneficiary / routing reference.
        F.col(ACCOUNT_KEY).asc(),
        # Secondary key: amount descending — largest transaction first
        # within each account group.  Uses the decoded integer value so
        # numeric ordering (not lexicographic) is applied, consistent
        # with DFSORT PD sort semantics.
        F.col(AMOUNT).desc(),
    )

    return sorted_df


