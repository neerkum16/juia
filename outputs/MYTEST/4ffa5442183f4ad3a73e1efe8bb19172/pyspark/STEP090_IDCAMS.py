def _collect_table_statistics(
    spark: SparkSession,
    dataset: DatasetEntry,
) -> Dict:
    """
    Collect dataset-level statistics from a Spark / Delta table.

    This function mirrors the STATISTICS and VOLUME attribute groups
    produced by LISTCAT ALL.  For Delta Lake tables it uses DESCRIBE
    DETAIL to obtain size bytes (≈ HI-U-RBA) and file counts; for
    all Spark tables it counts rows (≈ REC-TOTAL).

    Parameters
    ----------
    spark   : SparkSession
    dataset : DatasetEntry — the target table to inspect

    Returns
    -------
    dict
        Flat dictionary of collected statistics; None values are used
        where a statistic has no direct modern equivalent.
    """
    db_name, table_name = _split_table_ref(dataset.target_table)
    stats: Dict = {
        COL_RECORD_TOTAL:       None,
        COL_HI_ALLOC_RBA:       None,
        COL_HI_USED_RBA:        None,
        COL_RECORDS_INSERTED:   None,   # DML change tracking not available at rest
        COL_RECORDS_DELETED:    None,
        COL_RECORDS_UPDATED:    None,
        COL_RECORDS_RETRIEVED:  None,
        COL_CI_SPLITS:          None,   # VSAM internal — no modern equivalent
        COL_CA_SPLITS:          None,
        COL_FREE_CI_PERCENT:    None,
        COL_FREE_CA_PERCENT:    None,
        COL_VOLUME_SERIAL:      None,
        COL_DEVICE_TYPE:        "CLOUD_STORAGE",
        COL_CREATION_TIMESTAMP: None,
        COL_EXPIRATION_DATE:    "NOLIMIT",
        COL_OWNER_ID:           None,
        COL_CATALOGUE_NAME:     db_name,
        COL_KEY_OFFSET:         None,   # Physical key offset is not meaningful in columnar storage
        COL_KEY_LENGTH:         None,
        COL_MAX_RECORD_LENGTH:  None,
        COL_CI_SIZE:            None,
        COL_PRIMARY_SPACE:      None,
        COL_SECONDARY_SPACE:    None,
        COL_SPACE_TYPE:         None,
    }

    # --- Row count: equivalent to LISTCAT STATISTICS REC-TOTAL ---
    try:
        table_df: DataFrame = spark.table(dataset.target_table)
        stats[COL_RECORD_TOTAL] = table_df.count()
        logger.info(
            "  %-40s REC-TOTAL = %d",
            dataset.target_table,
            stats[COL_RECORD_TOTAL],
        )
    except Exception as exc:
        logger.warning("  Could not count rows for %s: %s", dataset.target_table, exc)

    # --- Delta Lake DESCRIBE DETAIL: size bytes ≈ HI-U-RBA, creation time ≈ HISTORY ---
    try:
        detail_df: DataFrame = spark.sql(           # noqa: internal metadata query — not a data query
            f"DESCRIBE DETAIL {dataset.target_table}"
        )
        detail_row = detail_df.collect()[0]

        # sizeInBytes ≈ HI-U-RBA (bytes of data currently written / used)
        size_bytes = detail_row["sizeInBytes"] if "sizeInBytes" in detail_row else None
        stats[COL_HI_USED_RBA]       = size_bytes
        stats[COL_HI_ALLOC_RBA]      = size_bytes   # Allocated == used in object storage

        # createdAt ≈ LISTCAT HISTORY CREATION DATE
        created_at = detail_row["createdAt"] if "createdAt" in detail_row else None
        stats[COL_CREATION_TIMESTAMP] = created_at

        # location doubles as a loose equivalent of VOLUME information
        location = detail_row["location"] if "location" in detail_row else None
        if location:
            stats[COL_VOLUME_SERIAL] = location

        logger.info(
            "  %-40s HI-U-RBA (bytes) = %s  CREATED = %s",
            dataset.target_table,
            stats[COL_HI_USED_RBA],
            stats[COL_CREATION_TIMESTAMP],
        )
    except Exception as exc:
        # Table may not be Delta; skip detail collection gracefully.
        logger.debug(
            "  DESCRIBE DETAIL not available for %s (%s) — non-Delta table?",
            dataset.target_table,
            exc,
        )

    # --- Schema inspection: key length ≈ LISTCAT DATA KEYLEN ---
    try:
        table_schema = spark.table(dataset.target_table).schema
        if dataset.expected_key_column:
            matching = [
                f for f in table_schema.fields
                if f.name == dataset.expected_key_column
            ]
            if matching:
                # StringType keys have no fixed byte length; report field position.
                key_position = next(
                    (i for i, f in enumerate(table_schema.fields)
                     if f.name == dataset.expected_key_column),
                    None,
                )
                stats[COL_KEY_OFFSET] = key_position
                # Approximate max record length as number of columns (schema width proxy)
                stats[COL_MAX_RECORD_LENGTH] = len(table_schema.fields)
    except Exception as exc:
        logger.debug("  Schema inspection failed for %s: %s", dataset.target_table, exc)

    return stats


def _split_table_ref(table_ref: str):
    """
    Split a fully qualified table reference (database.table) into its parts.

    Returns ('default', table_ref) when no database prefix is present.
    """
    parts = table_ref.split(".", maxsplit=1)
    return (parts[0], parts[1]) if len(parts) == 2 else ("default", parts[0])


def _table_exists(spark: SparkSession, table_ref: str) -> bool:
    """
    Return True when the Spark catalogue contains the specified table.

    This is the direct equivalent of LISTCAT returning condition code 0
    (dataset found in the ICF catalogue).  A False result is equivalent
    to LISTCAT condition code 4 or 8 (dataset not found).

    Strategy: attempt spark.table() and catch AnalysisException, which
    Spark raises for unknown databases or tables — more reliable than
    spark.catalog.tableExists() across all Spark versions.
    """
    try:
        spark.table(table_ref)
        return True
    except Exception:
        return False


