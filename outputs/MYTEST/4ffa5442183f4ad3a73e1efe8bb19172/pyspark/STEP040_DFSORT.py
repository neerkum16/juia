    from pyspark.sql.functions import udf
    from pyspark.sql.types import LongType as _LongType

    @udf(returnType=_LongType())
    def _decode_pd(raw: bytes) -> int:
        if raw is None:
            return None
        return decode_packed_decimal(raw)

    return _decode_pd


