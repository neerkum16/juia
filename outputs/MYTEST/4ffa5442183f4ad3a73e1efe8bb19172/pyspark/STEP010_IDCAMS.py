def initialise_wire_transfer_work_files(
    spark: SparkSession,
    database: str = "wire_transfer_db",
) -> Dict[str, str]:
    """
    Idempotently initialise (delete-then-recreate) the two VSAM KSDS work
    tables used by the wire transfer processing workflow.

    Business Rule
    -------------
    This function is the direct migration equivalent of the IDCAMS STEP010
    control cards.  It replicates the following behaviour:

    1. DELETE WIRE.WORK.INPUT.KSDS  CLUSTER PURGE
       Unconditionally drop any existing Delta table for the INPUT cluster.
       Tolerates absence (CC=8 equivalent) — not an error.

    2. DELETE WIRE.WORK.EXTRT.KSDS  CLUSTER PURGE
       Same tolerant-delete for the EXTRT cluster.

    3. IF LASTCC > 8 THEN SET MAXCC = 0
       The mainframe step unconditionally resets MAXCC to 0 after both
       DELETEs, suppressing even genuine unexpected errors (codes > 8) so
       that the DEFINE statements always proceed.  This implementation
       replicates that behaviour faithfully: _drop_table_if_exists() wraps
       each drop in a broad try/except that logs but suppresses all
       exceptions.  This is an intentional fidelity choice — if the target
       environment requires stricter error propagation, the except block in
       _drop_table_if_exists() should be changed to re-raise.

    4. DEFINE CLUSTER (NAME(WIRE.WORK.INPUT.KSDS) … CYLINDERS(20 5) …)
       Create an empty Delta table with the KSDS schema for the INPUT staging
       dataset.  Larger primary allocation (20 cylinders) reflects that this
       holds all raw wire transfer input records.

    5. DEFINE CLUSTER (NAME(WIRE.WORK.EXTRT.KSDS) … CYLINDERS(10 5) …)
       Create an empty Delta table for the extracted/filtered subset.  Smaller
       primary allocation (10 cylinders) because downstream steps populate
       only qualifying records here.

    IDCAMS SYSIN (verbatim)
    -----------------------
    ::

        DELETE WIRE.WORK.INPUT.KSDS  CLUSTER PURGE
        DELETE WIRE.WORK.EXTRT.KSDS  CLUSTER PURGE
        IF LASTCC > 8 THEN
          SET MAXCC = 0
        DEFINE CLUSTER                           -
          (NAME(WIRE.WORK.INPUT.KSDS)            -
           INDEXED                               -
           KEYS(16 0)                            -
           RECORDSIZE(200 200)                   -
           CYLINDERS(20 5)                       -
           SHAREOPTIONS(2 3))                    -
        DATA                                     -
          (NAME(WIRE.WORK.INPUT.KSDS.DATA))      -
        INDEX                                    -
          (NAME(WIRE.WORK.INPUT.KSDS.INDEX))
        DEFINE CLUSTER                           -
          (NAME(WIRE.WORK.EXTRT.KSDS)            -
           INDEXED                               -
           KEYS(16 0)                            -
           RECORDSIZE(200 200)                   -
           CYLINDERS(10 5)                       -
           SHAREOPTIONS(2 3))                    -
        DATA                                     -
          (NAME(WIRE.WORK.EXTRT.KSDS.DATA))      -
        INDEX                                    -
          (NAME(WIRE.WORK.EXTRT.KSDS.INDEX))

    Key Field Mapping
    -----------------
    +-----------------+----------+------+--------+--------------------------+
    | Mainframe Offset |  Length  | Fmt  | Column | Description              |
    +-----------------+----------+------+--------+--------------------------+
    |        1        |    16    |  CH  | wire_transfer_key  | KSDS primary key  |
    |       17        |   184    | RAW  | record_payload     | Opaque remainder  |
    +-----------------+----------+------+--------+--------------------------+

    Note on EBCDIC / PD fields
    --------------------------
    * KEY_COLUMN (wire_transfer_key) is a CH (character) field.  When records
      are loaded from mainframe extracts the key bytes must be transcoded from
      EBCDIC to UTF-8 before insertion.
    * RECORD_PAYLOAD_COLUMN is stored as BINARY (BinaryType) to preserve raw
      EBCDIC bytes.  Individual sub-fields within the payload — including any
      packed decimal (PD) amounts — must be decoded by the downstream step
      that reads this table.  No PD decoding occurs in this initialisation
      step because no data is written here.

    SHAREOPTIONS Concurrency Note
    -----------------------------
    SHAREOPTIONS(2 3) means:
      * Within a system : multiple readers + one writer at a time (option 2).
      * Across systems  : full read/write sharing (option 3).
    Delta Lake's ACID transaction log provides serialisable write isolation
    and concurrent read support natively, satisfying both requirements without
    application-level locking.

    Parameters
    ----------
    spark    : Active SparkSession with Delta Lake extensions configured.
    database : Metastore database / schema that will own the two tables.
               Defaults to "wire_transfer_db".  The database must already
               exist before this function is called.

    Returns
    -------
    dict[str, str]
        A summary dict with table names as keys and their fully qualified
        names as values, e.g.:
        {
          "WIRE.WORK.INPUT.KSDS" : "wire_transfer_db.wire_work_input_ksds",
          "WIRE.WORK.EXTRT.KSDS" : "wire_transfer_db.wire_work_extrt_ksds",
        }
        Callers can use this to verify or log what was created.

    Raises
    ------
    RuntimeError
        If the target database does not exist in the metastore.
    Exception
        Unexpected exceptions from the DEFINE (CREATE TABLE) phase propagate
        unchanged.  Exceptions from the DELETE phase are suppressed to
        replicate the mainframe 'IF LASTCC > 8 THEN SET MAXCC = 0' behaviour.
    """

    # ------------------------------------------------------------------
    # Section 0 — Pre-flight: verify the target database exists.
    # A missing database is not equivalent to a missing VSAM cluster; it
    # indicates a misconfigured environment and should fail loudly.
    # ------------------------------------------------------------------
    logger.info(
        "STEP010 — Wire transfer work-file initialisation starting.  "
        "Target database: %s",
        database,
    )

    # FIX (Issue 6): The original code used 'row.namespace' to extract the
    # database name from SHOW DATABASES, which works in Spark 3.x with Unity
    # Catalog but causes AttributeError in Hive metastore environments where
    # the column is named 'databaseName'.
    #
    # Fix: replace the SHOW DATABASES row-attribute approach with
    # spark.catalog.databaseExists(), which is environment-agnostic and works
    # identically in both Hive metastore and Unity Catalog deployments.
    if not spark.catalog.databaseExists(database):
        # Collect available database names for the error message using a
        # column-name-safe approach — getOrElse handles both 'namespace' and
        # 'databaseName' column names across Spark / catalog configurations.
        try:
            db_rows = spark.sql("SHOW DATABASES").collect()
            # Attempt Unity Catalog column name first, fall back to Hive name.
            try:
                existing_databases = [row.namespace for row in db_rows]
            except AttributeError:
                existing_databases = [row.databaseName for row in db_rows]
        except Exception:  # noqa: BLE001
            existing_databases = ["<unable to retrieve database list>"]

        raise RuntimeError(
            f"Target database '{database}' does not exist in the metastore.  "
            f"Create it before running STEP010.  "
            f"Available databases: {existing_databases}"
        )

    # Ensure subsequent spark.sql() calls resolve unqualified table names
    # against the correct database.
    spark.catalog.setCurrentDatabase(database)
    logger.info("Active database set to: %s", database)

    # ------------------------------------------------------------------
    # Section 1 — DELETE phase
    # Mainframe: DELETE WIRE.WORK.INPUT.KSDS  CLUSTER PURGE
    #            DELETE WIRE.WORK.EXTRT.KSDS  CLUSTER PURGE
    #
    # Drop both tables in the same order as the IDCAMS SYSIN cards.
    # _drop_table_if_exists() replicates both the CC=0 / CC=8 tolerance
    # AND the 'IF LASTCC > 8 THEN SET MAXCC = 0' unconditional suppression
    # by catching and logging (not re-raising) all exceptions.
    # ------------------------------------------------------------------
    logger.info("--- DELETE phase (replicates IDCAMS DELETE … CLUSTER PURGE) ---")

    # Mainframe: DELETE WIRE.WORK.INPUT.KSDS  CLUSTER PURGE
    _drop_table_if_exists(spark, INPUT_CLUSTER, database)

    # Mainframe: DELETE WIRE.WORK.EXTRT.KSDS  CLUSTER PURGE
    _drop_table_if_exists(spark, EXTRT_CLUSTER, database)

    logger.info("DELETE phase complete — both clusters purged (or were absent).")

    # ------------------------------------------------------------------
    # Section 2 — Condition-code suppression
    # Mainframe: IF LASTCC > 8 THEN SET MAXCC = 0
    #
    # The original SYSIN unconditionally resets MAXCC to 0 after BOTH
    # DELETE statements, suppressing even genuine unexpected errors (any
    # CC > 8) so that the DEFINE statements always proceed.
    #
    # This behaviour is faithfully replicated inside _drop_table_if_exists():
    # each drop call wraps its DROP TABLE IF EXISTS in a broad try/except
    # that logs the exception at WARNING level but does NOT re-raise,
    # allowing the DEFINE phase to proceed unconditionally — identical to
    # the mainframe's SET MAXCC = 0 reset.
    #
    # Intentional deviation note: propagating unexpected drop errors would
    # be safer in a cloud environment (fail-fast principle), but would NOT
    # be faithful to the original IDCAMS behaviour.  The current approach
    # prioritises fidelity.  To switch to fail-fast mode, change the
    # except block in _drop_table_if_exists() to re-raise the exception.
    # ------------------------------------------------------------------
    logger.info(
        "Condition-code guard (IF LASTCC > 8 THEN SET MAXCC = 0) — "
        "replicated faithfully: _drop_table_if_exists() suppresses all "
        "drop exceptions (logs at WARNING), allowing DEFINE to proceed "
        "unconditionally, matching mainframe MAXCC=0 reset semantics."
    )

    # ------------------------------------------------------------------
    # Section 3 — DEFINE phase
    # Mainframe: DEFINE CLUSTER (NAME(WIRE.WORK.INPUT.KSDS) …)
    #            DEFINE CLUSTER (NAME(WIRE.WORK.EXTRT.KSDS) …)
    #
    # Create both clusters fresh in the same order as the SYSIN cards.
    # ------------------------------------------------------------------
    logger.info("--- DEFINE phase (replicates IDCAMS DEFINE CLUSTER … INDEXED) ---")

    # Mainframe: DEFINE CLUSTER (NAME(WIRE.WORK.INPUT.KSDS)
    #                            INDEXED KEYS(16 0) RECORDSIZE(200 200)
    #                            CYLINDERS(20 5) SHAREOPTIONS(2 3))
    #              DATA  (NAME(WIRE.WORK.INPUT.KSDS.DATA))
    #              INDEX (NAME(WIRE.WORK.INPUT.KSDS.INDEX))
    _create_empty_delta_table(spark, INPUT_CLUSTER, database)

    # Mainframe: DEFINE CLUSTER (NAME(WIRE.WORK.EXTRT.KSDS)
    #                            INDEXED KEYS(16 0) RECORDSIZE(200 200)
    #                            CYLINDERS(10 5) SHAREOPTIONS(2 3))
    #              DATA  (NAME(WIRE.WORK.EXTRT.KSDS.DATA))
    #              INDEX (NAME(WIRE.WORK.EXTRT.KSDS.INDEX))
    _create_empty_delta_table(spark, EXTRT_CLUSTER, database)

    logger.info("DEFINE phase complete — both Delta tables created and empty.")

    # ------------------------------------------------------------------
    # Section 4 — Verification
    # Confirm both tables are visible in the metastore before returning.
    # This is analogous to a LISTCAT after DEFINE — a quick sanity check
    # that the cluster is truly catalogued before downstream steps run.
    # ------------------------------------------------------------------
    logger.info("--- Verification phase (equivalent to IDCAMS LISTCAT) ---")

    result: Dict[str, str] = {}
    for cluster in ALL_CLUSTERS:
        full_name = f"{database}.{cluster.table_name}"
        # FIX (Issue 5): The original code called
        #   spark.catalog.tableExists(cluster.table_name)
        # which relies on the current database being correctly set via
        # setCurrentDatabase() — fragile if the current database changes
        # between the set call and the verification call.
        #
        # Fix: always pass the fully qualified name including the database
        # prefix so the check is unambiguous and independent of the current
        # database setting.
        table_exists = spark.catalog.tableExists(full_name)
        if not table_exists:
            raise RuntimeError(
                f"Post-create verification failed: table '{full_name}' is "
                f"not visible in the metastore after CREATE TABLE.  "
                f"Check Delta Lake configuration and storage permissions."
            )
        logger.info(
            "Verified: table %s exists and is registered in the metastore  "
            "(mainframe cluster: %s).",
            full_name,
            cluster.cluster_name,
        )
        result[cluster.cluster_name] = full_name

    logger.info(
        "STEP010 — Wire transfer work-file initialisation complete.  "
        "Tables created: %s",
        list(result.values()),
    )
    return result


