def _drop_table_if_exists(
    spark: SparkSession,
    cluster: KsdsClusterDefinition,
    database: str,
) -> None:
    """
    Replicates the IDCAMS DELETE … CLUSTER PURGE behaviour.

    IDCAMS returns CC=0 when a cluster is successfully deleted and CC=8 when
    the cluster does not exist ("not catalogued").  Both outcomes allow
    processing to continue.  The Python equivalent is DROP TABLE IF EXISTS —
    it succeeds silently whether or not the table is present.

    The PURGE keyword on DELETE bypasses any retention date on the VSAM
    cluster.  Delta Lake has no built-in retention lock on table DDL, so no
    special handling is required; a plain DROP achieves the same effect.

    Semantic note — IDCAMS 'IF LASTCC > 8 THEN SET MAXCC = 0':
    The original SYSIN unconditionally suppresses ALL condition codes > 8
    from either DELETE by resetting MAXCC to 0, meaning even genuine
    unexpected delete errors are swallowed and DEFINE proceeds regardless.
    To faithfully replicate this behaviour, this helper wraps the DROP in a
    try/except that logs but suppresses ALL exceptions (not just absence),
    matching the mainframe's unconditional MAXCC suppression.  This is an
    intentional fidelity decision: if stricter error propagation is required
    for the target environment, replace the broad except with a raise.

    Parameters
    ----------
    spark   : Active SparkSession.
    cluster : Cluster definition whose table is to be dropped.
    database: Target database / schema name in the metastore.
    """
    full_table_name = f"{database}.{cluster.table_name}"
    logger.info(
        "IDCAMS DELETE equivalent — dropping table if exists: %s  "
        "(mainframe cluster: %s)",
        full_table_name,
        cluster.cluster_name,
    )

    # FIX (Issue 1 + Issue 2):
    # Previously used DeltaTable.isDeltaTable() which: (a) silently skips
    # non-Delta tables registered in the metastore, leaving stale tables that
    # cause the subsequent CREATE to fail; and (b) did not wrap exceptions to
    # replicate the mainframe's 'IF LASTCC > 8 THEN SET MAXCC = 0' behaviour.
    #
    # Fix: use spark.catalog.tableExists() to check metastore presence
    # independently of table format (resolves Issue 2 — non-Delta tables are
    # now also dropped).  Then wrap the entire drop in a broad try/except so
    # that ALL exceptions are logged-and-suppressed rather than propagated
    # (resolves Issue 1 — faithful replication of IDCAMS unconditional
    # MAXCC=0 suppression after either DELETE).
    #
    # Mainframe: DELETE WIRE.WORK.INPUT.KSDS  CLUSTER PURGE
    #            DELETE WIRE.WORK.EXTRT.KSDS  CLUSTER PURGE
    #            IF LASTCC > 8 THEN SET MAXCC = 0
    #
    # The IF LASTCC > 8 / SET MAXCC = 0 guard means: even if a DELETE fails
    # with an unexpected code > 8, the step continues.  We replicate this by
    # catching and logging all exceptions from the drop rather than re-raising.
    try:
        # Check metastore existence regardless of underlying table format.
        # This correctly handles Delta tables, Parquet tables, Hive tables,
        # and any other format registered in the metastore.
        table_present = spark.catalog.tableExists(full_table_name)

        if table_present:
            # Table exists in metastore — perform a hard drop regardless of
            # format (equivalent to DELETE + PURGE).  DROP TABLE IF EXISTS is
            # used as an extra safety net even though we already confirmed
            # existence above, guarding against a narrow TOCTOU window.
            spark.sql(f"DROP TABLE IF EXISTS {full_table_name}")
            logger.info(
                "Table %s dropped successfully  "
                "(equivalent to IDCAMS DELETE CC=0, cluster was catalogued).",
                full_table_name,
            )
        else:
            # Table absent — no action needed; equivalent to IDCAMS CC=8
            # ("not catalogued").  Absence is a benign, expected condition
            # on the first run of an idempotent initialisation step.
            logger.info(
                "Table %s not found — no drop required  "
                "(equivalent to IDCAMS DELETE CC=8, cluster not catalogued).",
                full_table_name,
            )
    except Exception as exc:  # noqa: BLE001
        # Faithful replication of 'IF LASTCC > 8 THEN SET MAXCC = 0':
        # The mainframe unconditionally resets MAXCC to 0 after both DELETEs,
        # suppressing even genuine unexpected errors so that DEFINE can proceed.
        # We log the exception at WARNING level so it is visible in the job
        # audit trail, but we do NOT re-raise — matching mainframe semantics.
        # If stricter behaviour is required for your environment, replace this
        # block with 'raise' to propagate unexpected errors instead.
        logger.warning(
            "Exception suppressed during DROP of %s — replicating mainframe "
            "'IF LASTCC > 8 THEN SET MAXCC = 0' unconditional suppression.  "
            "Error: %s",
            full_table_name,
            exc,
        )


