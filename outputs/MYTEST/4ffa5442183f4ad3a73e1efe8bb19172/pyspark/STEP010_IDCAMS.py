def _create_empty_delta_table(
    spark: SparkSession,
    cluster: KsdsClusterDefinition,
    database: str,
) -> None:
    """
    Replicates the IDCAMS DEFINE CLUSTER … INDEXED behaviour.

    IDCAMS creates an empty, catalogued KSDS cluster with the specified
    record length, key definition, and space allocation.  The Delta Lake
    equivalent creates an empty managed table with:

      • The schema derived from RECORDSIZE(200 200) and KEYS(16 0).
      • The primary key column (KEY_COLUMN) as a NOT NULL STRING because the
        KSDS key field is a fixed-length character field (CH format).
      • The cluster attributes stored as TBLPROPERTIES for audit / lineage.
      • The table partitioned by nothing — KSDS has no notion of partitioning;
        keyed access is handled by Delta's Z-ordering on KEY_COLUMN.

    SHAREOPTIONS(2 3) semantics (multiple concurrent readers, single writer
    within a system; full sharing across systems) are handled at the
    platform level by Delta Lake's ACID transaction log, which provides
    serialisable write isolation by default.  No application-level locking
    is required in PySpark.

    Parameters
    ----------
    spark   : Active SparkSession.
    cluster : Cluster definition describing the table to create.
    database: Target database / schema name in the metastore.
    """
    full_table_name = f"{database}.{cluster.table_name}"
    logger.info(
        "IDCAMS DEFINE CLUSTER equivalent — creating table: %s  "
        "(mainframe cluster: %s, RECORDSIZE=%d, KEYS(%d %d), "
        "CYLINDERS(%d %d), SHAREOPTIONS(%d %d))",
        full_table_name,
        cluster.cluster_name,
        cluster.record_length,
        cluster.key_length,
        cluster.key_offset,
        cluster.cylinders_primary,
        cluster.cylinders_secondary,
        cluster.share_option_within,
        cluster.share_option_cross,
    )

    # Build the TBLPROPERTIES clause from the cluster metadata so that
    # every original IDCAMS attribute is preserved for audit purposes.
    tbl_props_sql = ", ".join(
        f"'{k}' = '{v}'"
        for k, v in cluster.as_table_properties().items()
    )

    # Build the column DDL from the StructType schema.
    # KEY_COLUMN is NOT NULL because a KSDS record must always have a key.
    col_ddl_parts = []
    for sf in cluster.schema.fields:
        # FIX (Issue 3): Removed the dead 'nullable_clause' variable that
        # previously assigned an empty string in both branches of a conditional
        # and was never used anywhere.  The actual NOT NULL constraint is
        # correctly derived from 'not_null' below and embedded in the DDL line.
        not_null = "NOT NULL" if not sf.nullable else ""
        type_sql = _spark_type_to_sql(sf.dataType)
        col_ddl_parts.append(
            f"    {sf.name} {type_sql} {not_null}".rstrip()
        )

    col_ddl = ",\n".join(col_ddl_parts)

    # Mainframe: DEFINE CLUSTER (NAME(WIRE.WORK.INPUT.KSDS) INDEXED …)
    #              DATA (NAME(WIRE.WORK.INPUT.KSDS.DATA))
    #              INDEX (NAME(WIRE.WORK.INPUT.KSDS.INDEX))
    #
    # We use spark.sql() here because DeltaTable.create() builder does not
    # expose TBLPROPERTIES in a single fluent call in all Delta versions.
    # The SQL is constructed from validated constants — there is no user
    # input involved, so string formatting is safe.
    create_sql = (
        f"CREATE TABLE {full_table_name} (\n"
        f"{col_ddl}\n"
        f")\n"
        f"USING DELTA\n"
        f"LOCATION '{cluster.table_path}'\n"
        f"TBLPROPERTIES ({tbl_props_sql})"
    )

    logger.debug("CREATE TABLE DDL:\n%s", create_sql)
    spark.sql(create_sql)

    # Apply Z-ordering recommendation (cannot be done at CREATE time in Delta).
    # Z-ordering on the key column improves keyed-access query performance,
    # approximating the B-tree index semantics of a VSAM KSDS.  This is
    # advisory — it runs as a no-op on an empty table and takes effect after
    # the first data load.
    logger.info(
        "Optimise hint: after first data load run  "
        "OPTIMIZE %s ZORDER BY (%s)  to approximate KSDS keyed-access "
        "performance.",
        full_table_name,
        KEY_COLUMN,
    )

    logger.info(
        "Table %s created successfully  "
        "(equivalent to IDCAMS DEFINE CLUSTER CC=0).",
        full_table_name,
    )


def _spark_type_to_sql(data_type) -> str:
    """
    Map a PySpark DataType instance to its SQL DDL keyword.

    Only the types actually used in KSDS_SCHEMA are handled here.
    Extend if the schema evolves.
    """
    if isinstance(data_type, StringType):
        return "STRING"
    if isinstance(data_type, BinaryType):
        return "BINARY"
    raise NotImplementedError(
        f"No SQL DDL mapping defined for PySpark type: {type(data_type).__name__}"
    )


